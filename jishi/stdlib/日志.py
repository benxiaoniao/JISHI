# -*- coding: utf-8 -*-
"""基石标准库：日志。带级别的输出与「按级别过滤」。

写脚本时最烦的是「调试信息只能靠 `打印`，上线又要一条条删」。用这个模块：
调试信息走 `日志.调试(...)`，正式输出走 `日志.信息(...)`，上线时把级别
调高（`日志.设级别("警告")`）就全安静了。

```jsh
导入 日志
日志.设级别("调试")
日志.调试("这一步拿到了", 数据)     # 会打印
日志.设级别("警告")
日志.调试("再也不会打印")            # 静默
日志.警告("磁盘快满了")              # 还是会打印
```

**状态按「每次导入」隔离**（见 `__基石新建__`）：级别与前缀不挂模块级全局，
否则同一进程里跑第二个执行器会串（M41 的五路对拍测试暴露过）。
"""

from __future__ import annotations

import sys as _sys

from ..errors import RunValueError
from ..runtime import jishi_repr

__all__ = [
    "调试", "信息", "警告", "错误", "设级别", "取级别", "设前缀",
    "级别们",
]

#: 级别名 → 序号（越大越严重）。`静默` 比 `错误` 还大，用来彻底闭嘴。
_级别表 = {"调试": 10, "信息": 20, "警告": 30, "错误": 40, "静默": 99}

#: 级别顺序（从松到严）。
_级别顺序 = ["调试", "信息", "警告", "错误", "静默"]


def __基石新建__() -> dict:
    """每次 `导入 日志` 造一份独立状态（见模块文档末段）。"""
    状态 = {"级别": "信息", "前缀": ""}

    def 级别们() -> list:
        """列出所有可用的级别名（从松到严）。"""
        return list(_级别顺序)

    def 设级别(级别: str) -> None:
        """设置输出级别：低于它的调用会被静默丢掉。

        可取 `调试` / `信息`（默认）/ `警告` / `错误` / `静默`。
        """
        名 = str(级别)
        if 名 not in _级别表:
            raise RunValueError(
                f"不认识级别「{名}」",
                hint=f"可用的有：{'、'.join(_级别顺序)}")
        状态["级别"] = 名

    def 取级别() -> str:
        """返回当前级别名。"""
        return 状态["级别"]

    def 设前缀(前缀: str) -> None:
        """给每条日志加一个固定前缀（比如模块名）。给空串就取消。"""
        状态["前缀"] = str(前缀)

    def _输出(级别: str, 内容: tuple) -> None:
        if _级别表[级别] < _级别表[状态["级别"]]:
            return
        段 = []
        if 状态["前缀"]:
            段.append(状态["前缀"])
        段.append(f"[{级别}]")
        段.extend(jishi_repr(x, top=True) for x in 内容)
        流 = _sys.stderr if 级别 in ("警告", "错误") else _sys.stdout
        print(" ".join(段), file=流)

    def 调试(*内容) -> None:
        """调试级输出（默认不显示，要先 `设级别("调试")`）。"""
        _输出("调试", 内容)

    def 信息(*内容) -> None:
        """信息级输出（默认显示）。"""
        _输出("信息", 内容)

    def 警告(*内容) -> None:
        """警告级输出（写到标准错误）。"""
        _输出("警告", 内容)

    def 错误(*内容) -> None:
        """错误级输出（写到标准错误）。**不会**中止程序，只是记一笔。"""
        _输出("错误", 内容)

    return {"级别们": 级别们, "设级别": 设级别, "取级别": 取级别,
            "设前缀": 设前缀, "调试": 调试, "信息": 信息,
            "警告": 警告, "错误": 错误}
