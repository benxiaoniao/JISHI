# -*- coding: utf-8 -*-
"""基石标准库：测试。极简的「用例 + 断言 + 汇总」三件套。

内建 `断言` 够用但有两个缺口：① 报错只说「条件不成立」，看不出**期望什么、
实际什么**；② 一个断言失败就中断整个脚本，跑不了下一组。

```jsh
导入 测试

测试.用例("加法", 函数()：
    测试.相等(1 + 1, 2)
    测试.为真(1 < 2))

测试.用例("字符串", 函数()：
    测试.相等("ab".长度(), 2))

测试.汇总()          # 打印「通过 / 失败」；有失败就报错（CLI 退出码 1）
```

每个 `用例` 里的断言失败**不会**中断其它用例——`用例` 会接住断言错误、
记一笔、继续跑。块里其它异常（比如除零）也算这个用例失败，并把错误摘要留下。

**状态按「每次导入」隔离**（见 `__基石新建__`）：用例记录不挂模块级全局，
否则同一进程里跑第二个执行器会累积（M41 的五路对拍测试暴露过）。
"""

from __future__ import annotations

import sys as _sys

from ..errors import RunError, RunAssertionError
from ..runtime import jishi_repr

__all__ = [
    "用例", "相等", "不等", "为真", "为假", "近似", "包含",
    "抛出", "汇总", "重置", "统计",
]


def __基石新建__() -> dict:
    """每次 `导入 测试` 造一份独立状态（见模块文档末段）。"""
    记录: list[dict] = []
    当前: dict = {"条目": None}

    def 重置() -> None:
        """清空已记录的用例（写多批测试时用）。"""
        记录.clear()

    def _是断言(e: BaseException) -> bool:
        return (getattr(e, "exc_name", "") == "断言错误"
                or type(e).__name__ == "RunAssertionError")

    def _摘要(e: BaseException) -> str:
        名 = getattr(e, "title", None) or type(e).__name__
        消息 = getattr(e, "message", None) or str(e)
        return f"{名}（{消息}）" if 消息 else 名

    def 用例(名字, 函数=None):
        """跑一个用例：`测试.用例("名字", 函数()：…)`。

        块里的断言失败会记进这个用例、**不中断**其它用例。
        """
        if 函数 is None:
            raise RunError("「测试.用例」要一个函数，"
                           "写成 测试.用例(\"名字\", 函数()：…)")
        条 = {"名字": str(名字), "失败": [], "异常": None}
        记录.append(条)
        旧 = 当前["条目"]
        当前["条目"] = 条
        try:
            函数()
        except BaseException as e:              # noqa: BLE001 - 用例里什么都接
            # 断言失败已经由 `相等` 等记过了，这里只记「用例本身崩了」
            if not _是断言(e):
                条["异常"] = _摘要(e)
        finally:
            当前["条目"] = 旧
        return 条

    def _失败(说明: str, 详: str) -> None:
        """记一次失败：在用例里就记进用例，否则直接抛（独立用断言时）。"""
        if 当前["条目"] is not None:
            当前["条目"]["失败"].append((说明, 详))
            return
        raise RunAssertionError(f"{说明}：{详}")

    def _文本(v) -> str:
        return jishi_repr(v, top=True)

    def 相等(实际, 期望, 说明: str = "") -> None:
        """断言 实际 == 期望（失败时把两边都打出来）。"""
        if not (实际 == 期望):
            _失败(说明 or "相等", f"期望 {_文本(期望)}，实际 {_文本(实际)}")

    def 不等(实际, 不该等于, 说明: str = "") -> None:
        """断言 实际 != 不该等于。"""
        if 实际 == 不该等于:
            _失败(说明 or "不等",
                  f"不该等于 {_文本(不该等于)}，但实际就是它")

    def 为真(条件, 说明: str = "") -> None:
        """断言条件为真。"""
        if not 条件:
            _失败(说明 or "为真", f"期望为真，实际是 {_文本(条件)}")

    def 为假(条件, 说明: str = "") -> None:
        """断言条件为假。"""
        if 条件:
            _失败(说明 or "为假", f"期望为假，实际是 {_文本(条件)}")

    def 近似(实际, 期望, 误差: float = 1e-9, 说明: str = "") -> None:
        """断言 实际 与 期望 的差不超过 误差（浮点数比较用它）。"""
        try:
            差 = abs(实际 - 期望)
        except TypeError:
            _失败(说明 or "近似",
                  f"「{_文本(实际)}」与「{_文本(期望)}」不能比大小")
            return
        if not (差 <= 误差):
            _失败(说明 or "近似",
                  f"期望 {_文本(期望)}（±{_文本(误差)}），实际 {_文本(实际)}")

    def 包含(容器, 元素, 说明: str = "") -> None:
        """断言容器里有这个元素。"""
        try:
            有 = 元素 in 容器
        except TypeError:
            _失败(说明 or "包含", f"「{_文本(容器)}」不能判包含")
            return
        if not 有:
            _失败(说明 or "包含", f"{_文本(容器)} 里没有 {_文本(元素)}")

    def 抛出(函数, 说明: str = ""):
        """断言这段代码会报错，返回那个异常（可以再看它的类型）。

        例：`测试.抛出(函数()：1 / 0)`。
        """
        try:
            函数()
        except BaseException as e:              # noqa: BLE001 - 就是来看错误的
            return e
        _失败(说明 or "抛出", "期望报错，但它正常跑完了")
        return None

    def 统计() -> dict:
        """返回汇总数据：`{"用例", "通过", "失败", "出错"}`。"""
        失败 = sum(len(条["失败"]) for 条 in 记录)
        出错 = sum(1 for 条 in 记录 if 条["异常"])
        通过 = sum(1 for 条 in 记录
                   if not 条["失败"] and not 条["异常"])
        return {"用例": len(记录), "通过": 通过, "失败": 失败, "出错": 出错}

    def 汇总() -> bool:
        """打印汇总；**有任何失败就报错**（CLI 于是以退出码 1 结束）。

        返回是否全过。
        """
        数 = 统计()
        for 条 in 记录:
            if 条["异常"]:
                print(f"✗ {条['名字']}：用例里出错 —— {条['异常']}",
                      file=_sys.stderr)
            for 说明, 详 in 条["失败"]:
                print(f"✗ {条['名字']} · {说明}：{详}", file=_sys.stderr)
        全过 = 数["失败"] == 0 and 数["出错"] == 0
        标记 = "✅" if 全过 else "❌"
        尾巴 = f"（{数['用例']} 个用例）"
        if 全过:
            print(f"{标记} 全部通过 {尾巴}")
        else:
            print(f"{标记} 通过 {数['通过']} / 失败 {数['失败']}"
                  f" / 出错 {数['出错']} {尾巴}")
        if not 全过:
            # 用「抛断言错误」表达失败——脚本里没法直接设进程退出码，
            # 但抛出去 CLI 会以 1 退出，正好接进 CI。
            raise RunAssertionError(
                f"测试没全过：失败 {数['失败']} 项、出错 {数['出错']} 项")
        return True

    return {"用例": 用例, "相等": 相等, "不等": 不等, "为真": 为真,
            "为假": 为假, "近似": 近似, "包含": 包含, "抛出": 抛出,
            "汇总": 汇总, "重置": 重置, "统计": 统计}
