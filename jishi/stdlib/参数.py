# -*- coding: utf-8 -*-
"""基石标准库：参数。命令行解析（子命令 + 选项 + 位置参数）。

写 `待办清单` 时自己解析 `系统.参数()`、自己打印用法，正是本模块要消掉的
绕道写法。

```jsh
导入 参数
令 解析器 = 参数.新建("待办清单", "一个简单的待办工具")
参数.选项(解析器, "数据", "待办.json", "数据文件路径")
参数.标志(解析器, "详细", "打印更多信息")
令 结果 = 参数.解析(解析器, 系统.参数())
如果 结果["命令"] == "添加"：
    打印(结果["位置"], 结果["数据"], 结果["详细"])
```

**为什么是「句柄式」而不是 `解析器.选项(...)`**：Rust 宿主的 `Val::Builtin`
只能存**无捕获的函数指针**，没法给每个解析器挂一套自己的方法。为了三个执行器
与两个宿主**写法完全一致**（本项目对拍的前提），统一用「先 `新建` 拿到句柄，
再把句柄当第一个参数传回去」。

嫌两步麻烦就用**一次式**：

```jsh
令 结果 = 参数.解析(系统.参数(), {"数据": "待办.json", "详细": 假})
```

`解析()` 的返回值是一个字典，键固定为：

| 键 | 含义 |
|----|------|
| `命令` | 第一个非选项参数（子命令），没有就是 `""` |
| `位置` | 除子命令外剩下的位置参数（列表） |
| 各选项名 | 声明的选项值；`标志` 是布尔；没给就用默认值 |
"""

from __future__ import annotations

from ..errors import RunError

__all__ = ["新建", "选项", "标志", "用法", "解析"]

#: 解析器表（句柄 1 起；0 表示无效）。
_解析器表: list[dict] = []


def 新建(名字: str, 说明: str = "") -> int:
    """新建一个参数解析器，返回它的**句柄**（后面所有调用都带着它）。"""
    _解析器表.append({"名字": str(名字), "说明": str(说明), "选项表": []})
    return len(_解析器表)


def _取句柄(句柄) -> dict:
    if isinstance(句柄, bool) or not isinstance(句柄, int):
        raise RunError("这个值不是参数解析器（要用 参数.新建(...) 造一个）")
    if not 1 <= 句柄 <= len(_解析器表):
        raise RunError("参数解析器已失效（是不是跨了脚本？解析器不能保存复用）")
    return _解析器表[句柄 - 1]


def 选项(句柄, 名: str, 默认=None, 说明: str = "") -> int:
    """给解析器声明一个取值选项：`--名 值`（也接受 `--名=值`）。"""
    p = _取句柄(句柄)
    p["选项表"].append({"名": str(名), "默认": 默认,
                        "说明": str(说明), "是标志": False})
    return 句柄


def 标志(句柄, 名: str, 说明: str = "") -> int:
    """给解析器声明一个开关：写 `--名` 就是真，不写就是假。"""
    p = _取句柄(句柄)
    p["选项表"].append({"名": str(名), "默认": False,
                        "说明": str(说明), "是标志": True})
    return 句柄


def 用法(句柄) -> str:
    """生成用法说明（自动包含已声明的选项）。"""
    p = _取句柄(句柄)
    行 = [f"用法：{p['名字']} [命令] [选项]"]
    if p["说明"]:
        行.append(f"  {p['说明']}")
    if p["选项表"]:
        行.append("选项：")
        for o in p["选项表"]:
            if o["是标志"]:
                行.append(f"  --{o['名']:<10} {o['说明']}")
            else:
                行.append(f"  --{o['名']} <值>     {o['说明']}"
                          f"（默认 {_文本(o['默认'])}）")
    return "\n".join(行)


def _文本(v) -> str:
    from ..runtime import jishi_repr
    return jishi_repr(v, top=True)


def 解析(句柄, 参数们=None) -> dict:
    """解析参数列表，返回上面文档里说的那个字典。

    两种用法：`参数.解析(句柄, 系统.参数())` 或
    `参数.解析(系统.参数(), {"数据": "默认.json"})`（一次式，第一个参数
    是参数列表、第二个是「选项 → 默认值」字典）。

    认不出来（`--某某` 没声明过、取值选项后面没跟值）就**报错**——不静默忽略，
    否则用户敲错一个选项名，程序会当没看见继续跑。
    """
    if 参数们 is None:
        raise RunError("「参数.解析」还要一个参数列表，"
                       "通常写 参数.解析(解析器, 系统.参数())")
    # 一次式：第一个参数是可迭代（列表/文本）而不是句柄
    if not isinstance(句柄, int) or isinstance(句柄, bool):
        return _一次式(句柄, 参数们)
    p = _取句柄(句柄)
    return _解析(p["选项表"], 参数们)


def _一次式(参数们, 声明) -> dict:
    if not isinstance(声明, dict):
        raise RunError("「参数.解析」的第二个参数要是字典"
                       "（选项名 → 默认值）")
    表 = []
    for 名, 默认 in 声明.items():
        if isinstance(默认, bool):
            表.append({"名": str(名), "默认": False,
                       "说明": "", "是标志": True})
        else:
            表.append({"名": str(名), "默认": 默认,
                       "说明": "", "是标志": False})
    return _解析(表, 参数们)


def _解析(选项表: list, 参数们) -> dict:
    if isinstance(参数们, str):
        raise RunError("「参数.解析」要一个参数列表，"
                       "通常写 参数.解析(解析器, 系统.参数())")
    列表 = list(参数们)
    结果 = {o["名"]: o["默认"] for o in 选项表}
    已知 = {o["名"]: o for o in 选项表}
    位置: list = []
    命令 = ""
    i = 0
    while i < len(列表):
        项 = 列表[i]
        文本 = 项 if isinstance(项, str) else _文本(项)
        if 文本 == "--":                      # 之后全是位置参数
            位置.extend(列表[i + 1:])
            break
        if 文本.startswith("--"):
            体 = 文本[2:]
            if "=" in 体:                     # --名=值
                名, _, 值 = 体.partition("=")
                if 名 not in 已知:
                    raise RunError(_未知选项(选项表, 名))
                if 已知[名]["是标志"]:
                    raise RunError(f"「--{名}」是个开关，不该给值")
                结果[名] = 值
                i += 1
                continue
            if 体 not in 已知:
                raise RunError(_未知选项(选项表, 体))
            if 已知[体]["是标志"]:
                结果[体] = True
                i += 1
                continue
            if i + 1 >= len(列表):
                raise RunError(f"「--{体}」后面要跟一个值")
            结果[体] = 列表[i + 1]
            i += 2
            continue
        if not 命令 and not 位置:
            命令 = 文本
        else:
            位置.append(项)
        i += 1
    结果["命令"] = 命令
    结果["位置"] = 位置
    return 结果


def _未知选项(选项表: list, 名: str) -> str:
    已知名 = "、".join(f"--{o['名']}" for o in 选项表) or "（没有）"
    return (f"不认识选项「--{名}」。已声明的有：{已知名}\n"
            f"（敲错了？跑 `--帮助` 看用法）")
