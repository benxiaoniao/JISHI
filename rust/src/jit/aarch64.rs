/// `add sp, sp, #32` —— **把序言压下去的 48 字节补完**。
///
/// 🔴 少了这一条就是 M184 在 macOS/ARM 上的段错误现场：序言压了 48 字节
/// （`stp x19,x20` + `str x21` + `stp x29,x30`），而 `mov sp,x29` 之后
/// `ldp …, [sp], #16` 只弹回 16 ⇒ 返回时 `sp` 停在 `S-32` 而不是 `S`，
/// 调用者一用栈就崩。**字节层面完全看不出来**（每条指令单看都对），
/// 是 CI 的 macos-arm64 跑出来的（退出码 -11）。
const 退栈: u32 = 0x9100_83FF;
/// `ret`
const 返回: u32 = 0xD65F_03C0;

/// 把一个 64 位立即数装进寄存器：`movz` + 至多三条 `movk`。
///
/// 📌 **高 48 位是 0 就只发一条 `movz`**（`i = i + 1` 里的那个 `1`）。
/// 循环体里的常数是**每圈**都要装的，四条 vs 一条差得不小；
/// 而「值很小」是最常见的情况，值得为它多一个分支。
fn 装数(出: &mut Vec<u32>, d: u8, v: i64) {
    let u = v as u64;
    出.push(0xD280_0000 | (((u & 0xFFFF) as u32) << 5) | d as u32);
    if u >> 16 == 0 {
        return;
    }
    for i in 1..4u32 {
        出.push(0xF280_0000 | (i << 21) | ((((u >> (16 * i)) & 0xFFFF) as u32) << 5) | d as u32);
    }
}

