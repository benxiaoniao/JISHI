fn r3(码: u32, d: u8, n: u8, m: u8) -> u32 {
    码 | ((m as u32) << 16) | ((n as u32) << 5) | d as u32
}

/// `add xd, xn, xm`
fn 加(d: u8, n: u8, m: u8) -> u32 {
    r3(0x8B00_0000, d, n, m)
}
/// `sub xd, xn, xm`
fn 减(d: u8, n: u8, m: u8) -> u32 {
    r3(0xCB00_0000, d, n, m)
}
/// `adds xd, xn, xm`（置 NZCV）
fn 加溢(d: u8, n: u8, m: u8) -> u32 {
    r3(0xAB00_0000, d, n, m)
}
/// `subs xd, xn, xm`
fn 减溢(d: u8, n: u8, m: u8) -> u32 {
    r3(0xEB00_0000, d, n, m)
}
/// `mul xd, xn, xm`（**不置标志**，溢出要靠 `smulh` 比）
fn 乘(d: u8, n: u8, m: u8) -> u32 {
    r3(0x9B00_7C00, d, n, m)
}
/// `smulh xd, xn, xm`（有符号乘法的**高 64 位**）
fn 乘高(d: u8, n: u8, m: u8) -> u32 {
    r3(0x9B40_7C00, d, n, m)
}
/// `sdiv xd, xn, xm` —— ⚠️ 除以 0 **不陷阱**（给 0），所以除零要自己查。
fn 除(d: u8, n: u8, m: u8) -> u32 {
    r3(0x9AC0_0C00, d, n, m)
}
/// `msub xd, xn, xm, xa` = `xa - xn*xm`（算余数：被除数 - 商×除数）
fn 乘减(d: u8, n: u8, m: u8, a: u8) -> u32 {
    0x9B00_8000 | ((m as u32) << 16) | ((a as u32) << 10) | ((n as u32) << 5) | d as u32
}
/// `neg xd, xm`
fn 取负(d: u8, m: u8) -> u32 {
    0xCB00_03E0 | ((m as u32) << 16) | d as u32
}
/// `negs xd, xm`（置 V）
fn 取负溢(d: u8, m: u8) -> u32 {
    0xEB00_03E0 | ((m as u32) << 16) | d as u32
}
/// `cmp xn, xm`（= `subs xzr, xn, xm`）
fn 比(n: u8, m: u8) -> u32 {
    0xEB00_001F | ((m as u32) << 16) | ((n as u32) << 5)
}
/// `cmp xn, xm, asr #63` —— 乘法溢出检查用：`smulh` 的结果必须等于「结果的符号扩展」。
fn 比右移63(n: u8, m: u8) -> u32 {
    // SUBS 移位寄存器形态：shift=ASR(10)，imm6=63
    0xEB80_FC00 | ((m as u32) << 16) | ((n as u32) << 5) | 零 as u32
}
/// `cmn xm, #imm12`（= `adds xzr, xm, #imm`）—— 用来问「除数是不是 -1」。
fn 加比立即(m: u8, 立即: u32) -> u32 {
    0xB100_0000 | ((立即 & 0xFFF) << 10) | ((m as u32) << 5) | 零 as u32
}
/// `cmp xn, #0`
fn 比零(n: u8) -> u32 {
    0xF100_0000 | ((n as u32) << 5) | 零 as u32
}
/// `cset xd, 条件`
fn 定值(d: u8, 条件: u32) -> u32 {
    // CSINC xd, xzr, xzr, invert(cond)
    0x9A9F_07E0 | (((条件 ^ 1) & 0xF) << 12) | d as u32
}
/// `add xd, xn, #imm12`
fn 加立即(d: u8, n: u8, 立即: u32) -> u32 {
    0x9100_0000 | ((立即 & 0xFFF) << 10) | ((n as u32) << 5) | d as u32
}
/// `sub xd, xn, #imm12`
fn 减立即(d: u8, n: u8, 立即: u32) -> u32 {
    0xD100_0000 | ((立即 & 0xFFF) << 10) | ((n as u32) << 5) | d as u32
}
/// `eor xd, xn, xm`
fn 异或(d: u8, n: u8, m: u8) -> u32 {
    r3(0xCA00_0000, d, n, m)
}
/// `mov xd, xm`（= `orr xd, xzr, xm`）
fn 搬(d: u8, m: u8) -> u32 {
    0xAA00_03E0 | ((m as u32) << 16) | d as u32
}

