//! AArch64（ARM64）后端：把 IR 发成机器码（M184）。
//!
//! 和 x86-64 那一个**共用同一份 IR**（`super::指令`）—— 这正是 M182 抽 IR 的
//! 全部理由。这个文件只做「IR → 4 字节定长指令」的编码。
//!
//! ## 🔴 先说一句最难听的：**这台机器上验不了**
//!
//! 开发机是 Windows x86-64，**跑不了 ARM64 机器码**。所以这个后端的正确性靠三层：
//!
//! 1. **编码层**：每条指令的 32 位常量都用一个脚本喂给 capstone 反汇编核对过
//!    （`build/ev/m184/enc*.py`，那是开发期的一次性工具，不进仓库）；
//! 2. **字节层**：`tests/test_m184_aarch64.py` 在 x86-64 上**也能调** `生成()`
//!    （本模块不加 `cfg` 门），断言「该发的指令确实发了、该补的偏移补对了」；
//! 3. **执行层**：CI 的 `macos-latest`（arm64）真跑 —— **2026-11-08 跑通了**
//!    （4392 passed / 56 skipped，其中没有一条是「JIT 被跳过」）。
//!
//! 📌 那一轮 CI 还照出一个**字节判据抓不到**的真 bug：尾声没把 `sp` 还完
//! （序言压 48 字节、尾声只还 16）⇒ 返回时 `sp` 少 32，调用者一用栈就 SIGSEGV。
//! **每条指令单看都对**，错的是「一共还了多少」—— 这就是为什么
//! 「编码层 + 结构层」再严也替代不了「真跑一遍」。现在末尾有 `add sp, sp, #32`，
//! 并有判据 `test_尾声要把栈指针补回原样` 盯着这笔账。
//!
//! ⚠️ **仍然没测的**：ARM 上的**性能**（一个数字都没有 —— 本机跑不了 ARM 码，
//! CI 也没跑 bench）；Windows-on-ARM（`支持()` 里没写这个平台）。
//!
//! ## 寄存器怎么分（AAPCS64）
//!
//! | 寄存器 | 谁用 | 说明 |
//! |---|---|---|
//! | `x9`–`x12` | 整数槽（最多 4 个） | caller-saved |
//! | `d0`–`d3` | 浮点槽 | caller-saved |
//! | `x13`–`x17` | 临时（左右操作数 / 乘法高位 / 余数） | caller-saved |
//! | `x19` | `遍历` 的**索引** | **callee-saved** ⇒ 序言保存、三个出口恢复 |
//! | `x20` | `遍历` 的**元素基址**（= 参2 + 8） | 同上 |
//! | `x21` | **槽缓冲指针** | 同上。存寄存器里而不是栈上：ARM 的除法不占专用寄存器 |
//! | `x29`/`x30` | 帧指针 / 返回地址 | 序言 `stp`、尾声 `ldp` |
//!
//! ## 栈帧布局（`x29` 往上全是**正偏移**，所以不需要 `LDUR`）
//!
//! ```text
//!   stp x19,x20,[sp,#-16]!   ; [x29+32] = x19, [x29+40] = x20
//!   str x21,   [sp,#-16]!    ; [x29+16] = x21（占 16 字节，高 8 字节空着）
//!   stp x29,x30,[sp,#-16]!   ; [x29] = x29, [x29+8] = x30
//!   mov x29, sp
//! ```
//!
//! 尾声按 `[x29+16]` / `[x29+32]` 读回，然后 `mov sp, x29` 一次性抹掉
//! 表达式栈上的残留（**去优化出口必须这么做** —— 那儿的 `sp` 是不平衡的），
//! 再 `ldp x29,x30,[sp],#16` + **`add sp, sp, #32`** 把序言压的 48 字节还完。
//!
//! 🔴 **那 32 字节是 M184 在 macOS 上段错误的全部原因**：`mov sp, x29` 只把
//! `sp` 钉到 `S-48`，`ldp` 弹回 16 ⇒ 返回时 `sp = S-32`，调用者一用栈就崩
//! （退出码 -11）。**字节白名单验不出来**（每条指令单看都对），
//! 是 CI 的 macos-arm64 真跑才照出来的。
//!
//! ## 表达式栈：16 字节步长
//!
//! ARM64 没有单寄存器的 `push`，所以用 `str xN,[sp,#-16]!` / `ldr xN,[sp],#16`。
//! 一次占 16 字节（浪费一半），换来 `sp` 始终 16 字节对齐 —— AAPCS64 的硬要求，
//! 用 8 字节步长会破坏它。
//!
//! ## 三条出口（与 x86-64 完全一致）
//!
//! | 标签 | 含义 | 写回槽？ | 返回码 |
//! |---|---|---|---|
//! | 1 | 正常跑完 | ✅ | 0 |
//! | 3 | `中断` | ✅ | 2 |
//! | 2 | 去优化（溢出 / 除零 / `MIN / -1`） | ❌ | 1 |

