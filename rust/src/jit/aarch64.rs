/// 补表里这一条是什么跳转 —— 决定「偏移写进哪几位、范围多大」。
#[derive(Clone, Copy, PartialEq, Eq)]
enum 类 {
    /// `b`：imm26，单位是指令（±128MB）
    近,
    /// `b.cond`：imm19，单位是指令（±1MB）
    条件,
    /// `cbz` / `cbnz`：imm19，单位是指令
    比较零,
}

struct 发 {
    字: Vec<u32>,
    补: Vec<(usize, u16, 类)>,
    标: Vec<Option<usize>>,
}

impl 发 {
    fn new(标数: usize) -> Self {
        发 { 字: Vec::with_capacity(256), 补: Vec::new(), 标: vec![None; 标数] }
    }

    fn 新标(&mut self) -> u16 {
        self.标.push(None);
        (self.标.len() - 1) as u16
    }

    fn 打标(&mut self, 标: u16) {
        self.标[标 as usize] = Some(self.字.len());
    }

    /// 发一条跳转：`码` 里 imm 位留空，等 `收尾` 补。
    fn 跳(&mut self, 码: u32, 标: u16, 类: 类) {
        self.补.push((self.字.len(), 标, 类));
        self.字.push(码);
    }

    /// 补齐所有跳转。
    ///
    /// 🔴 **有落点没打上就整段作废**（返回 `None`）—— 同 x86-64 那条规矩。
    /// ARM64 上「没补」的表现和 x86 不太一样：`imm = 0` 是「跳到**自己**」，
    /// 对 `b.cond` 来说是「条件成立就原地打转」= 死循环，比 x86 的分支失效更响。
    fn 收尾(self) -> Option<Vec<u8>> {
        let mut 字 = self.字;
        for (位, 标, 类) in &self.补 {
            let 到 = self.标.get(*标 as usize).copied().flatten()?;
            let 差 = 到 as i64 - *位 as i64; // 单位：指令
            let 填 = match 类 {
                类::近 => {
                    if 差 < -(1 << 25) || 差 >= (1 << 25) {
                        return None; // 超出 ±128MB：不编
                    }
                    (差 as u32) & 0x03FF_FFFF
                }
                类::条件 | 类::比较零 => {
                    if 差 < -(1 << 18) || 差 >= (1 << 18) {
                        return None; // 超出 ±1MB：不编
                    }
                    ((差 as u32) & 0x7FFFF) << 5
                }
            };
            字[*位] |= 填;
        }
        let mut 出 = Vec::with_capacity(字.len() * 4);
        for w in 字 {
            出.extend_from_slice(&w.to_le_bytes());
        }
        Some(出)
    }
}

/// 整数的比较 → 条件码（有符号）。
fn 整数条件(c: 比较) -> u32 {
    match c {
        比较::等 => 条_EQ,
        比较::不等 => 条_NE,
        比较::小于 => 条_LT,
        比较::大于 => 条_GT,
        比较::小于等 => 条_LE,
        比较::大于等 => 条_GE,
    }
}

/// 条件取反（`比跳` 要「假则跳」）。
fn 取反(条件: u32) -> u32 {
    条件 ^ 1
}

/// 把操作数装进整数寄存器。
fn 装(f: &mut 发, d: u8, x: 源) {
    match x {
        源::槽(k) => f.字.push(搬(d, 槽整[k as usize])),
        源::数(v) => 装数(&mut f.字, d, v),
    }
}

/// 浮点二元运算：弹右、弹左，算完把**位模式**压回栈。
fn 发浮点算(f: &mut 发, op: 运算, 左转: bool, 右转: bool) -> Option<()> {
    f.字.push(栈弹(临2));
    f.字.push(栈弹(临1));
    if 右转 {
        f.字.push(转浮(浮右, 临2));
    } else {
        f.字.push(浮入(浮右, 临2));
    }
    if 左转 {
        f.字.push(转浮(浮左, 临1));
    } else {
        f.字.push(浮入(浮左, 临1));
    }
    match op {
        运算::加 => f.字.push(浮三(浮加_码, 浮左, 浮左, 浮右)),
        运算::减 => f.字.push(浮三(浮减_码, 浮左, 浮左, 浮右)),
        运算::乘 => f.字.push(浮三(浮乘_码, 浮左, 浮左, 浮右)),
        运算::除法 => {
            // 🔴 基石里 `1.0 / 0.0` **报 E2001**（M183 查过 `binop`），不是 `inf`。
            // `fcmp` 在无序（NaN）时 `EQ=0`，所以这一条**不会**把 NaN 误判成零 ——
            // 比 x86 少补一个 `jp`（那边 `ucomisd` 会把 NaN 同时置 ZF 和 PF）。
            f.字.push(浮比零(浮右));
            f.跳(条件跳(条_EQ, 0), 标优, 类::条件);
            f.字.push(浮三(浮除_码, 浮左, 浮左, 浮右));
        }
        // 浮点的 `//` `%` 前端根本不发（要 floor / fmod）—— 真来了就整段不编。
        _ => return None,
    }
    f.字.push(浮出(临1, 浮左));
    f.字.push(栈压(临1));
    Some(())
}

/// 浮点比较：`fcmp` + `cset`。
///
/// 🔴 **`<` 和 `<=` 必须交换操作数**。ARM 的 `fcmp` 在无序（有 NaN）时置
/// `N=0,Z=0,C=1,V=1`，于是：
///
/// | 条件 | 无序时的结果 | 对不对 |
/// |---|---|---|
/// | `EQ`（Z=1） | 假 | ✅ |
/// | `NE`（Z=0） | 真 | ✅ |
/// | `GT`（Z=0 且 N==V） | 假 | ✅ |
/// | `GE`（N==V） | 假 | ✅ |
/// | `LT`（N!=V） | **真** | ❌ |
/// | `LE` | **真** | ❌ |
///
/// 所以 `a < b` 发成 `fcmp b, a` + `GT`、`a <= b` 发成 `fcmp b, a` + `GE`
/// （`b > a` 与 `b >= a` 在无序时都是假，正好）。这是 LLVM 在 AArch64 上的
/// 标准做法 —— 我原来以为「ARM 的 fcmp 天生 IEEE、不用像 x86 那样补 `setnp`」，
/// **那个想法错在 LT/LE 这两条上**，查手册才发现。
fn 发浮点比(f: &mut 发, c: 比较, 左转: bool, 右转: bool) {
    f.字.push(栈弹(临2));
    f.字.push(栈弹(临1));
    if 右转 {
        f.字.push(转浮(浮右, 临2));
    } else {
        f.字.push(浮入(浮右, 临2));
    }
    if 左转 {
        f.字.push(转浮(浮左, 临1));
    } else {
        f.字.push(浮入(浮左, 临1));
    }
    let (n, m, 条件) = match c {
        // 交换操作数：`fcmp 右, 左` 问的是「右 > 左」，等价于「左 < 右」
        比较::小于 => (浮右, 浮左, 条_GT),
        比较::小于等 => (浮右, 浮左, 条_GE),
        比较::大于 => (浮左, 浮右, 条_GT),
        比较::大于等 => (浮左, 浮右, 条_GE),
        比较::等 => (浮左, 浮右, 条_EQ),
        比较::不等 => (浮左, 浮右, 条_NE),
    };
    f.字.push(浮比(n, m));
    f.字.push(定值(临1, 条件));
    f.字.push(栈压(临1));
}

/// 整数 `//` 与 `%`。
///
/// 三件事按顺序：**除零 → 除数 -1 → 普通路径 + 向下取整修正**。
///
/// - 除零：`sdiv` 在 ARM 上**给 0，不陷阱**（与 x86 的 `SIGFPE` 相反）。
///   但语义上必须报 `E2001`，所以这儿显式去优化。
/// - 除数 `-1`：`i64::MIN / -1` 在 `sdiv` 上得 `i64::MIN`（回绕），而解释器用
///   `i128` 得 `+2^63` ⇒ 溢出。所以走 `negs` + `b.vs`，顺带余数恒为 0。
/// - 向下取整：`sdiv` 是**截断**（`-7 // 3` 给 `-2`），基石要 `-3`。
///   修正条件：**余数 ≠ 0 且 余数与除数异号** ⇒ 商减一、余加除数。
fn 发除模(f: &mut 发, op: 运算) {
    f.字.push(栈弹(临2)); // 除数
    f.字.push(栈弹(临1)); // 被除数

    let 普 = f.新标();
    let 汇 = f.新标();

    // —— 除零 → 去优化（解释器报 E2001）——
    f.跳(非零跳字(临2, 0), 普, 类::比较零);
    f.跳(无条件跳(0), 标优, 类::近);
    f.打标(普);

    // —— 除数 == -1：单独走 ——
    f.字.push(加比立即(临2, 1)); // cmn x14, #1
    let 普通 = f.新标();
    f.跳(条件跳(条_NE, 0), 普通, 类::条件);
    f.字.push(取负溢(临3, 临1)); // negs x15, x13
    f.跳(条件跳(条_VS, 0), 标优, 类::条件);
    装数(&mut f.字, 临4, 0); // mov 余数 = 0
    f.跳(无条件跳(0), 汇, 类::近);

    // —— 普通路径 ——
    f.打标(普通);
    f.字.push(除(临3, 临1, 临2)); // sdiv x15, x13, x14
    f.字.push(乘减(临4, 临3, 临2, 临1)); // msub x16, x15, x14, x13
    f.跳(零跳字(临4, 0), 汇, 类::比较零); // 余数 0 ⇒ 不用修正
    f.字.push(异或(临5, 临4, 临2)); // eor x17, x16, x14
    f.字.push(比零(临5)); // cmp x17, #0
    f.跳(条件跳(条_PL, 0), 汇, 类::条件); // 非负 ⇒ 同号 ⇒ 不用修正
    f.字.push(减立即(临3, 临3, 1)); // 商 -= 1
    f.字.push(加(临4, 临4, 临2)); // 余 += 除数

    f.打标(汇);
    f.字.push(栈压(if op == 运算::整除 { 临3 } else { 临4 }));
}

// ---------------------------------------------------------------------------
// 收尾（三个出口）
// ---------------------------------------------------------------------------

fn 收(f: &mut 发, 方案: &方案, 码: u32, 写回: bool) {
    if 写回 {
        for (k, 型) in 方案.槽型.iter().enumerate() {
            let off = (k * 8) as u32;
            match 型 {
                类型::整数 => f.字.push(存槽整(off, 槽整[k])),
                类型::浮点 => f.字.push(存槽浮(off, 槽浮[k])),
            }
        }
    }
    // 恢复 callee-saved（`x29` 往上，全是正偏移）→ 抹掉表达式栈 → 恢复 x29/x30
    //
    // ⚠️ 三步的**顺序**和「补回多少字节」都要和序言对得上：
    //    序言：stp x19,x20 (-16) · str x21 (-16) · stp x29,x30 (-16) = **-48**
    //    尾声：ldr/ldp 从 `[x29+16]`/`[x29+32]` 读回 · `mov sp,x29` 把 sp 钉回帧基
    //          （**去优化出口的 sp 是不平衡的，必须这么钉**） ·
    //          `ldp …, [sp], #16` 弹回 16 · **`add sp, sp, #32` 补上剩下 32** = +48
    f.字.push(取_21);
    f.字.push(取_19_20);
    f.字.push(帧撤);
    f.字.push(取_29_30);
    f.字.push(退栈);
    // mov w0, #码（`w0` 写会把高 32 位清零，返回 i64 也正确）
    f.字.push(0x5280_0000 | (码 << 5));
    f.字.push(返回);
}

/// 把 IR 发成机器码。**有任何一条跳转找不到落点（或超出范围）就返回 `None`**。
pub(super) fn 生成(方案: &方案) -> Option<Vec<u8>> {
    let mut f = 发::new(方案.标数);

    // 序言：保存 callee-saved（**顺序决定尾声中那几个偏移**，见模块文档的图）
    f.字.push(存_19_20);
    f.字.push(存_21);
    f.字.push(存_29_30);
    f.字.push(帧立);
    f.字.push(搬(缓, 0)); // mov x21, x0

    // 装槽（`x21` 已经是缓冲指针）
    for (k, 型) in 方案.槽型.iter().enumerate() {
        let off = (k * 8) as u32;
        match 型 {
            类型::整数 => f.字.push(载槽整(槽整[k], off)),
            类型::浮点 => f.字.push(载槽浮(槽浮[k], off)),
        }
    }

    // `遍历`：基址 = 参2 + 8（跳过「个数」），索引清零
    if 方案.是遍历 {
        f.字.push(加立即(基, 1, 8));
        装数(&mut f.字, 索, 0);
    }

    for 步 in &方案.指令们 {
        match *步 {
            指令::标(标) => f.打标(标),
            指令::跳(标) => f.跳(无条件跳(0), 标, 类::近),
            指令::零跳(标) => {
                f.字.push(栈弹(临1));
                f.跳(零跳字(临1, 0), 标, 类::比较零);
            }
            指令::非零跳(标) => {
                f.字.push(栈弹(临1));
                f.跳(非零跳字(临1, 0), 标, 类::比较零);
            }
            指令::越界跳(标) => {
                // 索引 >= 个数（个数在元素基址前面那 8 字节）
                f.字.push(载个数(临3));
                f.字.push(比(索, 临3));
                f.跳(条件跳(条_GE, 0), 标, 类::条件);
            }
            指令::压槽(k) => match 方案.槽型[k as usize] {
                类型::整数 => f.字.push(栈压(槽整[k as usize])),
                类型::浮点 => {
                    f.字.push(浮出(临1, 槽浮[k as usize]));
                    f.字.push(栈压(临1));
                }
            },
            指令::压数(v) => {
                装数(&mut f.字, 临1, v);
                f.字.push(栈压(临1));
            }
            指令::压浮点(位) => {
                装数(&mut f.字, 临1, 位 as i64);
                f.字.push(栈压(临1));
            }
            指令::压元素 => {
                f.字.push(载元素(临3));
                f.字.push(栈压(临3));
            }
            指令::步进 => f.字.push(加立即(索, 索, 1)),
            指令::二元 { 运算: op, 类型, 左转, 右转 } => match 类型 {
                类型::整数 => match op {
                    运算::加 | 运算::减 => {
                        f.字.push(栈弹(临2));
                        f.字.push(栈弹(临1));
                        f.字.push(if op == 运算::加 {
                            加溢(临1, 临1, 临2)
                        } else {
                            减溢(临1, 临1, 临2)
                        });
                        f.跳(条件跳(条_VS, 0), 标优, 类::条件);
                        f.字.push(栈压(临1));
                    }
                    运算::乘 => {
                        // 🔴 `mul` **不置 NZCV**，所以不能像 `adds` 那样 `b.vs`。
                        // 用 `smulh` 取高 64 位，再和「结果的符号扩展」比：
                        // 不相等就是溢出。
                        f.字.push(栈弹(临2));
                        f.字.push(栈弹(临1));
                        f.字.push(乘高(临3, 临1, 临2));
                        f.字.push(乘(临1, 临1, 临2));
                        f.字.push(比右移63(临3, 临1));
                        f.跳(条件跳(条_NE, 0), 标优, 类::条件);
                        f.字.push(栈压(临1));
                    }
                    _ => 发除模(&mut f, op),
                },
                类型::浮点 => 发浮点算(&mut f, op, 左转, 右转)?,
            },
            指令::取负 => {
                f.字.push(栈弹(临1));
                f.字.push(取负溢(临1, 临1));
                f.跳(条件跳(条_VS, 0), 标优, 类::条件);
                f.字.push(栈压(临1));
            }
            指令::取负浮点 => {
                f.字.push(栈弹(临1));
                f.字.push(浮入(浮左, 临1));
                f.字.push(浮取负(浮左, 浮左));
                f.字.push(浮出(临1, 浮左));
                f.字.push(栈压(临1));
            }
            指令::存槽(k) => match 方案.槽型[k as usize] {
                类型::整数 => f.字.push(栈弹(槽整[k as usize])),
                类型::浮点 => {
                    f.字.push(栈弹(临1));
                    f.字.push(浮入(槽浮[k as usize], 临1));
                }
            },
            指令::丢弃 => f.字.push(栈弹(临1)),
            指令::比压 { 比较: c, 类型, 左转, 右转 } => match 类型 {
                类型::整数 => {
                    f.字.push(栈弹(临2));
                    f.字.push(栈弹(临1));
                    f.字.push(比(临1, 临2));
                    f.字.push(定值(临1, 整数条件(c)));
                    f.字.push(栈压(临1));
                }
                类型::浮点 => 发浮点比(&mut f, c, 左转, 右转),
            },
            指令::算存(左, op, 右, k) => {
                装(&mut f, 临1, 左);
                装(&mut f, 临2, 右);
                match op {
                    运算::加 => {
                        f.字.push(加溢(临1, 临1, 临2));
                        f.跳(条件跳(条_VS, 0), 标优, 类::条件);
                    }
                    运算::减 => {
                        f.字.push(减溢(临1, 临1, 临2));
                        f.跳(条件跳(条_VS, 0), 标优, 类::条件);
                    }
                    _ => {
                        f.字.push(乘高(临3, 临1, 临2));
                        f.字.push(乘(临1, 临1, 临2));
                        f.字.push(比右移63(临3, 临1));
                        f.跳(条件跳(条_NE, 0), 标优, 类::条件);
                    }
                }
                f.字.push(搬(槽整[k as usize], 临1));
            }
            指令::比跳(左, c, 右, 标) => {
                装(&mut f, 临1, 左);
                装(&mut f, 临2, 右);
                f.字.push(比(临1, 临2));
                f.跳(条件跳(取反(整数条件(c)), 0), 标, 类::条件);
            }
            指令::比真跳(左, c, 右, 标) => {
                装(&mut f, 临1, 左);
                装(&mut f, 临2, 右);
                f.字.push(比(临1, 临2));
                f.跳(条件跳(整数条件(c), 0), 标, 类::条件);
            }
        }
    }

    // 正常出口（0）
    f.打标(标出);
    收(&mut f, 方案, 0, true);
    // `中断`（2）—— **要写回**
    f.打标(标断);
    收(&mut f, 方案, 2, true);
    // 去优化（1）—— **不写回**
    f.打标(标优);
    收(&mut f, 方案, 1, false);

    f.收尾()
}

// ---------------------------------------------------------------------------
// 函数级 JIT（M190 的第二刀）：把整个函数编成机器码
// ---------------------------------------------------------------------------
//
// 与上面的 `生成`（循环 JIT）**完全分开**：那个活在「抬头 → 回跳」那一段里、
// 靠 `x21` 指向宿主给的槽缓冲；这个有**自己的帧**、自己的调用约定，
// 而且会 `bl` 到自己身上（自递归）。设计见 `docs/设计决策.md` D114。
//
// ## 约定（AAPCS64 原生，不发明新的）
//
// ```text
// extern "C" fn(a: i64, b: i64, c: i64, 状态: *mut [i64; 2]) -> i64
//                x0      x1      x2          x3                  x0
// ```
//
// - `状态[0]` = 去优化旗（0 正常 / 1 去优化）
// - `状态[1]` = **当前递归深度**（与解释器的 `MAX_FRAMES = 1000` 同一个上限）
//
// 🔴 **为什么状态要指针传、而不是返回 `(i64, i64)`**：ARM64 的 AAPCS64 支持
// 双寄存器返回（x0/x1），但**两个后端用同一个约定**才不用维护两套调用点。
// 而 Win64 上 16 字节返回结构体走隐藏指针、会把参数整体挤歪一格
// （x86-64 那版就是这么错的：未到热度阈值时全对，一编上就无限递归），
// 所以两边统一走「单返回值 + 状态指针」。

/// 函数级 JIT 的临时寄存器 —— **全部 caller-saved**。
///
/// 🔴 **一个 callee-saved 都不碰**：用了 `x19`–`x28` 就得在序言 `stp` 保存、
/// 三个出口都要恢复（循环 JIT 那 48 字节的债就是这么欠下的）。而函数级 JIT 里
/// `bl` 会把 `x0`–`x18` 全踩掉 ⇒ 凡是**跨调用还要用**的值一律放栈上
/// （表达式栈本来就在栈上），寄存器只做「两条指令之间」的搬运。
const 临A: u8 = 9;
const 临B: u8 = 10;
const 临C: u8 = 11;

/// `stur xn, [x29, #imm]` —— 有符号 9 位偏移（±256 字节），帧内访问够用。
fn 帧存(off: i32, n: u8) -> u32 {
    debug_assert!((-256..=255).contains(&off), "帧偏移超出 stur 的 imm9 范围");
    0xF800_0000 | (((off as u32) & 0x1FF) << 12) | (29 << 5) | n as u32
}

/// `ldur xd, [x29, #imm]`
fn 帧取(d: u8, off: i32) -> u32 {
    debug_assert!((-256..=255).contains(&off), "帧偏移超出 ldur 的 imm9 范围");
    0xF840_0000 | (((off as u32) & 0x1FF) << 12) | (29 << 5) | d as u32
}

/// `stur xn, [xm, #imm]`（基址任意寄存器 —— 状态结构靠它）
fn 基存(x: u8, off: i32, n: u8) -> u32 {
    debug_assert!((-256..=255).contains(&off));
    0xF800_0000 | (((off as u32) & 0x1FF) << 12) | ((x as u32) << 5) | n as u32
}

/// `ldur xd, [xm, #imm]`
fn 基取(d: u8, x: u8, off: i32) -> u32 {
    debug_assert!((-256..=255).contains(&off));
    0xF840_0000 | (((off as u32) & 0x1FF) << 12) | ((x as u32) << 5) | d as u32
}

/// `cmp xn, #imm12`
fn 比数值(n: u8, 立即: u32) -> u32 {
    0xF100_0000 | ((立即 & 0xFFF) << 10) | ((n as u32) << 5) | 零 as u32
}

/// `bl <imm26>` —— 偏移以**指令**为单位，编码与 `b` 同形，只是 opcode 不同。
const 调用_码: u32 = 0x9400_0000;

/// 把一整个函数编成机器码。
///
/// 帧布局（`x29` 往下，负偏移）：
///
/// ```text
/// [x29-8]                        槽 0
/// [x29-16]                       槽 1 …
/// [x29-8*(槽数+1)]               表达式栈第 0 层 …
/// [x29-8*(槽数+栈层+1)]          状态结构指针（旗 + 深度）
/// ```
///
/// 🔴 **帧大小必须是 16 的倍数**（AAPCS64 硬要求：公共接口处 `sp` 16 对齐）。
/// 进函数时 `sp` 16 对齐，`stp x29,x30,[sp,#-16]!` 之后还是，
/// `sub sp, sp, #16n` 之后仍然是。
pub(super) fn 生成函数(
    形: &super::函数方案,
    指令们: &[crate::Instr],
    常量们: &[Val],
) -> Option<Vec<u8>> {
    use crate::op;
    macro_rules! 编不了 {
        () => {{
            if std::env::var("JISHI_JIT_DEBUG").is_ok() {
                eprintln!("[jit-func码/arm] 第 {} 行放弃", line!());
            }
            return None;
        }};
    }

    let 指令们 = super::有效指令(指令们, 常量们);
    let 总 = 指令们.len();
    let 完标 = (总 + 1) as u16; // 正常返回
    let 去标 = (总 + 2) as u16; // 去优化
    let mut f = 发::new(总 + 3); // 0 = 函数入口，1..=总 = 各条字节码

    let 槽数 = 形.槽数;
    if 槽数 > 8 || 形.参数数 == 0 || 形.参数数 > 3 {
        编不了!();
    }
    const 栈层: usize = 8;
    // 槽 + 表达式栈 + 状态指针，再向上取到 16 的倍数
    let 帧 = ((8 * (槽数 + 栈层 + 1) + 15) / 16) * 16;
    let 旗偏 = -(8 * (槽数 + 栈层 + 1) as i32);
    let 槽偏 = |i: usize| -> i32 { -(8 * (i as i32 + 1)) };
    let 栈偏 = |j: usize| -> i32 { -(8 * (槽数 as i32 + j as i32 + 1)) };

    // ---- 序言 ----
    f.打标(0);
    f.字.push(存_29_30); // stp x29, x30, [sp, #-16]!
    f.字.push(帧立); // mov x29, sp
    f.字.push(0xD100_03FF | ((帧 as u32 & 0xFFF) << 10)); // sub sp, sp, #帧

    // 形参落槽（x0..x2），状态指针单独放
    for i in 0..形.参数数 {
        f.字.push(帧存(槽偏(i), i as u8));
    }
    f.字.push(帧存(旗偏, 3)); // str x3, [x29, #旗偏]

    // ---- 进一层递归深度，与解释器同一个上限 ----
    //
    // 🔴 不数深度的后果：解释器有 `MAX_FRAMES = 1000`，机器码的递归不建
    // 解释器帧 ⇒ 「数(1500) 解释器报错、JIT 跑通」= **改了语义**；
    // 死递归更会变成真撞栈（SIGSEGV），而不是那句人话报错。
    f.字.push(帧取(临A, 旗偏)); // ldr x9, [x29, #旗偏]
    f.字.push(基取(临B, 临A, 8)); // ldr x10, [x9, #8]  ← 深度
    f.字.push(加立即(临B, 临B, 1)); // add x10, x10, #1
    f.字.push(基存(临A, 8, 临B)); // str x10, [x9, #8]
    f.字.push(比数值(临B, 1000)); // cmp x10, #1000
    f.跳(条件跳(条_GE, 0), 去标, 类::条件); // b.ge 去标

    let mut 深: usize = 0;

    for (i, ins) in 指令们.iter().enumerate() {
        f.打标((i + 1) as u16);
        match ins.op {
            op::LOAD_CONST => {
                let v = super::取整(常量们, ins.a)?;
                if 深 >= 栈层 {
                    编不了!();
                }
                装数(&mut f.字, 临A, v);
                f.字.push(帧存(栈偏(深), 临A));
                深 += 1;
            }
            op::LOAD_FAST => {
                let k = ins.a as usize;
                if k >= 槽数 || 深 >= 栈层 {
                    编不了!();
                }
                f.字.push(帧取(临A, 槽偏(k)));
                f.字.push(帧存(栈偏(深), 临A));
                深 += 1;
            }
            op::STORE_FAST => {
                let k = ins.a as usize;
                if 深 == 0 || k >= 槽数 {
                    编不了!();
                }
                深 -= 1;
                f.字.push(帧取(临A, 栈偏(深)));
                f.字.push(帧存(槽偏(k), 临A));
            }
            op::POP_TOP => {
                if 深 == 0 {
                    编不了!();
                }
                深 -= 1;
            }
            op::LOAD_GLOBAL => {
                // 🔴 不物化、**但要算栈深** —— 它占一个「表达式栈位置」。
                // 漏了这一句，后面每个 `CALL` 的实参偏移都差一格
                // （x86-64 那一版第一版就是这么错的）。
                if 深 >= 栈层 {
                    编不了!();
                }
                深 += 1;
            }
            op::BIN_OP => {
                let 算 = super::认运算(ins.a)?;
                if 深 < 2 {
                    编不了!();
                }
                深 -= 2;
                f.字.push(帧取(临B, 栈偏(深 + 1))); // 右
                f.字.push(帧取(临A, 栈偏(深))); // 左
                match 算 {
                    super::运算::加 => {
                        f.字.push(加溢(临A, 临A, 临B));
                        f.跳(条件跳(条_VS, 0), 去标, 类::条件);
                    }
                    super::运算::减 => {
                        f.字.push(减溢(临A, 临A, 临B));
                        f.跳(条件跳(条_VS, 0), 去标, 类::条件);
                    }
                    super::运算::乘 => {
                        // 🔴 `mul` **不置 NZCV** ⇒ 用 `smulh` 取高 64 位，
                        // 与「结果的符号扩展」比，不等就是溢出。
                        f.字.push(乘高(临C, 临A, 临B));
                        f.字.push(乘(临A, 临A, 临B));
                        f.字.push(比右移63(临C, 临A));
                        f.跳(条件跳(条_NE, 0), 去标, 类::条件);
                    }
                    _ => 编不了!(), // 整除 / 取余：第一版不编（除零、MIN/-1 都要另查）
                }
                f.字.push(帧存(栈偏(深), 临A));
                深 += 1;
            }
            op::COMPARE => {
                let c = super::认比较(ins.a)?;
                if 深 < 2 {
                    编不了!();
                }
                深 -= 2;
                f.字.push(帧取(临B, 栈偏(深 + 1))); // 右
                f.字.push(帧取(临A, 栈偏(深))); // 左
                f.字.push(比(临A, 临B));
                f.字.push(定值(临A, 整数条件(c)));
                f.字.push(帧存(栈偏(深), 临A));
                深 += 1;
            }
            op::POP_JUMP_IF_FALSE | op::POP_JUMP_IF_TRUE => {
                if 深 == 0 || ins.a < 0 || ins.a as usize > 总 {
                    编不了!();
                }
                深 -= 1;
                f.字.push(帧取(临A, 栈偏(深)));
                let 码 = if ins.op == op::POP_JUMP_IF_FALSE {
                    零跳字(临A, 0)
                } else {
                    非零跳字(临A, 0)
                };
                f.跳(码, (ins.a as usize + 1) as u16, 类::比较零);
            }
            op::JUMP => {
                if ins.a < 0 || ins.a as usize > 总 {
                    编不了!();
                }
                f.跳(无条件跳(0), (ins.a as usize + 1) as u16, 类::近);
            }
            op::RETURN => {
                if 深 == 0 {
                    编不了!();
                }
                深 -= 1;
                f.字.push(帧取(临A, 栈偏(深)));
                f.字.push(搬(0, 临A)); // mov x0, x9 —— 返回值
                f.跳(无条件跳(0), 完标, 类::近);
            }
            op::CALL => {
                let 实参 = ins.a as usize;
                if 实参 > 3 || 实参 == 0 || 深 < 实参 + 1 {
                    编不了!();
                }
                深 -= 实参 + 1;
                for k in 0..实参 {
                    f.字.push(帧取(k as u8, 栈偏(深 + 1 + k)));
                }
                f.字.push(帧取(3, 旗偏)); // x3 = 状态指针，原样传给内层
                f.跳(调用_码, 0, 类::近); // bl 函数入口（自己的起点）
                // 内层把旗立起来 ⇒ 整段退出去优化（x0 里是垃圾，别用）
                // 🔴 两级间接：`[x29+旗偏]` 存的是**指针**，旗在它指向处。
                f.字.push(帧取(临C, 旗偏));
                f.字.push(基取(临C, 临C, 0));
                f.跳(非零跳字(临C, 0), 去标, 类::比较零);
                f.字.push(帧存(栈偏(深), 0));
                深 += 1;
            }
            _ => 编不了!(),
        }
    }

    // 走到末尾还没 `返回` ⇒ 形态不认识（交给解释器，绝不猜）
    f.跳(无条件跳(0), 去标, 类::近);

    // ---- 正常出口 ----
    f.打标(完标);
    还一层(&mut f, 旗偏);
    f.字.push(帧撤); // mov sp, x29 —— 一次性抹掉表达式栈的残留
    f.字.push(取_29_30); // ldp x29, x30, [sp], #16
    f.字.push(返回); // ret（返回值已在 x0）
    let _ = 深;

    // ---- 去优化出口 ----
    f.打标(去标);
    f.字.push(帧取(临A, 旗偏));
    装数(&mut f.字, 临B, 1);
    f.字.push(基存(临A, 0, 临B)); // str x10, [x9]  ← 旗 = 1
    还一层(&mut f, 旗偏);
    装数(&mut f.字, 0, 0); // mov x0, #0（调用方会丢掉）
    f.字.push(帧撤);
    f.字.push(取_29_30);
    f.字.push(返回);

    let r = f.收尾();
    if r.is_none() && std::env::var("JISHI_JIT_DEBUG").is_ok() {
        eprintln!("[jit-func码/arm] 收尾失败：有跳转找不到落点");
    }
    r
}

/// 退一层递归深度（两个出口都要调）。
///
/// 🔴 少了它：深度只增不减 ⇒ 跑久了明明没递归却报「递归层数太深了」。
fn 还一层(f: &mut 发, 旗偏: i32) {
    f.字.push(帧取(临C, 旗偏));
    f.字.push(基取(临A, 临C, 8));
    f.字.push(减立即(临A, 临A, 1));
    f.字.push(基存(临C, 8, 临A));
}
