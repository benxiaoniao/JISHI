# A1 · 文本能按码点比大小（原来是「不能比较」，只有 Rust 漏了这一支）
# ---------------------------------------------------------------------------

#: ⚠️ 这一段里的 `𝄞`(U+1D11E) 与 `\ufffd`(U+FFFD) 是**故意挑的**：
#:    UTF-16 码元序会把它们比反（`\ufffd` 的码元 FFFD > 代理项 D834），
#:    而码点序是 `\ufffd`(65533) < `𝄞`(119070)。用它们才能抓出「谁在按 UTF-16 比」。
#:    📌 别改成两个 CJK 字 —— 那些在两种序下结论相同，判据会假绿。
_A1 = """
# ① 中文按码点（甲 U+7532 > 乙 U+4E59）
打印(`甲乙:`, `甲` < `乙`, `甲` > `乙`)
# ② ASCII：大写在小写前；相等要能出来
打印(`ASCII:`, `A` < `b`, `B` < `a`, `A` <= `A`, `A` >= `A`)
# ③ 前缀与空串（字典序的老规矩，别在改比较时弄丢）
打印(`前缀:`, `ab` < `abc`, `` < `a`, `abc` > `ab`)
# ④ 🔴 星平面 vs 基本平面：UTF-16 实现会在这里给相反的答案
打印(`星平面:`, `\ufffd` < `𝄞`, `𝄞` > `\ufffd`)
# ⑤ 排序必须与比较同序（`排序` 是**原地**排、返回空；`排序按` 才返回新列表）
令 词们 = [`乙`, `甲`, `𝄞`, `A`]
词们.排序()
打印(`排序:`, 词们)
"""


def test_A1_文本能按码点比(tmp_path):
    出, 码 = _跑(_A1, tmp_path)
    assert 码 == 0, 出[-600:]
    紧 = _紧(出)
    assert "甲乙: 假 真" in 紧, 紧
    assert "ASCII: 真 真 真 真" in 紧, 紧
    assert "前缀: 真 真 真" in 紧, 紧
    # 🔴 这两项是 UTF-16 与码点的分水岭，不是随便两个字符
    assert "星平面: 真 真" in 紧, 紧
    assert "排序: ['A', '乙', '甲', '𝄞']" in 紧, 紧


def test_A1_三宿主比较结论一致(tmp_path):
    """Python / Rust / Node 三家必须同序 —— Node 用 UTF-16，最容易在这里偏。"""
    出们 = {}
    for 引擎 in ("Rust", "Python", "Node"):
        出, 码 = _跑(_A1, tmp_path, 引擎=引擎)
        assert 码 == 0, f"{引擎}：{出[-400:]}"
        出们[引擎] = _紧(出)
    assert 出们["Rust"] == 出们["Python"] == 出们["Node"], 出们


def test_A1_跨类型仍然不能比(tmp_path):
    """允许文本比大小**不等于**允许乱比：数字和文本放在一起还得报错。

    📌 这条是「改比较」时的护栏 —— 把 `Val::Str` 那一支写成
       「转成字节再比」就会把跨类型也放过去，那时排序里混一个数字就静默出错。
    """
    出, 码 = _跑('打印(1 < `a`)\n', tmp_path)
    assert 码 != 0, 出[-400:]
    assert "不能比较" in 出 or "类型" in 出, 出[-500:]


