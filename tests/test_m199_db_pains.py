import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))          # noqa: E402

from conftest import rust_exe_path                                    # noqa: E402


def _跑(源: str, tmp_path: Path, 引擎="Rust", 名="脚本.jsh", 工作目录=None):
    """跑一段基石源码，返回 `(合并输出, 退出码)`。"""
    import subprocess

    脚本 = tmp_path / 名
    # `名` 可以带子目录（B2 要「脚本在 A、cwd 在 B」）—— 父目录得先有
    脚本.parent.mkdir(parents=True, exist_ok=True)
    脚本.write_text(源, encoding="utf-8", newline="\n")
    if 引擎 == "Rust":
        if not rust_exe_path().is_file():
            pytest.skip("没编 jishi-rs（先 cargo build --release）")
        命令 = [str(rust_exe_path()), str(脚本)]
    elif 引擎 == "Node":
        from oracle.jishi import serialize
        from oracle.jishi.compiler import compile_source

        (tmp_path / "程序.json").write_text(
            serialize.dumps(compile_source(源, str(脚本))), encoding="utf-8")
        import shutil

        if shutil.which("node") is None:
            pytest.skip("没有 node")
        命令 = ["node", str(ROOT / "oracle" / "node" / "index.js"), "程序.json"]
    else:                                   # Python（判据基准）
        命令 = [sys.executable, "-m", "oracle.jishi.cli", str(脚本)]
    r = subprocess.run(命令, cwd=str(工作目录 or tmp_path), capture_output=True,
                       timeout=300, input=b"")
    return (r.stdout + r.stderr).decode("utf-8", "replace"), r.returncode


def _紧(s: str) -> str:
    """把连续空白压成一个空格（`打印` 多参数的空格数不值得在断言里数）。"""
    return " ".join(s.split())


