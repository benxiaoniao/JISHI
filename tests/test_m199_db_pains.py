# B4 · 字典成员判断「在」未命中必须走哈希
# ---------------------------------------------------------------------------

_B4 = """
令 大 = {}
遍历 i 在 范围(2000)：
    大[`键{i}`] = i

# ① 未命中的「在」与「获取」结论必须一致
打印(`在:`, `没有1` 在 大, `获取:`, 大.获取(`没有1`, 空) != 空)
# ② 命中也是
打印(`在:`, `键1` 在 大, `获取:`, 大.获取(`键1`, 空) != 空)
# ③ 各种可哈希键都要走哈希：数字 / 布尔（真 == 1）/ 空
令 怪 = {}
怪[1] = `甲`
怪[空] = `乙`
打印(`数字:`, 1 在 怪, `,`, 2 在 怪, `,`, 真 在 怪, `,`, 空 在 怪)
# ④ `不在` 与 `在` 互为反
打印(`不在:`, `没有1` 不在 大, `在:`, `没有1` 在 大)
"""


def test_B4_字典在的结论与获取一致(tmp_path):
    """语义锚：`键 在 字典` 必须和 `字典.获取(键, 空) != 空` 同结论。

    这条**不测速度**，测的是「改快之后没改坏」—— 包括不可哈希的键（列表）
    那条线性兜底。
    """
    出, 码 = _跑(_B4, tmp_path)
    assert 码 == 0, 出[-500:]
    紧 = _紧(出)
    assert "在: 假 获取: 假" in 紧, 紧
    assert "在: 真 获取: 真" in 紧, 紧
    assert "数字: 真 , 假 , 真 , 真" in 紧, 紧
    assert "不在: 真 在: 假" in 紧, 紧


def test_B4_三宿主结论一致(tmp_path):
    出们 = {}
    for 引擎 in ("Rust", "Python", "Node"):
        出, 码 = _跑(_B4, tmp_path, 引擎=引擎)
        assert 码 == 0, f"{引擎}：{出[-400:]}"
        出们[引擎] = _紧(出)
    assert 出们["Rust"] == 出们["Python"] == 出们["Node"], 出们


#: 未命中 vs 获取 的**比值**上限。修好是 ~0.6；没修是 **408**。
#: 📌 用比值不用绝对时间：共享 runner 上的绝对耗时没有判别力（AGENTS §1）；
#:    比值在**同一个进程里交错取样、各取 min** 就抗得住负载。
_B4_性能 = """
导入 时间

令 大 = {}
遍历 i 在 范围(100000)：
    大[`键{i}`] = i

令 命中最 = 999.0
令 未命中最 = 999.0
令 获取最 = 999.0
遍历 轮 在 范围(3)：
    令 t0 = 时间.高精度时间()
    遍历 i 在 范围(2000)：
        如果 `键{i}` 在 大：
            令 写 = i
    令 a = 时间.高精度时间() - t0

    令 t1 = 时间.高精度时间()
    遍历 i 在 范围(2000)：
        如果 `没有{i}` 在 大：
            令 写 = i
    令 b = 时间.高精度时间() - t1

    令 t2 = 时间.高精度时间()
    遍历 i 在 范围(2000)：
        如果 大.获取(`没有{i}`, 空) != 空：
            令 写 = i
    令 c = 时间.高精度时间() - t2

    如果 a < 命中最：
        命中最 = a
    如果 b < 未命中最：
        未命中最 = b
    如果 c < 获取最：
        获取最 = c

打印(`比值 `, 未命中最 / 获取最)
"""


def test_B4_未命中不再线性扫(tmp_path):
    """🔴 这是本站的核心性能判据：10 万键上「未命中」不能退化成全表扫。

    修之前实测 **0.87 秒 / 2000 次**（= 0.44 ms 一次，且随字典规模线性增长），
    而 `字典.获取` 只要 0.0021 秒 —— **408 倍**。修完是 0.6 倍。
    阈值取 20 倍：离修好（0.6）有 30 倍余量，离没修（408）有 20 倍余量。
    """
    出, 码 = _跑(_B4_性能, tmp_path)
    assert 码 == 0, 出[-600:]
    行 = [x for x in 出.splitlines() if "比值" in x]
    assert 行, 出[-400:]
    比值 = float(行[-1].split("比值")[-1].strip())
    assert 比值 < 20, (
        f"字典「在」的未命中比「获取」慢 {比值:.0f} 倍（上限 20）—— "
        f"大概率是 `contains()` 又走回线性扫了")


