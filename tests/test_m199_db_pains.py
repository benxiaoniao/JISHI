def _造包(根: Path, 名: str = "甲包"):
    """在 `根/.jishi/packages/<名>/` 造一个最小可用的本地包。"""
    d = 根 / ".jishi" / "packages" / 名
    d.mkdir(parents=True, exist_ok=True)
    (d / "包.json").write_text(
        f'{{"名字": "{名}", "版本": "0.1.0"}}\n', encoding="utf-8", newline="\n")
    (d / f"{名}.jsh").write_text(_B2_包入口, encoding="utf-8", newline="\n")
    return d


