# ---------------------------------------------------------------------------
# E5 · 包内报错要指向**包里那个文件**（不是入口脚本 + 拼接行号）
# ---------------------------------------------------------------------------

#: 两个模块的包：`乙.jsh` 第 4 行会越界，`甲包.jsh` 第 2 行调用它。
#: 拼接后的全局行号分别是 4 → 7（入口脚本只有 4 行，第 7 行**根本不存在**）。
_E5_甲 = "函数 转交(值)：\n    返回 算(值)\n"
_E5_乙 = "# 乙.jsh —— 第 4 行故意越界\n函数 算(值)：\n    令 列 = [1, 2, 3]\n    返回 列[值]\n"
_E5_入口 = "导入 甲包 从 本地包\n\n打印(`开始`)\n打印(甲包.转交(9))\n"


def _造两级包(根: Path):
    _造包(根, "甲包")
    d = 根 / ".jishi" / "packages" / "甲包"
    (d / "甲包.jsh").write_text(_E5_甲, encoding="utf-8", newline="\n")
    (d / "乙.jsh").write_text(_E5_乙, encoding="utf-8", newline="\n")


def test_E5_包内报错指向包内文件的行(tmp_path):
    """🔴 清单里「伤害最大」的一条。

    修之前：`┌─ 入口.jsh:4:13`，调用链写「算 ← 第 7 行」。入口脚本只有 4 行，
    那个 7 是**两个模块拼接后的全局行号**，用户拿着它哪儿也找不到。
    """
    _造两级包(tmp_path)
    (tmp_path / "入口.jsh").write_text(_E5_入口, encoding="utf-8", newline="\n")
    出, 码 = _跑(_E5_入口, tmp_path, 名="入口.jsh")
    assert 码 != 0, 出[-400:]
    # ① 文件名要落在包里那个模块上
    assert "乙.jsh" in 出, f"报错没指向包里的文件：{出[-600:]}"
    assert "入口.jsh:4" not in 出, f"还标着入口脚本的行号：{出[-600:]}"
    # ② 行号是**文件内**的 4（不是拼接后的 7）
    assert ":4:13" in 出, f"行号不是文件内行号：{出[-600:]}"
    # ③ 源码行要真的是出问题那一行（不是入口脚本的第 4 行）
    assert "返回 列[值]" in 出, f"源码行取错了文件：{出[-600:]}"


def test_E5_调用链也是文件内行号(tmp_path):
    """调用链每一帧的「第 N 行」属于**调用者**那个文件。

    `算` 是被 `甲包.jsh` 第 2 行调的（拼接后是第 7 行）。
    """
    _造两级包(tmp_path)
    出, 码 = _跑(_E5_入口, tmp_path, 名="入口.jsh")
    assert 码 != 0
    assert "算 ← 第 2 行" in 出, f"调用链行号没换算：{出[-600:]}"
    assert "第 7 行" not in 出, f"还留着拼接行号：{出[-600:]}"


def test_E5_入口脚本自己的报错不受影响(tmp_path):
    """🔴 改动不能把「普通脚本」也带偏：入口里的错误照旧指入口。

    这条盯的是 `src_file` 的缺省值 —— 一旦写成「总是取某个包」，所有脚本
    报错的文件名都会变成包里的文件。
    """
    出, 码 = _跑("令 甲 = [1]\n打印(甲[9])\n", tmp_path, 名="普通.jsh")
    assert 码 != 0
    assert "普通.jsh:2" in 出, 出[-500:]
    assert "乙.jsh" not in 出 and "甲包" not in 出, 出[-500:]


