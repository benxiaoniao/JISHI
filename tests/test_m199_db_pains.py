def test_A5_且会点名逻辑运算符(tmp_path):
    """中文语感默认「与=且」，而报错原本是「这一行没写完」—— 指向别处。

    这条不要求「且」能用（那是加同义词，项目规矩是不造第二个名字），
    只要求**报错说人话**。
    """
    出, 码 = _跑('令 甲 = 真 且 假\n', tmp_path)
    assert 码 != 0
    assert "与" in 出 and "或" in 出 and "非" in 出, 出[-600:]


