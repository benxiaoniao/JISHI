# -*- coding: utf-8 -*-
"""M234 · 性能与余量：高基数 `容器.分组` · 多键排序选型 · 字典热路径调研。

## 这一站解决的是什么

M234 是「性能与余量」站，三件事的结论分别是：

| 事 | 结论 |
|---|---|
| **`容器.分组` 1 万行 3.2 秒** | 真有，但**只在「键基数高」时**：实现里每个元素都把**已有的全部键重新 `display()`** 一遍做等值比较（O(n²)）。1 万行 / 1 万种键实测 **3.04 秒**；50 种键只要 5 ms（M211 的复测就是 50 键，所以没看出来）。改成字典索引后 **9 ms** |
| **多键排序要不要加 API** | **不加**。`排序按(函数(r)：[甲, 乙])`（复合键列表 + 列表字典序比较）1 万行 9.7 ms，比 `排序按比较` 的 137 ms 快 14 倍 —— 已经是最优解，只是**用户不知道能这么写**，所以补进语言卡与文档 |
| **字典热路径余量** | 调研结论进 `docs/设计决策.md` D135（开放寻址 / shape 化**不落地**，理由在那边） |

## 顺手修掉的两个语义 bug（不只是慢）

原实现用 `display(键)` 的字符串当等价判定，而 `display` 对文本**不加引号**：

- `1` 与 `"1"` 的 display 都是 `1` ⇒ **整数键和文本键被错误合并成一组**（Python 里是两个键）；
- `真` 的 display 是 `真`、`1` 的是 `1` ⇒ **该合并的没合并**（Python 里 `True == 1`）。

现在用 `Dict` 当索引，键的等价规则与最终返回的字典**完全一致**，两个 bug 一起没了。

## 判据怎么验

- **计时只跑一个宿主**（Rust）—— 三个宿主快慢本来就不同，那不是语义不一致。
- **高基数那条打 `计时` 标记**（断言墙上时间，并行负载会抬高）；
  **多键排序那条用比值**（能抗负载），不打标记。
- **语义两组对拍**：与 Python 宿主逐字一致（含键序），且把上面两个 bug 单独钉死。
"""

from __future__ import annotations

import os
import subprocess
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from tests.conftest import rust_exe_path  # noqa: E402

RUST_EXE = rust_exe_path()
_需要引擎 = pytest.mark.skipif(not RUST_EXE.is_file(),
                              reason="没有 Rust 发行版（cargo build --release）")


def _跑(源: str, tmp: Path, 名: str) -> str:
    """只跑 Rust 宿主（性能计时的那个）。"""
    文件 = tmp / f"{名}-{os.getpid()}.jsh"
    文件.write_text(源, encoding="utf-8", newline="\n")
    r = subprocess.run([str(RUST_EXE), str(文件)], cwd=str(tmp),
                       capture_output=True, text=True, encoding="utf-8", timeout=300)
    assert r.returncode == 0, (r.stdout or "") + (r.stderr or "")
    return (r.stdout or "").replace("\r\n", "\n")


def _跑两宿主(源: str, tmp: Path, 名: str) -> tuple[str, str]:
    """Rust 与 Python 各跑一遍，返回两份 stdout（语义对拍用）。"""
    文件 = tmp / f"{名}-{os.getpid()}.jsh"
    文件.write_text(源, encoding="utf-8", newline="\n")
    r = subprocess.run([str(RUST_EXE), str(文件)], cwd=str(tmp),
                       capture_output=True, text=True, encoding="utf-8", timeout=300)
    assert r.returncode == 0, "Rust：" + (r.stdout or "") + (r.stderr or "")
    p = subprocess.run([sys.executable, "-m", "oracle.jishi.cli", str(文件)],
                       cwd=str(ROOT), capture_output=True, text=True,
                       encoding="utf-8", timeout=300)
    assert p.returncode == 0, "Python：" + (p.stdout or "") + (p.stderr or "")
    return ((r.stdout or "").replace("\r\n", "\n"),
            (p.stdout or "").replace("\r\n", "\n"))


# ---------------------------------------------------------------------------
# 一、`容器.分组` 的复杂度（这一站的起因）
# ---------------------------------------------------------------------------

@_需要引擎
@pytest.mark.计时
def test_高基数分组不是平方的(tmp_path):
    """1 万行、**1 万种键**的分组必须远低于 1 秒。

    🔴 这条才抓得住 2026-11 的那个真问题：原实现每来一个元素，都把**已有的全部键
    重新 `display()` 一遍**做等值比较 —— O(n²)。1 万行 / 1 万键实测 **3.04 秒**。

    ⚠️ 为什么 M211 的「1 万行分组」判据没抓到：它用的是 `i % 50`（**50 种键**），
    于是只有 50 次比较、全程 5 ms。⇒ **基数**是这类判据的关键变量，必须写死在高位。

    📌 打 `计时`：断言的墙上时间，并行负载会抬高（本机 9 ms，阈值给 300 ms 留余量）。
    """
    源 = '''导入 容器
导入 时间
导入 文本 为 文本库
令 行们 = []
遍历 i 在 范围(10000)：
    行们.追加({"编号": 文本(i), "金额": i})
令 起 = 时间.高精度时间()
令 组 = 容器.分组(行们, 函数(行)：行["编号"])
令 耗时 = (时间.高精度时间() - 起) * 1000
打印(长度(组))
打印(文本库.小数位(耗时, 1))
'''
    出 = _跑(源, tmp_path, "grp_wide").strip().splitlines()
    assert 出[0] == "10000", f"组数不对（键没归一？）：{出}"
    毫秒 = float(出[1])
    assert 毫秒 < 300, (
        f"1 万行 / 1 万种键的分组要 {毫秒} ms —— O(n²) 又回来了"
        f"（字典索引那条路被改掉了吗？）")


@_需要引擎
@pytest.mark.计时
def test_低基数分组也很快(tmp_path):
    """M211 复测的那个口径（50 种键）同样不许退步。"""
    源 = '''导入 容器
导入 时间
导入 文本 为 文本库
令 行们 = []
遍历 i 在 范围(10000)：
    行们.追加({"类别": i % 50, "金额": i})
令 起 = 时间.高精度时间()
令 组 = 容器.分组(行们, 函数(行)：行["类别"])
令 耗时 = (时间.高精度时间() - 起) * 1000
打印(长度(组))
打印(文本库.小数位(耗时, 1))
'''
    出 = _跑(源, tmp_path, "grp_narrow").strip().splitlines()
    assert 出[0] == "50", 出
    assert float(出[1]) < 300, f"低基数分组的 {出[1]} ms 也退步了"


# ---------------------------------------------------------------------------
# 二、`容器.分组` 的键等价（原来那两个 bug 的碑）
# ---------------------------------------------------------------------------

@_需要引擎
def test_分组的键等价跟字典一致(tmp_path):
    """下表就是「字典怎么认键，分组就怎么分」—— 原来按 `display` 拼串判等，两处都错。

    | 写法 | 字典口径（Python 同） | 旧实现（display） |
    |---|---|---|
    | `1` / `1.0` / `真` | **同一个键** | 三个键（`真` 的 display 是「真」） |
    | `1` / `"1"` | **两个键** | **一个键**（display 都是 `1`） |
    """
    源 = '''导入 容器

令 组 = 容器.分组([1, 1.0, 真, "1"], 函数(x)：x)
打印(长度(组))
遍历 键 在 组：
    打印(类型(键), 键, 长度(组[键]))
'''
    rust, py = _跑两宿主(源, tmp_path, "grp_key")
    assert rust == py, f"两宿主不一致：\nRust:\n{rust}\nPython:\n{py}"
    assert rust.strip().splitlines()[0] == "2", (
        f"应该只有 2 个键（数字侧一个、文本一个），实际：\n{rust}")


@_需要引擎
def test_分组的键序是首次出现顺序(tmp_path):
    """与 Python 的 dict 一致：分组结果的键按**第一次见到**的顺序排。"""
    源 = '''导入 容器
令 组 = 容器.分组(["乙", "甲", "丙", "甲", "乙"], 函数(x)：x)
遍历 键 在 组：
    打印(键, 长度(组[键]))
'''
    rust, py = _跑两宿主(源, tmp_path, "grp_order")
    assert rust == py, f"两宿主不一致：\nRust:\n{rust}\nPython:\n{py}"
    assert rust.splitlines() == ["乙 2", "甲 2", "丙 1"], rust


# ---------------------------------------------------------------------------
# 三、多键排序的选型（**不加 API** 的依据）
# ---------------------------------------------------------------------------

@_需要引擎
def test_复合键列表比比较函数快得多(tmp_path):
    """1 万行两键排序：`排序按(…[甲,乙])` 必须比 `排序按比较` 快（**比值**判据）。

    🔴 这条守的是「卡与文档里的推荐写法」：建议用户拼复合键列表，而不是写比较函数。
    用**比值**而不是绝对耗时 —— 共享 runner 的负载会把两边一起抬高，比值仍然稳。

    2026-11-26 本机实测：复合键 9.7 ms / 比较函数 137 ms（**14 倍**）。
    阈值取 3 倍（留足余量：只要求「明显更快」，不绑定具体机器）。
    """
    源 = '''导入 时间
导入 文本 为 文本库

函数 造行(行数)：
    令 出 = []
    令 i = 0
    当 i < 行数：
        出.追加({"甲": (i * 7919) % 101, "乙": (i * 104729) % 97})
        i = i + 1
    返回 出

函数 比两键(左, 右)：
    如果 左["甲"] != 右["甲"]：
        返回 左["甲"] - 右["甲"]
    返回 左["乙"] - 右["乙"]

令 行们 = 造行(10000)
令 起 = 时间.高精度时间()
令 一 = 行们.排序按(函数(r)：[r["甲"], r["乙"]])
令 键耗 = 时间.高精度时间() - 起
令 起2 = 时间.高精度时间()
令 二 = 行们.排序按比较(比两键)
令 比耗 = 时间.高精度时间() - 起2
打印(一[0]["甲"], 一[0]["乙"], 二[0]["甲"], 二[0]["乙"])
打印(文本库.小数位(键耗 * 1000, 2))
打印(文本库.小数位(比耗 * 1000, 2))
'''
    出 = _跑(源, tmp_path, "sort_two").strip().splitlines()
    # 两种写法必须给出**同一个顺序**（不然推荐就是错的）
    assert 出[0] == "0 0 0 0", f"两种写法结果不同：{出[0]}"
    键毫秒, 比毫秒 = float(出[1]), float(出[2])
    assert 比毫秒 > 键毫秒 * 3, (
        f"复合键 {键毫秒}ms / 比较函数 {比毫秒}ms —— 比值不再是「明显更快」了，"
        f"卡里的推荐写法该重新核一遍")
