# 二、W3 / W4 / W21：包内「非名字的赋值目标」里的名字要被捕获
# ---------------------------------------------------------------------------

_PKG = """配置 = {"x": 1}

类 状态:
    表 = {}

函数 设_下标(v):
    配置["x"] = v

函数 取_下标():
    返回 配置["x"]

函数 设_类属性(v):
    状态.表["k"] = v

函数 取_类属性():
    返回 状态.表["k"]

索引 = {}

函数 转键(x):
    返回 "k" + 文本(x)

函数 记(子):
    索引[转键(子["id"])] = 子

函数 读(id):
    返回 索引[转键(id)]["名"]
"""

_MAIN = """导入 丙 从 本地包 为 丙
丙.设_下标(5)
打印(丙.取_下标())
丙.设_类属性(7)
打印(丙.取_类属性())
丙.记({"id": 3, "名": "甲"})
打印(丙.读(3))
"""


def _写(p: Path, t: str) -> None:
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(t, encoding="utf-8", newline="\n")


def _造包工程(tmp: Path, 模块源码: str = _PKG, 主程序: str = _MAIN) -> Path:
    _写(tmp / ".jishi" / "packages" / "丙" / "包.json",
        json.dumps({"名字": "丙", "版本": "0.1.0", "依赖": {}}, ensure_ascii=False))
    _写(tmp / ".jishi" / "packages" / "丙" / "丙.jsh", 模块源码)
    _写(tmp / "run.jsh", 主程序)
    return tmp


def _跑两宿主(工程: Path) -> dict:
    """在工程根跑 Rust 与 Python 两个宿主；返回 `{名字: (退出码, stdout, stderr)}`。"""
    出 = {}
    if RUST.is_file():
        r = subprocess.run([str(RUST), "run.jsh"], cwd=str(工程), capture_output=True,
                           text=True, encoding="utf-8", errors="replace", timeout=180)
        出["rust"] = (r.returncode, (r.stdout or "").replace("\r\n", "\n"), r.stderr or "")
    环 = dict(os.environ, PYTHONPATH=str(ROOT))
    r = subprocess.run([sys.executable, "-m", "oracle.jishi.cli", "run.jsh"], cwd=str(工程),
                       capture_output=True, text=True, encoding="utf-8", errors="replace",
                       timeout=180, env=环)
    出["py"] = (r.returncode, (r.stdout or "").replace("\r\n", "\n"), r.stderr or "")
    return 出


def _断言一致(出: dict) -> str:
    基准 = None
    for 名, (码, 文, 错) in 出.items():
        assert 码 == 0, f"[{名}] 本该正常退出：{错[:400] or 文[:400]}"
        if 基准 is None:
            基准 = 文
        else:
            assert 文 == 基准, f"[{名}] 与基准不一致：\n基准={基准!r}\n{名}={文!r}"
    assert 基准 is not None
    return 基准


def test_包内改模块字典_两宿主一致(tmp_path):
    """`配置["x"] = v`：函数第一次出现就是**下标写**，仍要捕获到模块级 `配置`。

    这是 `营造框架` 里最坑的一条 —— 他们的绕行是 `令 d = 配置 / d[k] = v`。
    """
    出 = _跑两宿主(_造包工程(tmp_path / "w3"))
    assert _断言一致(出) == "5\n7\n甲\n"


def test_包内改类属性_两宿主一致(tmp_path):
    """`状态.表["k"] = v`：赋值目标是**属性套下标**，中间的类名也要被捕获。"""
    源 = """类 状态:
    表 = {}

函数 设(v):
    状态.表["k"] = v

函数 取():
    返回 状态.表["k"]
"""
    主 = """导入 丙 从 本地包 为 丙
丙.设(9)
打印(丙.取())
"""
    出 = _跑两宿主(_造包工程(tmp_path / "w4", 源, 主))
    assert _断言一致(出) == "9\n"


def test_包内下标表达式调兄弟函数_两宿主一致(tmp_path):
    """`索引[转键(id)] = 子`：**下标表达式里**的兄弟函数名同样要被捕获（W21）。

    他们的记录里这条「偶发」——本判据钉住：不是偶发，是稳定可复现。
    """
    出 = _跑两宿主(_造包工程(tmp_path / "w21"))
    assert _断言一致(出) == "5\n7\n甲\n"


def test_真未定义的名字仍然报错(tmp_path):
    """修复不能把「真没定义」也放过 —— 必须仍报 E0301（两宿主都报）。"""
    源 = """函数 炸():
    未定义的名字["x"] = 1
"""
    主 = """导入 丙 从 本地包 为 丙
丙.炸()
"""
    出 = _跑两宿主(_造包工程(tmp_path / "undef", 源, 主))
    for 名, (码, 文, 错) in 出.items():
        assert 码 != 0, f"[{名}] 本该报错，却成功退出：{文!r}"
        assert "E0301" in 错 or "找不到名字" in 错, f"[{名}] 报错不对：{错[:300]}"


