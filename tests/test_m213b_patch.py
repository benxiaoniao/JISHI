def test_函数值相等按身份_五引擎一致():
    """同一个函数给「真」、两个分开定义的给「假」、内建比自己给「真」。

    ⚠️ 这里的三个值都要对：只把 `Func == Func` 写成恒真会让 `f == g` 也变真，
    那比原来更糟（原来至少是恒假）。**只比同一性**，不比名字。
    """
    源 = """函数 f():
    返回 1
函数 g():
    返回 1
令 d = {"fn": f}
打印(d["fn"] == f)
打印(f == g)
打印(长度 == 长度)
打印(类型(f) == 类型(g))
"""
    assert _five_agree(源) == "真\n假\n真\n真\n"


def test_类值相等按身份_五引擎一致():
    """两个类不相等、同一个类相等（Python 的类对象也是身份比较）。"""
    源 = """类 甲:
    值 = 1
类 乙:
    值 = 1
令 d = {"类": 甲}
打印(d["类"] == 甲)
打印(甲 == 乙)
"""
    assert _five_agree(源) == "真\n假\n"


