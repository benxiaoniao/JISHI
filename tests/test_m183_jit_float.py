@需要jit
def test_nan的比较全部正确():
    """`nan != nan` 为**真**；`nan < x` / `nan == x` 为**假**。

    这条是浮点 JIT 最容易写错的地方：`ucomisd` 在无序时 ZF=PF=CF=1，
    直接 `sete` / `setb` 会把 NaN 当成「相等」「小于」。
    """
    源 = """
函数 主(n)：
    令 i = 0
    令 无穷 = 1e308 * 10.0
    令 甲 = 无穷 - 无穷
    令 分 = 0
    当 i < n：
        如果 甲 == 甲：
            分 = 分 + 1000
        如果 甲 != 甲：
            分 = 分 + 100
        如果 甲 < 0.0：
            分 = 分 + 10
        如果 甲 <= 0.0：
            分 = 分 + 20
        如果 甲 > 0.0：
            分 = 分 + 30
        如果 甲 >= 0.0：
            分 = 分 + 40
        i = i + 1
    返回 分
打印(主(200000))
"""
    码1, 出1, _ = _跑(源)
    码2, 出2, _ = _跑(源, 开=False)
    assert 码1 == 码2 == 0
    assert 出1 == 出2, f"JIT[{出1}] vs 解释[{出2}]"
    # nan 只会命中「!=」那一条：200000 × 100
    assert 出1.strip() == "20000000", 出1
    _, _, 错 = _跑(源, 调试=True)
    assert "编好了" in 错, 错[-600:]


