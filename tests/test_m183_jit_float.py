# -*- coding: utf-8 -*-
"""M183：JIT v2 —— 浮点（SSE2 标量）。

## 这一组守的是什么

浮点最坑的地方不是「算错」，而是**看起来对**：

| 坑 | 不编对的样子 |
|---|---|
| `nan != nan` | `ucomisd` 在无序时置 `PF=1`，`setne` 会当成「相等」⇒ 给**假**（应当是真） |
| `nan < 1.0` | `setb` 在无序时也成立 ⇒ 给**真**（应当是假） |
| `-0.0` | `0.0 == -0.0` 必须成立；打印出来是 `-0.0` |
| `1.0 / 0.0` | 基石**报 `E2001`**，不是 `inf`（`divsd` 会安安静静给 `inf`） |
| 混合提升 | `1 + 2.5` / `2.5 + 1` / `1 * 2.5` 三种顺序都要对 |

所以每条都是「开 JIT / 关 JIT **逐字节**比」，而不是「数值差不多」。

⚠️ 与 M182 一样：**编不出来时解释器也会给对结果**，所以另有一组
「真的编了」的判据，否则 JIT 整个坏掉也全绿。
"""

import hashlib
import os
import platform
import re
import subprocess
import tempfile
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
EXE = ROOT / "rust" / "target" / "release" / ("jishi-rs.exe" if os.name == "nt" else "jishi-rs")

# 🔴 **M184 起 JIT 有两个后端**（x86-64 / ARM64）⇒ 判据在两种架构上都要真跑。
# CI 的 `macos-latest` 是 arm64 —— 那边跑的是**真的 ARM 机器码**，
# 这是「ARM 后端到底对不对」唯一的一锤定音（本机 x86-64 只能验编码）。
是已知架构 = platform.machine().lower() in ("amd64", "x86_64", "arm64", "aarch64")
需要jit = pytest.mark.skipif(
    not 是已知架构 or not EXE.is_file(),
    reason="JIT 只在 x86-64 / ARM64 上（先在目标机上 cargo build --release）",
)


def _跑(源码: str, 开=True, 调试=False, 超时=180):
    路径 = str(
        Path(tempfile.gettempdir())
        / f"jishi_m183_{hashlib.md5(源码.encode('utf-8')).hexdigest()[:12]}.jsh"
    )
    Path(路径).write_text(源码, encoding="utf-8", newline="\n")
    env = dict(os.environ)
    if not 开:
        env["JISHI_JIT"] = "0"
    elif 调试:
        env["JISHI_JIT"] = "调试"
    try:
        r = subprocess.run([str(EXE), 路径], capture_output=True, env=env,
                           timeout=超时, cwd=str(ROOT))
    except subprocess.TimeoutExpired:
        pytest.fail(f"跑超时（{超时} 秒）—— 生成的机器码很可能跳错地方了")
    return (r.returncode,
            r.stdout.decode("utf-8", "replace"),
            r.stderr.decode("utf-8", "replace"))


