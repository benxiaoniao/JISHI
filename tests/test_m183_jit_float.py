@需要jit
def test_精确小数不进JIT_守卫拦住():
    """`精确(0.5)` 造出来的是 `Val::Dec`（精确小数），不在 JIT 的类型里。

    编译期只看得到「这个槽当前是什么类型」（`Dec` 不在 {整数, 浮点} 里），
    所以它会先按整数编出来，**再由守卫按实际类型拒掉** —— 结果是解释器跑，
    一个字节都不许按 f64 解释。这条守的就是那道守卫。
    """
    源 = """
函数 主(n)：
    令 i = 0
    令 s = 精确(0.5)
    当 i < n：
        s = s + 1
        i = i + 1
    返回 s
打印(主(200000))
"""
    码1, 出1, _ = _跑(源)
    码2, 出2, _ = _跑(源, 开=False)
    assert 码1 == 码2 == 0 and 出1 == 出2, f"JIT[{出1}] vs 解释[{出2}]"
    _, _, 错 = _跑(源, 调试=True)
    assert "精确小数" in 错 and "不符" in 错, (
        f"守卫没把「精确小数」挡住（那会被当成整数算）：{错[-600:]}")


