@需要jit
def test_同一段代码先浮点后整数_不编错():
    """同一个函数先拿浮点跑（编成浮点版），再拿整数跑 —— 守卫必须拦住。

    拦不住就会把 `Val::Int` 当成 f64 的位模式去算，结果是**一个莫名其妙的数**。
    """
    源 = """
函数 累(n, 起)：
    令 i = 0
    令 s = 起
    当 i < n：
        s = s + 1
        i = i + 1
    返回 s
打印(累(200000, 0.5))
打印(累(200000, 0))
打印(累(200000, 0.5))
"""
    码1, 出1, _ = _跑(源)
    码2, 出2, _ = _跑(源, 开=False)
    assert 码1 == 码2 == 0
    assert 出1 == 出2, f"JIT[{出1}] vs 解释[{出2}]"
    assert 出1.splitlines()[0].endswith("200000.5"), 出1
    assert 出1.splitlines()[1].strip() == "200000", 出1
