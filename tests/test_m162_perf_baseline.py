# -*- coding: utf-8 -*-
"""M162 · 性能基线：让「变快/变慢」变成**判据**，而不是印象。

## 这个文件存在的理由

0.2.x 的性能一直只有「基石自己四个引擎之间」的对比，从来没有一条 vs CPython 的线 ——
于是「这里好像比 Python 慢」只能靠感觉，改完也没法说「到底快了没有」。
0.3.0 要做的三站性能优化（M163 调用扁平化 / M164 容器文本 / M165 数字字典）
全都得靠这条线判断有没有做对。

## 为什么判据是「**不许比基线差**」而不是「必须 ≥1.0」

2026-11-01 的实测是 **0.94x**（10 个场景还比 CPython 慢）。此刻若把「≥1.0」写成硬判据，
它第一天就是红的 —— 而红的判据只有两个下场：被忽略，或者被删掉。
所以这里分两层：

| 层 | 判据 | 状态 |
|---|---|---|
| **不退化** | 每个场景、几何平均都**不许比基线差 20% 以上** | 现在就绿，改坏了立刻红 |
| **达标** | 几何平均 ≥ 1.0（0.3.0 收口线） | 见 `docs/路线图-0.3.x.md` M169；**M163–M165 做完后收紧** |

📌 **换机器怎么办**：基线里存了机器指纹。对不上就 `skip` ——
「这台机器上的数」和「那台机器上的数」放一起比没有意义（M114 的教训：
报可复现的那一档，别把冷热缓存/硬件差异混进来）。

## 为什么打 `计时`

基准跑一轮 40~60 秒，且**断言的是墙上时间**——并行负载会把它抬高成假红。
按 AGENTS §1.3 的规矩进串行节（`tools/test_all.py` 的第 2 节），CI 只跑 `not 计时`。
"""

import json
import platform
import subprocess
import sys
from pathlib import Path

import pytest

sys.path.insert(0, ".")

from conftest import ROOT                                            # noqa: E402

基线路径 = ROOT / "bench" / "baseline_cpython.json"
#: 允许的退化幅度（**几何平均**上）。
#:
#: 🔴 15% 这个数是被实测逼出来的。两个阶段的数据：
#:
#: - **动态算重复次数时**（M162 的第一版）：同一台机器、同一份代码连跑三次，
#:   几何平均是 **0.94 / 0.95 / 1.06** —— 差 11%。根因不是机器忙，而是
#:   每轮都按当时的负载重新算「重复几次」，于是**两次跑的根本不是同一道题**。
#: - **固定成基线里的重复次数后**：**1.07 / 1.06**（<1%）。
#:
#: ⇒ 所以 `_跑基准` 一律带 `--用基线`；容差留 15% 是给「机器状态不同」的余量，
#: 不是给「方法不稳」的遮羞布。
容差 = 0.15
#: 单个场景的容差放得更宽（**只作记录，不作硬判**）：
#: 小场景的噪声能到 2~3 倍（递归斐波那契实测 0.32~0.97），逐条硬判没有判别力。
单场景容差 = 0.50


def _读基线() -> dict:
    return json.loads(基线路径.read_text(encoding="utf-8"))


def _跑基准(轮数: int = 2) -> dict:
    """跑一遍基准，返回它写出的快照（不落盘到基线文件，避免测试改基线）。

    🔴 一律带上 `--用基线`：让这一轮跑的是**与基线同样规模**的程序。
    不带的话每轮会按当时机器负载重新算「重复几次」，两次跑的根本不是同一道题
    （实测同一台机器、同一份代码，动态算出来的规模能让倍数差 3 倍）。
    """
    import tempfile
    出 = Path(tempfile.mkdtemp(prefix=f"m162bench_{__import__('os').getpid()}_"))
    目标 = 出 / "结果.json"
    命令 = [sys.executable, str(ROOT / "tools" / "bench_vs_python.py"),
            "--轮数", str(轮数), "--json", str(目标)]
    if 基线路径.exists():
        命令 += ["--用基线", str(基线路径)]
    r = subprocess.run(命令, cwd=str(ROOT), capture_output=True,
                       timeout=900, input=b"")
    assert 目标.exists(), (
        "基准没写出结果：\n"
        + (r.stdout + r.stderr).decode("utf-8", "replace")[-800:])
    return json.loads(目标.read_text(encoding="utf-8"))


@pytest.mark.计时
def test_基准机制自检_两份实现必须等价():
    """先确认「比的是同一件事」：17 个场景的输出必须逐字相同。

    这条不判快慢，只判**可比性** —— 一旦某个场景的基石版和 Python 版算出不同结果，
    后面的倍数全部作废（那是在比两段不同的程序）。
    """
    快照 = _跑基准(轮数=1)
    不等价 = [r["名字"] for r in 快照["场景"] if r.get("不等价")]
    assert 不等价 == [], f"这些场景两份实现输出不同，倍数无意义：{不等价}"
    assert len(快照["场景"]) >= 15, f"场景少得可疑：{len(快照['场景'])} 个"


@pytest.mark.计时
def test_不许比基线退化():
    """三条判据，从硬到软：

    1. **几何平均**不许比基线差 15%（聚合量，噪声已被 17 个场景摊平）；
    2. **「比 CPython 慢」的场景数**不许比基线多 2 个以上（这条防「整体还行、
       但某几项塌了」）；
    3. 单个场景只作**记录**，差一半才报 —— 小场景噪声能到 2~3 倍，逐条硬判没有判别力。

    ⚠️ 这条**不是**验收目标，是「别把已经做到的弄回去」。目标线 ≥1.0 见路线图 M169。
    """
    基线 = _读基线()
    现在 = _跑基准(轮数=3)

    # 换机器就不比：两边机器指纹对不上时，差多少都不说明问题
    这一台 = 现在["机器"]
    那一台 = 基线["机器"]
    if 这一台["平台"] != 那一台["平台"] or 这一台["处理器"] != 那一台["处理器"]:
        pytest.skip(
            f"基线是在别的机器上录的（{那一台['平台']} / {那一台['处理器']}），"
            f"这台是 {这一台['平台']} / {这一台['处理器']} —— 换机器请重录基线："
            "python tools/bench_vs_python.py --json bench/baseline_cpython.json")

    # ① 几何平均（主判据）
    老几何, 新几何 = 基线["几何平均"], 现在["几何平均"]
    assert 新几何 >= 老几何 * (1 - 容差), (
        f"几何平均从 {老几何:.2f}x 掉到 {新几何:.2f}x（超过 {容差:.0%} 容差）。"
        "若是机器变忙先排除干扰再重跑；确认是回归就查这次改了什么")

    # ② 慢场景数（防「平均还行、某几项塌了」）
    老慢 = len([r for r in 基线["场景"] if r.get("倍数") and r["倍数"] < 1])
    新慢 = len([r for r in 现在["场景"] if r.get("倍数") and r["倍数"] < 1])
    assert 新慢 <= 老慢 + 2, (
        f"比 CPython 慢的场景从 {老慢} 个涨到 {新慢} 个"
        f"（现在是：{[r['名字'] for r in 现在['场景'] if r.get('倍数') and r['倍数'] < 1]}）")

    # ③ 单场景只作记录（差一半才报）
    基线表 = {r["名字"]: r["倍数"] for r in 基线["场景"] if r.get("倍数")}
    现在表 = {r["名字"]: r["倍数"] for r in 现在["场景"] if r.get("倍数")}
    塌了 = [f"{名}：{老:.2f}x → {现在表[名]:.2f}x"
            for 名, 老 in 基线表.items()
            if 名 in 现在表 and 现在表[名] < 老 * (1 - 单场景容差)]
    assert 塌了 == [], (
        "这些场景比基线慢了一半以上（已超出噪声范围）：\n  " + "\n  ".join(塌了))


def test_基线文件长什么样():
    """基线不是随手一个数字：机器指纹、时间、启动成本、逐场景都要有。"""
    基线 = _读基线()
    assert 基线["格式"] == "jishi-bench-vs-cpython"
    assert 基线["机器"]["平台"], "没记平台 —— 换机器就没法判断了"
    assert 基线["机器"]["jishi"], "没记基石版本"
    assert 基线["启动ms"]["基石"] > 0 and 基线["启动ms"]["cpython"] > 0
    有倍数 = [r for r in 基线["场景"] if r.get("倍数")]
    assert len(有倍数) >= 15, f"基线里有效场景太少：{len(有倍数)}"
    assert 基线["几何平均"] and 基线["几何平均"] > 0
