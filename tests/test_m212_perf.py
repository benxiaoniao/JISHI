def _跑(源: str, tmp: Path, 名: str) -> str:
    """跑一段脚本（有 Rust 用 Rust，否则 Python），返回 stdout。"""
    文件 = tmp / f"{名}-{os.getpid()}.jsh"
    文件.write_text(源, encoding="utf-8", newline="\n")
    if RUST_EXE.is_file():
        r = subprocess.run([str(RUST_EXE), str(文件)], capture_output=True,
                           text=True, encoding="utf-8", timeout=600)
    else:
        r = subprocess.run([sys.executable, "-m", "oracle.jishi.cli", str(文件)],
                           capture_output=True, text=True, encoding="utf-8",
                           timeout=600, cwd=str(ROOT))
    assert r.returncode == 0, (r.stdout or "") + (r.stderr or "")
    return (r.stdout or "").replace("\r\n", "\n")


def _跑三边(源: str, tmp: Path, 名: str) -> dict:
    """三宿主各跑一遍，返回 `{名: (码, stdout, stderr)}`（语义一致性用）。"""
    文件 = tmp / f"{名}-{os.getpid()}.jsh"
    文件.write_text(源, encoding="utf-8", newline="\n")

    def _收(r):
        return (r.returncode, (r.stdout or "").replace("\r\n", "\n"),
                (r.stderr or "").replace("\r\n", "\n"))

    出: dict = {"rs": None, "py": None, "js": None}
    if RUST_EXE.is_file():
        出["rs"] = _收(subprocess.run([str(RUST_EXE), str(文件)], capture_output=True,
                                     text=True, encoding="utf-8", timeout=600))
    出["py"] = _收(subprocess.run([sys.executable, "-m", "oracle.jishi.cli", str(文件)],
                                  capture_output=True, text=True, encoding="utf-8",
                                  timeout=600, cwd=str(ROOT)))
    return 出


