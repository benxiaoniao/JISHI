from oracle.jishi.errors import JishiError            # noqa: E402
from oracle.jishi.interpreter import run_source       # noqa: E402


def _跑(源码: str, tmp: Path) -> str:
    """在 tmp 里跑一段基石源码，返回 stdout（出错就抛 JishiError）。"""
    buf = io.StringIO()
    cwd = os.getcwd()
    os.chdir(tmp)
    try:
        with redirect_stdout(buf):
            run_source(源码, filename="测.jsh")
    finally:
        os.chdir(cwd)
    return buf.getvalue()


def _错(源码: str, tmp: Path) -> JishiError:
    with pytest.raises(JishiError) as ei:
        _跑(源码, tmp)
    return ei.value


