def test_语言卡里有数据库的十五个函数():
    """`--lang-spec` 是从 Python 源码扫出来的 —— 漏一个函数这条就红。"""
    r = subprocess.run([sys.executable, "-m", "oracle.jishi.cli", "--lang-spec"],
                       cwd=ROOT, capture_output=True)
    spec = json.loads(r.stdout.decode("utf-8"))
    模块 = {m["module"]: m for m in spec["stdlib"]}
    assert "数据库" in 模块, "语言卡里没有 `数据库` 模块"
    got = {f["name"] for f in 模块["数据库"]["functions"]}
    assert got == {
        "打开", "关闭", "表们", "有表", "建表", "建索引",
        "插入", "批量插入", "查询", "条数", "汇总",
        "修改", "删除", "执行", "执行查询",
    }, got
    # 每个函数都要有说明（第一行进语言卡 —— 模型靠它知道怎么用）
    for f in 模块["数据库"]["functions"]:
        assert f.get("doc"), f"「{f['name']}」没有写明用途"


