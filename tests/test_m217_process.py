# -*- coding: utf-8 -*-
"""M217 · `进程` 模块：子进程**句柄**（交互式：边写边读、stderr 分流、超时、终止）。

## 这一站补的是什么

`系统.执行` 是「跑完拿输出」。有一类活它干不了：交互式子进程（REPL、ffmpeg 进度、
ssh 会话）、要边喂边读的（不然管道一满两边互锁）、stderr 要实时看的。

## 判据为什么这么写

| # | 判据 | 抓的是 |
|---|---|---|
| ① | 回声：写一行、读回一行 | 基本的读写回路（**不是**「起得来就算」） |
| ② | `读行(超时=0.2)` 没输出时按时返回 | 超时真的生效，不是「等到有数据」 |
| ③ | `终止` 后 `在运行` 假、`退出码` 非空 | 句柄状态跟着子进程走，不是缓存 |
| ④ | stdout / stderr **分流** | 两条管道没被合成一条（合成的话两边的行会串味） |
| ⑤ | **孙进程不拖住我们** | O-2 坑3：孙进程继承 stdout ⇒ 管道永不 EOF，「读到 EOF 才返回」会让 0.2 秒变 8.4 秒 |
| ⑥ | 起不来的程序报 `运行期错误` | 错误可操作（带命令名），不是挂住或静默 |
| ⑦ | `合并错误=真` 时 stderr 进 stdout | 选项真的生效 |
| ⑧ | 三宿主的 `类型` / 显示 / 退出码口径一致 | 宿主对象不能各说各话 |

🔴 每条都在 **Rust / Python** 两个宿主上跑（`_跑三边`）。`进程` 是新模块，
「某个宿主少实现一半」正是这类模块最典型的翻车方式。
"""

from __future__ import annotations

import os
import shutil
import subprocess
import sys
from pathlib import Path

import pytest

sys.path.insert(0, ".")

from conftest import ROOT, rust_exe_path  # noqa: E402

RUST_EXE = rust_exe_path()
PY = sys.executable.replace("\\", "/")

#: 回声子进程：读一行回一行；收到「错」就写 stderr；收到「退」就退出（码 3）
回声脚本 = '''import sys
for line in sys.stdin:
    line = line.rstrip("\\n")
    if line == "错":
        sys.stderr.write("错误一行\\n")
        sys.stderr.flush()
        continue
    if line == "退":
        sys.exit(3)
    sys.stdout.write("回:" + line + "\\n")
    sys.stdout.flush()
'''

#: 只往 stderr 写一行（`合并错误=真` 时它该出现在 stdout 那条管道里）
合并脚本 = '''import sys
sys.stderr.write("到 stdout 了\\n")
sys.stderr.flush()
'''

#: 孙进程：起一个继承 stdout 的孙进程（睡 20 秒）然后自己退出
孙进程脚本 = '''import subprocess, sys
subprocess.Popen([sys.executable, "-c", "import time; time.sleep(20)"])
print("主进程结束", flush=True)
'''


def _跑(源: str, tmp: Path, 名: str) -> str:
    """Rust 宿主跑一遍。"""
    文件 = tmp / f"{名}-{os.getpid()}.jsh"
    文件.write_text(源, encoding="utf-8", newline="\n")
    assert RUST_EXE.is_file(), "这条判据要 Rust 宿主（发行版走的就是它）"
    r = subprocess.run([str(RUST_EXE), str(文件)], capture_output=True,
                       text=True, encoding="utf-8", timeout=180)
    assert r.returncode == 0, (r.stdout or "") + (r.stderr or "")
    return (r.stdout or "").replace("\r\n", "\n")


def _跑宿主(源: str, tmp: Path, 名: str) -> dict:
    """Rust / Python 两个宿主各跑一遍 → `{宿主: stdout}`。

    只返回 stdout；某个宿主跑挂了直接失败（`进程` 模块不许「某个宿主没有」）。
    """
    文件 = tmp / f"{名}-{os.getpid()}.jsh"
    文件.write_text(源, encoding="utf-8", newline="\n")
    出: dict = {}

    r = subprocess.run([str(RUST_EXE), str(文件)], capture_output=True,
                       text=True, encoding="utf-8", timeout=180)
    assert r.returncode == 0, ("rust", r.stdout, r.stderr)
    出["rust"] = (r.stdout or "").replace("\r\n", "\n")

    r = subprocess.run([sys.executable, "-m", "oracle.jishi.cli", str(文件)],
                       capture_output=True, text=True, encoding="utf-8",
                       timeout=180, cwd=str(ROOT))
    assert r.returncode == 0, ("python", r.stdout, r.stderr)
    出["python"] = (r.stdout or "").replace("\r\n", "\n")

    return 出


def _去时序(文本: str) -> list[str]:
    """去掉**墙上时间**的几行再比 —— 那些数只用来判上界，不可能逐字节相同。"""
    return [行 for 行 in 文本.strip().splitlines()
            if not (行.startswith("用时") or 行.startswith("超时用时"))]


def _写子脚本(tmp: Path, 名: str, 内容: str) -> str:
    p = tmp / f"{名}-{os.getpid()}.py"
    p.write_text(内容, encoding="utf-8", newline="\n")
    return str(p).replace("\\", "/")


