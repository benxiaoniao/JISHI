_边角 = '''导入 进程
导入 文本 为 文本库

尝试：
    进程.启动("肯定没有这个程序_zzz", [])
    打印("没报错")
捕获 异常 为 e：
    打印("起不来", e.类型)

# ⑦ 合并错误=真 ⇒ stderr 进 stdout 那条管道
令 子 = 进程.启动("__PY__", ["-u", "__合并__"], {"合并错误": 真})
打印("合并读到", 进程.读行(子, 5))
打印("合并错管道", 进程.读错误行(子, 0.2))
打印("等待", 进程.等待(子, 5))

# 子进程自己退出后：在运行 假、退出码 是它给的码
令 子2 = 进程.启动("__PY__", ["-u", "-c", "import sys; sys.exit(7)"])
打印("等码", 进程.等待(子2, 5))
打印("已退出", 进程.在运行(子2), 进程.退出码(子2))

# 写进一个已经退出的子进程：给一句可操作的错，不是静默
尝试：
    进程.写行(子2, "还在吗")
    打印("写没报错")
捕获 异常 为 e：
    打印("写已关", e.类型)
'''


def test_起不来与合并错误与退出码(tmp_path):
    """⑥ 起不来报 `运行期错误`；⑦ `合并错误` 真的合并；退出码跟着子进程走。"""
    合并 = _写子脚本(tmp_path, "merged", 合并脚本)
    源 = _边角.replace("__PY__", PY).replace("__合并__", 合并)
    出 = _跑宿主(源, tmp_path, "edge")
    行 = 出["rust"].strip().splitlines()
    assert 行[0] == "起不来 运行期错误", 行
    assert 行[1] == "合并读到 到 stdout 了", 行
    assert 行[2] == "合并错管道 空", 行
    assert 行[3] == "等待 0", 行
    assert 行[4] == "等码 7", 行
    assert 行[5] == "已退出 假 7", 行
    assert 行[6] == "写已关 运行期错误", 行
    assert _去时序(出["python"]) == _去时序(出["rust"]), ("python", _去时序(出["python"])[:3], 行[:3])


