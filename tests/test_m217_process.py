_主流程 = '''导入 进程
导入 时间
导入 文本 为 文本库

# ⚠️ 基石没有函数提升：辅助函数要在**用之前**定义
函数 在运行文本(值)：
    返回 "真" 如果 值 否则 "假"

令 起 = 时间.高精度时间()
令 子 = 进程.启动("__PY__", ["-u", "__回声__"])
打印("类型", 类型(子), 在运行文本(进程.在运行(子)))
打印("写", 进程.写行(子, "你好"))
打印("读", 进程.读行(子, 5))

# ④ stderr 走另一条管道
进程.写行(子, "错")
打印("错行", 进程.读错误行(子, 5))
# 分流：stderr 里有东西时，stdout 那条**没有**对应的行
打印("错时分流", 进程.读行(子, 0.2))

# ② 超时：没有输出时按时返回（不是等到有数据才回）
令 起超 = 时间.高精度时间()
打印("超时读", 进程.读行(子, 0.2))
令 超时用时 = 时间.高精度时间() - 起超
打印("超时用时", 文本库.小数位(超时用时, 1))
进程.写行(子, "再见")
打印("再读", 进程.读行(子, 5))

# ③ 终止
打印("终止前", 进程.在运行(子))
打印("终止", 进程.终止(子))
打印("终止后", 进程.在运行(子))
令 码 = 进程.退出码(子)
打印("退出码非空", 码 != 空, 码)
打印("再终止", 进程.终止(子))
'''


def test_回声_分流_超时_终止三宿主一致(tmp_path):
    """① + ② + ③ + ④：一条脚本把四件事走完，三宿主的 stdout **逐字节相同**。"""
    回声 = _写子脚本(tmp_path, "echo", 回声脚本)
    源 = _主流程.replace("__PY__", PY).replace("__回声__", 回声)
    出 = _跑宿主(源, tmp_path, "main")
    行 = 出["rust"].strip().splitlines()
    assert 行[0] == "类型 进程 真", 行
    assert 行[1] == "写 真", 行
    assert 行[2] == "读 回:你好", 行
    assert 行[3] == "错行 错误一行", 行
    assert 行[4] == "错时分流 空", 行       # ④：stderr 没有漏进 stdout
    assert 行[5] == "超时读 空", 行          # ②：没输出 ⇒ 空
    assert float(行[6].split()[1]) < 3, 行   # ②：而且是**按时**返回的
    assert 行[7] == "再读 回:再见", 行
    assert 行[8] == "终止前 真", 行
    assert 行[9] == "终止 真", 行
    assert 行[10] == "终止后 假", 行         # ③
    assert 行[11].startswith("退出码非空 真"), 行
    assert 行[12] == "再终止 假", 行         # 幂等
    # 两宿主逐字节一致
    assert _去时序(出["python"]) == _去时序(出["rust"]), ("python 与 rust 不一致",
                                                          _去时序(出["python"])[:3], _去时序(出["rust"])[:3])


