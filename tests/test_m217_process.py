_锁源 = '''导入 数据库
导入 路径
导入 文件
导入 时间
导入 json
导入 进程
导入 系统
导入 文本 为 文本库

令 p = 路径.连接(路径.临时目录(), "m217lock_" + 文本(时间.时间戳()) + "_" + 文本(时间.高精度时间()) + ".db")
令 库 = 数据库.打开(p)
数据库.建表(库, "账", ["名"])
数据库.插入(库, "账", {"名": "甲"})
数据库.关闭(库)
打印("关掉后锁在吗", 文件.文件存在(p + ".lock"))

# ① 属主进程已经没了（号是假的）⇒ 锁该被**自动回收**
文件.写文本(p + ".lock", json.转文本({"属主": "旧的", "进程号": 999999, "主机名": 系统.主机名(), "打开时间": "昨天"}))
令 库2 = 数据库.打开(p)
打印("回收后能开", 数据库.条数(库2, "账"))
数据库.关闭(库2)

# ② 属主还活着（就是我自己）⇒ 必须拒绝
文件.写文本(p + ".lock", json.转文本({"属主": "别人", "进程号": 进程.进程号(), "主机名": 系统.主机名()}))
尝试：
    数据库.打开(p)
    打印("没报错")
捕获 异常 为 e：
    打印("活锁拒绝", e.类型)

# ③ 老格式（没记进程号）⇒ 不敢判断，照旧拒绝
文件.写文本(p + ".lock", json.转文本({"属主": "老", "打开时间": "昨天"}))
尝试：
    数据库.打开(p)
    打印("没报错")
捕获 异常 为 e：
    打印("老锁拒绝", e.类型)

# ④ 锁文件坏了（不是 JSON）⇒ 也是拒绝，不许崩
文件.写文本(p + ".lock", "这不是 JSON")
尝试：
    数据库.打开(p)
    打印("没报错")
捕获 异常 为 e：
    打印("坏锁拒绝", e.类型)

文件.删除文件(p + ".lock")
文件.删除文件(p)
文件.删除文件(p + ".log")
'''


def test_陈旧锁自动回收_活锁仍然拒绝(tmp_path):
    """W13：强杀之后 `.lock` 残留 ⇒ **下次打开自动回收**，不用用户手删。

    四条口径（三宿主逐字一致）：
    ① 属主进程号已不存在（同机）⇒ 回收，库能开；
    ② 属主还活着 ⇒ 拒绝（**这条最重要**：把活的判成死的 = 两个进程写一个库）；
    ③ 老格式没记进程号 ⇒ 保守拒绝；
    ④ 锁文件坏了 ⇒ 拒绝，不许崩。

    📌 「本机能判、跨机不判」：锁里记了主机名，共享盘上别的机器的锁**一律不回收**。
    """
    出 = _跑宿主(_锁源, tmp_path, "lock")
    行 = 出["rust"].strip().splitlines()
    assert 行[0] == "关掉后锁在吗 假", 行
    assert 行[1] == "回收后能开 1", 行
    assert 行[2] == "活锁拒绝 运行期错误", 行
    assert 行[3] == "老锁拒绝 运行期错误", 行
    assert 行[4] == "坏锁拒绝 运行期错误", 行
    assert _去时序(出["python"]) == _去时序(出["rust"])
