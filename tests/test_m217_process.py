_孙进程 = '''导入 进程
导入 时间
导入 文本 为 文本库

令 起 = 时间.高精度时间()
令 子 = 进程.启动("__PY__", ["-u", "__孙__"])
打印("读到", 进程.读行(子, 5))
令 码 = 进程.等待(子, 5)
令 用时 = 时间.高精度时间() - 起
打印("码", 码)
打印("用时", 文本库.小数位(用时, 1))
'''


def test_孙进程不拖住我们(tmp_path):
    """⑤ O-2 坑3：孙进程继承了 stdout（管道永不 EOF）。

    `等待` 只等**直接子进程** ⇒ 必须在 3 秒内返回 0，而不是陪着孙进程睡 20 秒。
    M217 之前那种「读到管道 EOF 才返回」的写法，这里会变成 8.4 秒。
    """
    孙 = _写子脚本(tmp_path, "grand", 孙进程脚本)
    源 = _孙进程.replace("__PY__", PY).replace("__孙__", 孙)
    出 = _跑宿主(源, tmp_path, "grand")
    行 = 出["rust"].strip().splitlines()
    assert 行[0] == "读到 主进程结束", 行
    assert 行[1] == "码 0", 行
    用时 = float(行[2].split()[1])
    assert 用时 < 3, f"等了 {用时} 秒 —— 孙进程拖住我们了（坑3 复发）"
    assert _去时序(出["python"]) == _去时序(出["rust"]), "python 与 rust 不一致"


