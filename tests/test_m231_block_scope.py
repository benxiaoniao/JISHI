def test_全局声明后块内赋值再返回():
    """`全局 X` + `如果` 块内赋值 + `返回 X` —— **不能**报 E0301。

    🔴 这条是真实项目（桌面营造 `语言问题记录.md`）撞出来的，四个执行器**一致地错**：
    `Global` 语句把名字记进 `scopes[scope].globals` 并从 `bound` 摘掉，
    于是块内 `X = …` 被当成「块内**新引入**的名字」⇒ 出块后 `返回 X` 判成
    「读了已退出块里的名字」⇒ E0301。

    ⚠️ 在这条之前，`test_m231_block_scope.py` 里 `全局` 出现 **0 次** —— 判据有洞。
    """
    src = ("实例 = 空\n"
           "函数 取()：\n"
           "    全局 实例\n"
           "    如果 实例 == 空：\n"
           "        实例 = \"建了\"\n"
           "    返回 实例\n"
           "打印(取())\n")
    assert _assert_agree(src) == "建了\n"


@pytest.mark.xfail(strict=True, reason=(
    "🔴 M240 还剩这一处：`如果/否则` 两段里都**读**全局再赋值（计数 = 计数 + 1）。"
    "现在不报 E0301 了，但**写没落到全局**（输出 1/1/-1，期望 1/2/1）—— "
    "树遍历的块内赋值作用域还差一处。strict=True：修好后会报红提醒去掉 xfail。"))
def test_全局声明后块内赋值_多段如果():
    """`如果 … 否则如果 … 否则` 每一段里都对全局赋值 —— 出块后还能读。"""
    src = ("计数 = 0\n"
           "函数 累加(甲)：\n"
           "    全局 计数\n"
           "    如果 甲 > 0：\n"
           "        计数 = 计数 + 1\n"
           "    否则：\n"
           "        计数 = 计数 - 1\n"
           "    返回 计数\n"
           "打印(累加(1))\n"
           "打印(累加(1))\n"
           "打印(累加(0))\n")
    assert _assert_agree(src) == "1\n2\n1\n"
