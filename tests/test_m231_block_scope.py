def test_循环里造闭包各拿各的():
    """`遍历 i … 函们.追加(函数()：i * 10)` → 0 10 20，不是 20 20 20。"""
    src = ("令 函们 = []\n"
           "遍历 i 在 范围(3)：\n"
           "    函们.追加(函数()：i * 10)\n"
           "遍历 f 在 函们：\n"
           "    打印(f())\n")
    assert _assert_agree(src) == "0\n10\n20\n"


def test_循环体内令一个再捕获():
    """`遍历 i：令 j = i  函们.追加(函数()：j * 10)` —— 同样各拿各的。"""
    src = ("令 函们 = []\n"
           "遍历 i 在 范围(3)：\n"
           "    令 j = i\n"
           "    函们.追加(函数()：j * 10)\n"
           "遍历 f 在 函们：\n"
           "    打印(f())\n")
    assert _assert_agree(src) == "0\n10\n20\n"


def test_如果块里令一个再捕获():
    """块里 `令` 的变量被闭包捕获，出块后闭包照样读得到（环境被闭包提着）。"""
    src = ("令 拿 = 空\n"
           "如果 真：\n"
           "    令 k = 42\n"
           "    拿 = 函数()：k\n"
           "打印(拿())\n")
    assert _assert_agree(src) == "42\n"


# ---------------------------------------------------------------------------
# 四、块级作用域与老语义的边界：`如果`/`尝试` 之外不受影响
# ---------------------------------------------------------------------------

def test_函数体不是块():
    """函数体本身**不是**块 —— 函数里 `令` 的，函数里到处能用（这是函数作用域）。"""
    src = ("函数 f()：\n"
           "    令 a = 1\n"
           "    如果 真：\n"
           "        a = a + 1\n"
           "    如果 真：\n"
           "        a = a + 1\n"
           "    返回 a\n"
           "打印(f())\n")
    assert _assert_agree(src) == "3\n"


def test_推导式与匿名函数的形参不撞块():
    """推导式的循环变量、匿名函数的形参都是**各自的作用域**，不该被块级化误伤。

    （M231 过渡期真踩过：`[行[0] 遍历 行 在 有效]` 里的 `行` 撞上外层
    「已退出」的 `行`，被误判成越界引用。）
    """
    src = ("令 行们 = [[1], [2], [3]]\n"
           "打印([行[0] 遍历 行 在 行们])\n"
           "令 排序按 = 函数(名)：名\n"
           "打印(排序按(\"甲\"))\n")
    assert _assert_agree(src) == "[1, 2, 3]\n甲\n"


def test_循环外读循环变量也报错():
    """循环变量本身也是**块级**的（`遍历 i` 之后 `打印(i)` ⇒ E0301）。"""
    src = ("函数 f()：\n"
           "    令 和 = 0\n"
           "    遍历 i 在 [1, 2]：\n"
           "        和 = 和 + i\n"
           "    返回 i\n"
           "打印(f())\n")
    got = _assert_agree(src)
    assert "E0301" in got and "「i」" in got, got


