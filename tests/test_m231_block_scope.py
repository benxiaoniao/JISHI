# -*- coding: utf-8 -*-
"""M231 · 块级作用域（A 完整版）—— 语义的守门测试。

这一版的语义（拍板 A，收窄成 A2，见 `docs/设计决策.md` D131）：

| 块 | 谁开的 |
|---|---|
| 循环体 | `遍历` / `循环` / `当` |
| 分支体 | `如果` 的每一段、`否则` |
| 异常三段 | `尝试` 体、每个 `捕获` 体、`最终` 体 |

三条规矩：

1. **块里 `令` 出来的新名字，出块就没了** —— 块外读是 `E0301`（**编译期**就报，
   不等到运行期）。
2. **外层本来就有同名的，块里 `令` 是改外层** —— 这是 A2 口径，保护全仓 122 处
   `令 总 = 总 + 1` 那种累加写法（改成「一律块内声明」它们会静默变哑巴）。
3. **闭包抓到的是各自那一轮的变量**（D1 晚绑定，M231 的主要目标）。

⚠️ 这套判据盯的是「**两个前端 × 三个执行器逐字节一致**」，因为块级作用域是
**改语义**的活 —— 只要有一个执行器没跟上，用户就会遇到「同一份代码换个引擎
结果不同」，那比没有这个特性还糟。
"""

import io
import os
import sys
from contextlib import redirect_stdout
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from oracle.jishi import tokenizer as T                                   # noqa: E402
from oracle.jishi.compiler import compile_source                          # noqa: E402
from oracle.jishi.interpreter import run_source as run_tree               # noqa: E402
from oracle.jishi.vm import VM                                            # noqa: E402

HAS_RUST = T.rust_available()
try:
    from oracle.jishi import cvm_bind                                     # noqa: E402
    HAS_CVM = True
except Exception:                                                        # noqa: BLE001
    HAS_CVM = False


# ---------------------------------------------------------------------------
# 工具：两个前端 × 三个执行器，逐字节比
# ---------------------------------------------------------------------------

def _run(fn) -> str:
    """跑一次，返回 stdout（正常）或「输出 + 完整报错文本」（出错）。"""
    buf = io.StringIO()
    try:
        with redirect_stdout(buf):
            fn()
        return buf.getvalue()
    except BaseException as e:                                           # noqa: BLE001
        return buf.getvalue() + "「报错」" + type(e).__name__ + ":" + str(e)


def _all_engines(src: str, filename: str = "块作用域.jsh") -> dict:
    got = {}
    for front in ("python", "rust"):
        if front == "rust" and not HAS_RUST:
            continue
        old = os.environ.get(T.FRONTEND_ENV)
        os.environ[T.FRONTEND_ENV] = front
        try:
            row = [
                _run(lambda: run_tree(src, filename)),
                _run(lambda: VM(compile_source(src, filename), filename).run()),
            ]
            if HAS_CVM:
                row.append(_run(lambda: cvm_bind.run_source_c(src, filename)))
            got[front] = tuple(row)
        finally:
            if old is None:
                os.environ.pop(T.FRONTEND_ENV, None)
            else:
                os.environ[T.FRONTEND_ENV] = old
    return got


def _assert_agree(src: str, filename: str = "块作用域.jsh") -> str:
    """代码执行到哪一层，六个结果就要逐字节相同。"""
    原 = sys.stdin
    sys.stdin = io.StringIO("")          # `输入()` 别去读终端把测试挂住
    try:
        got = _all_engines(src, filename)
    finally:
        sys.stdin = 原
    names = ("树遍历", "Python VM") + (("C VM",) if HAS_CVM else ())
    参照前端, 参照 = next(iter(got.items()))
    for front, row in got.items():
        for name, a, b in zip(names, 参照, row):
            assert a == b, (
                f"两个前端 / 执行器不一致：{front} 的「{name}」\n"
                f"  参照（{参照前端}）: {a!r}\n  实际（{front}）  : {b!r}\n"
                f"源码：\n{src}")
    # 六个结果已经逐字节相同 ⇒ 返回第一个执行器的输出就够（字符串，好断言）
    return 参照[0]


