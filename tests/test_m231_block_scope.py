@pytest.mark.parametrize("case", _ESCAPE_CASES,
                         ids=[c[0] for c in _ESCAPE_CASES])
def test_块外读不到(case):
    """块外读块里 `令` 的新名字 ⇒ `E0301`，而且**一句都不许先打印**。

    🔴 「一句都不许先打印」这句是关键：块越界引用必须在**执行之前**查出来。
    不查的话，树遍历会先把循环/分支跑完、打一堆东西，最后才在那一行报错 ——
    而字节码宿主是编译期直接报，两边输出一半有一半没有（M231 过渡期真撞过）。
    """
    _名, src, 名字 = case
    got = _assert_agree(src)
    assert got.startswith("「报错」"), f"居然没报错：{got!r}"
    assert "E0301" in got, f"错误码不对：{got!r}"
    assert f"「{名字}」" in got, f"没点名到「{名字}」：{got!r}"
    # 报错文本前面不许有任何正常输出
    assert got.split("「报错」")[0] == "", f"报错之前先打印了东西：{got!r}"


