def test_比大小写错层级会报错并列出真字段(tmp_path):
    """`{">": 100}` 要报「表「账目」里没有这些字段：>」+ 提示。

    ⚠️ 以前三个执行器**静默给空列表**（SQLite 把双引号里的未知名字当字符串
    字面量），Node 直接甩一句英文 SQL 报错 —— 三种行为。这是教程 §11.4
    「比大小要嵌一层」那条坑的正主，所以钉在这里。
    """
    文本 = _一致(准备 +
               '打印(数据库.查询(库, "账目", {">": 100}))\n', tmp_path)
    assert "表「账目」里没有这些字段：>" in 文本, 文本
    assert "它有：id、日期、类别、金额分" in 文本, f"字段清单没了：{文本!r}"
    assert "嵌一层" in 文本, f"提示没了：{文本!r}"


def test_条件里的字段名写对就正常(tmp_path):
    """报错别把正常用法也挡了（同一张表、同样的字段名）。"""
    文本 = _一致(准备 +
               '打印(长度(数据库.查询(库, "账目", {"类别": "餐饮"})))\n'
               '打印(数据库.条数(库, "账目", {"金额分": {"非空": 真}}))\n', tmp_path)
    assert 文本.strip().splitlines() == ["2", "3"], 文本


def test_字段名里不许写_id(tmp_path):
    """每张表自动带 `id` —— 写了要报一句能照着改的话。"""
    文本 = _一致('导入 数据库\n'
              '令 库 = 数据库.打开(":memory:")\n'
              '数据库.建表(库, "试", ["id", "名字"])\n', tmp_path)
    assert "字段名里不用写 id" in 文本, 文本
    assert "把 id 从字段列表里去掉" in 文本, f"提示没了：{文本!r}"
