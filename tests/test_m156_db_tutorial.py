def test_教程示例能跑且自己清理(tmp_path):
    源码 = (ROOT / "examples" / "tutorial" / "11_记账数据库.jsh").read_text(
        encoding="utf-8")
    文本 = _一致(源码, tmp_path)

    for 片段 in ("新记了 3 笔；一共 5 笔",
               "2026-10-03 餐饮 22.00 元 聚餐",      # 最新两笔（id 倒序）
               "2026-10-02 购物 89.90 元",           # 超过 50 元的
               "餐饮 3 笔，合计 45.50 元，平均 15.17 元",   # 分类汇总
               "演示完成（账目.db 已清理）"):
        assert 片段 in 文本, f"缺「{片段}」：\n{文本}"
    assert not (tmp_path / "账目.db").exists(), "示例没把库文件删掉"


def test_教程示例里金额都按两位小数显示(tmp_path):
    """钱是「分」存的，显示必须回到两位 —— 这是这一章的重点之一。"""
    文本 = _一致('导入 数据库\n'
              '导入 文本 为 文本库\n'
              '打印(文本库.小数位(2550 / 100, 2))\n'
              '打印(文本库.小数位(4 / 100, 2))\n', tmp_path)
    assert 文本.strip().splitlines() == ["25.50", "0.04"], 文本


