def test_倒序是从大到小(tmp_path):
    """以前 `ORDER BY "金额分", rowid DESC` —— 主字段没倒，拿到的是升序。"""
    文本 = _一致(准备 +
               '遍历 账 在 数据库.查询(库, "账目", 空, "金额分", 真)：\n'
               '    打印(账["金额分"])\n', tmp_path)
    assert 文本.strip().splitlines() == ["10000", "2550", "1200"], 文本


def test_正序仍然是最小在前(tmp_path):
    """改方向时别把默认那半边弄坏。"""
    文本 = _一致(准备 +
               '遍历 账 在 数据库.查询(库, "账目", 空, "金额分", 假)：\n'
               '    打印(账["金额分"])\n', tmp_path)
    assert 文本.strip().splitlines() == ["1200", "2550", "10000"], 文本


def test_多字段倒序时每个字段都倒(tmp_path):
    文本 = _一致(准备 +
               '遍历 账 在 数据库.查询(库, "账目", 空, ["类别", "金额分"], 真)：\n'
               '    打印(账["类别"], 账["金额分"])\n', tmp_path)
    assert 文本.strip().splitlines() == ["餐饮 2550", "餐饮 1200", "交通 10000"], 文本


def test_不给排序时倒序等于最新在前(tmp_path):
    """`排序` 不写 → 按 `id`；`倒序=真` → 最新记的在前。"""
    文本 = _一致(准备 +
               '遍历 账 在 数据库.查询(库, "账目", 空, 空, 真)：\n'
               '    打印(账["id"])\n', tmp_path)
    assert 文本.strip().splitlines() == ["3", "2", "1"], 文本


def test_倒序加条数取最贵的几笔(tmp_path):
    """教程里就是这么用的（「超过 50 元的，从贵到便宜」）—— 两条一起验。"""
    文本 = _一致(准备 +
               '遍历 账 在 数据库.查询(库, "账目", {"金额分": {">": 2000}}, "金额分", 真, 1)：\n'
               '    打印(账["金额分"])\n', tmp_path)
    assert 文本.strip() == "10000", 文本


