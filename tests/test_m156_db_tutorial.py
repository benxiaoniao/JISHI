"""M156 · 教程第 11 章（`数据库`）连同它撞出来的两个真 bug。

## 一、教程示例必须真能跑

`examples/tutorial/11_记账数据库.jsh` 讲的是「把账存进 SQLite」：
建表 → 记号几笔 → 查最近的 → 按金额倒序查大额 → 分类汇总 → 改一笔 →
删一笔 → 手写一句 SQL → 关库并清理。要求**五个执行器输出逐字相同**，
而且跑完**不留 `账目.db`**（其余教程示例都这样）。

## 二、写教程撞出来的两个东西（这是这一站真正值钱的部分）

### ① `数据库.查询` 的 `倒序` 只倒了 `rowid`（三个引擎同错）

`_定序` 以前拼成 `ORDER BY "金额", rowid DESC` —— 方向只加在兜底的 `rowid`
上，**主排序字段还是升序**。于是「倒序取最贵的几笔」拿到的是最便宜的几笔。
`tests/cases/31_标准库_M112.jsh` 里那条语料**把 bug 当成了期望**
（升序的 12.00 / 25.50 / 100.00），所以五引擎对拍一直全绿。

⇒ 三处都改成「方向加在**每个**排序字段上」，语料期望一并改正。

### ② `整数(精确小数)` / `小数(精确小数)` 在宿主上报错

| 表达式 | Python / 树遍历 / C VM | Rust / Node（改前） |
|---|---|---|
| `整数(精确(8.5))` | `8`（`int(Decimal)`） | 报「「8.5」不能转成整数」 |
| `小数(精确(1.5))` | `1.5` | 报「「1.5」不能转成小数」 |

装钱那段（`整数(精确(金额) * 100)`）正好踩中 —— 教程在宿主上根本跑不起来。
宿主补上「向零截断」与「按十进制文本转 f64」，与 Python 的口径对齐。
"""

import shutil
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, ".")

from conftest import ROOT, rust_exe_path, 去掉遮蔽提示          # noqa: E402

CVM驱动 = '''\
import sys
sys.path.insert(0, r"{root}")
for _s in (sys.stdout, sys.stderr):
    try:
        _s.reconfigure(newline="\\n")
    except Exception:
        pass
from oracle.jishi import cvm_bind, errors as E

src = open("程序.jsh", encoding="utf-8").read()
try:
    cvm_bind.run_source_c(src, filename="程序.jsh")
except E.JishiError as e:
    e.with_source(src.replace("\\r\\n", "\\n").split("\\n"))
    sys.stderr.write(e.render() + "\\n")
    sys.exit(1)
'''


def _五份(源码: str, tmp_path: Path) -> dict:
    from oracle.jishi import serialize
    from oracle.jishi.compiler import compile_source

    (tmp_path / "程序.jsh").write_text(源码, encoding="utf-8", newline="\n")
    (tmp_path / "驱动.py").write_text(
        CVM驱动.format(root=str(ROOT).replace("\\", "\\\\")), encoding="utf-8")
    表 = {
        "树遍历": [sys.executable, "-m", "oracle.jishi.cli", "--tree", "程序.jsh"],
        "Python VM": [sys.executable, "-m", "oracle.jishi.cli", "程序.jsh"],
        "C VM": [sys.executable, "驱动.py"],
    }
    rs = rust_exe_path()
    if rs.is_file():
        表["Rust 宿主"] = [str(rs), "程序.jsh"]
    node = shutil.which("node")
    if node:
        (tmp_path / "程序.json").write_text(
            serialize.dumps(compile_source(源码, "程序.jsh")), encoding="utf-8")
        表["Node 宿主"] = [node, str(ROOT / "oracle" / "node" / "index.js"),
                           "程序.json"]
    出 = {}
    for 名字, 命令 in 表.items():
        r = subprocess.run(命令, cwd=str(tmp_path), capture_output=True,
                           timeout=120, input=b"")    # 空 stdin：`输入()` 才会撞结束
        出[名字] = 去掉遮蔽提示((r.stdout + r.stderr).decode("utf-8", "replace"))
    return 出


def _一致(源码: str, tmp_path: Path) -> str:
    出 = _五份(源码, tmp_path)
    值 = set(出.values())
    assert len(值) == 1, "五个执行器说法不一致：\n" + "\n".join(
        f"—— {k} ——\n{v}" for k, v in 出.items())
    return 值.pop()


# 所有用例共用的一张表（内存库，不碰磁盘）
# ⚠️ `金额分` 特意是「不按 id 排」的：25.5 元 / 100 元 / 12 元 ——
#    升序与插入顺序不同，这样「倒序」才真的被验证到（以前语料里恰好反过来）。
准备 = ('导入 数据库\n'
      '令 库 = 数据库.打开(":memory:")\n'
      '数据库.建表(库, "账目", ["日期", "类别", "金额分"])\n'
      '数据库.插入(库, "账目", {"日期": "2026-10-01", "类别": "餐饮", "金额分": 2550})\n'
      '数据库.插入(库, "账目", {"日期": "2026-10-01", "类别": "交通", "金额分": 10000})\n'
      '数据库.插入(库, "账目", {"日期": "2026-10-02", "类别": "餐饮", "金额分": 1200})\n')


