# -*- coding: utf-8 -*-
"""M211 · 标准库补件：多键排序 · 二分查找 · 列表字典序比较 · 卡与文档。

## 这一站解决的是什么

`基石数据库` 的作者交回来的清单（W1 / W2 / W3 / C1 / W4）里，五条卡在
「有需求、但语言没有」上：

| 缺什么 | 谁撞出来的 |
|---|---|
| **按比较函数排序**（多键） | 索引要「先按类别、再按金额」，`排序按` 只能算一个键，只好拼复合键 |
| **二分查找** | 有索引就会想要 O(log n) 找位置；没有就只能 `索引()` 线性扫 |
| **列表字典序比较** | Rust 宿主上 `[1,2] < [1,3]` 报 `E2002`，另四个执行器给「真」 |
| 卡里 `数据库` 一节太薄 | 条件怎么嵌、空值怎么算、汇总给什么结构 —— 照卡写代码必踩 |
| `刷新` 到底刷了什么 | 三个宿主的缓冲策略不同，文档一个字没写 |

## 判据怎么验

- **三宿主逐字一致**（Rust / Python / Node 跑同一段脚本比 stdout）——
  包括**报错文案**（这是「同一门语言」的底线，M55 起的老规矩）。
- **语义边界钉住**：稳定排序、重复元素取最左、左闭右开、不可比就报错。
- **性能各一条**：二分 vs 线性、排序按比较 vs 双键 `排序按`（**比值**判据，
  能抗负载；绝对耗时只当参考打印）。
"""

