# 一、三宿主跑同一段脚本，逐字对比
# ---------------------------------------------------------------------------

def _跑三宿主(源: str, tmp: Path, 名: str) -> dict:
    """三个宿主各跑一遍 → `{名: (退出码, stdout, stderr)}`。"""
    文件 = tmp / f"{名}-{os.getpid()}.jsh"
    文件.write_text(源, encoding="utf-8", newline="\n")

    def _收(r) -> tuple:
        return (r.returncode,
                (r.stdout or "").replace("\r\n", "\n"),
                (r.stderr or "").replace("\r\n", "\n"))

    出: dict = {}
    if RUST_EXE.is_file():
        r = subprocess.run([str(RUST_EXE), str(文件)], capture_output=True,
                           text=True, encoding="utf-8", timeout=180)
        出["rs"] = _收(r)
    else:
        出["rs"] = None

    r = subprocess.run([sys.executable, "-m", "oracle.jishi.cli", str(文件)],
                       capture_output=True, text=True, encoding="utf-8",
                       timeout=180, cwd=str(ROOT))
    出["py"] = _收(r)

    return 出


def _三边一致(源: str, tmp: Path, 名: str) -> str:
    出 = _跑三宿主(源, tmp, 名)
    有 = {k: v for k, v in 出.items() if v is not None}
    assert 有, "一个宿主都跑不了"
    for k, (码, 文, 错) in 有.items():
        assert 码 == 0, f"[{k}] 退出码 {码}：{(文 + 错)[:400]}"
    基准 = 有["rs"][1] if "rs" in 有 else 有["py"][1]
    for k, (_, 文, _) in 有.items():
        assert 文 == 基准, f"[{k}] 与基准不一致：\n基准={基准!r}\n实得={文!r}"
    return 基准


def _报错三边一致(源: str, tmp: Path, 名: str) -> str:
    """跑一段**必然会报错**的脚本：三宿主都要失败，且**报错那一行逐字相同**。"""
    出 = _跑三宿主(源, tmp, 名)
    有 = {k: v for k, v in 出.items() if v is not None}
    assert 有
    for k, (码, _, 错) in 有.items():
        assert 码 != 0, f"[{k}] 本该报错，却成功退出"
    行们 = {k: _首行错误(错) for k, (_, _, 错) in 有.items()}
    唯一 = set(行们.values())
    assert len(唯一) == 1, "三宿主报错文案不同：\n" + "\n".join(
        f"  {k}: {v}" for k, v in 行们.items())
    return 唯一.pop()


def _跑单宿主(源: str, tmp: Path, 名: str) -> str:
    """只跑**一个**宿主（能做性能计时的那个）：有 Rust 用 Rust，否则 Python。

    ⚠️ 性能数字**不能三边比**：三个宿主本来就快慢不同，那是它们各自的本事，
    不是「语义不一致」。语义一致性由别的用例钉（同一段程序、同样的输出）。
    """
    文件 = tmp / f"{名}-{os.getpid()}.jsh"
    文件.write_text(源, encoding="utf-8", newline="\n")
    if RUST_EXE.is_file():
        r = subprocess.run([str(RUST_EXE), str(文件)], capture_output=True,
                           text=True, encoding="utf-8", timeout=300)
    else:
        r = subprocess.run([sys.executable, "-m", "oracle.jishi.cli", str(文件)],
                           capture_output=True, text=True, encoding="utf-8",
                           timeout=300, cwd=str(ROOT))
    assert r.returncode == 0, (r.stdout or "") + (r.stderr or "")
    return (r.stdout or "").replace("\r\n", "\n")


def _首行错误(stderr: str) -> str:
    for 行 in stderr.splitlines():
        if 行.startswith("错误"):
            return 行.strip()
    return stderr.strip().splitlines()[0] if stderr.strip() else ""


