# -*- coding: utf-8 -*-
"""M139 · `向量`：一列数字上的逐元素运算与点积。

## 这个文件钉什么（和 `test_m52_jishilib.py` 分工不同）

`test_m52` 管**实现方式**：同一段程序在五个引擎上逐字节一致、与宿主层 `.py`
也逐字节一致。这里管**语义本身**：

1. 十一个函数各自算得对（含空向量、单元素、整数/小数混着）；
2. **长度不等必须报错**，而且把两个长度都打出来 —— 这是最容易犯的错，
   静默按短的算会得到「结果不对但程序不报错」，最难查；
3. **切片越界报错**（不像列表切片那样悄悄截断）；
4. **向量就是普通列表**：能下标、能遍历、能 `长度()`、能直接打印 ——
   这条是「不做新值类型」那个决定的可观测后果（用户 2026-10-26 拍板）；
5. 不改变输入（没有副作用）。
"""

import io
import sys
from contextlib import redirect_stdout

import pytest

sys.path.insert(0, ".")

from oracle.jishi.errors import JishiError          # noqa: E402
from oracle.jishi.interpreter import run_source     # noqa: E402


def _跑(源码: str) -> str:
    out = io.StringIO()
    with redirect_stdout(out):
        run_source(源码)
    return out.getvalue()


def _错(源码: str) -> JishiError:
    with pytest.raises(JishiError) as 捕:
        _跑(源码)
    return 捕.value


# ---------------------------------------------------------------------------
# 一、算得对
# ---------------------------------------------------------------------------

def test_构造():
    出 = _跑("导入 向量\n打印(向量.构造(3), 向量.构造(2, 1.5), 向量.构造(0))\n")
    assert 出 == "[0, 0, 0] [1.5, 1.5] []\n"


def test_加与减是逐元素的():
    出 = _跑(
        "导入 向量\n"
        "打印(向量.加([1, 2, 3], [10, 20, 30]))\n"
        "打印(向量.减([10, 20, 30], [1, 2, 3]))\n"
    )
    assert 出 == "[11, 22, 33]\n[9, 18, 27]\n"


def test_标量乘():
    出 = _跑("导入 向量\n打印(向量.标量乘([1, 2], 3), 向量.标量乘([1, 2], 0.5))\n")
    assert 出 == "[3, 6] [0.5, 1.0]\n"


def test_点积():
    出 = _跑("导入 向量\n打印(向量.点积([1, 2], [3, 4]), 向量.点积([1.5, 2], [2, 4]))\n")
    assert 出 == "11 11.0\n"


def test_和与均值():
    出 = _跑("导入 向量\n打印(向量.和([1, 2, 3]), 向量.均值([2, 4, 6]), 向量.和([]))\n")
    assert 出 == "6 4.0 0\n"


def test_最大最小与维数():
    出 = _跑(
        "导入 向量\n"
        "打印(向量.最大([1, 9, 3]), 向量.最小([1, 9, 3]))\n"
        "打印(向量.最大([-5]), 向量.最小([-5]))\n"
        "打印(向量.维数([1, 2, 3]), 向量.维数([]))\n"
    )
    assert 出 == "9 1\n-5 -5\n3 0\n"


def test_切片():
    出 = _跑(
        "导入 向量\n"
        "打印(向量.切片([1, 2, 3, 4], 1, 3))\n"     # 不含止
        "打印(向量.切片([1, 2, 3], 1))\n"           # 不给止 = 到末尾
        "打印(向量.切片([1, 2, 3], 0, 0))\n"        # 空切片
        "打印(向量.切片([1, 2, 3], 3))\n"           # 末尾的空切片
    )
    assert 出 == "[2, 3]\n[2, 3]\n[]\n[]\n"


# ---------------------------------------------------------------------------
# 二、该报的错要报，而且说清楚
# ---------------------------------------------------------------------------

def test_长度不等要报错并说出两个长度():
    e = _错("导入 向量\n打印(向量.加([1, 2, 3], [1, 2]))\n")
    assert "长度相同" in e.message
    assert "3" in e.message and "2" in e.message, e.message


def test_点积和减法也查长度():
    for 名 in ("点积", "减"):
        e = _错(f"导入 向量\n打印(向量.{名}([1], [1, 2]))\n")
        assert "长度相同" in e.message, e.message


def test_传文本要报类型错误():
    e = _错('导入 向量\n打印(向量.加("甲乙", [1, 2]))\n')
    assert e.exc_name == "类型错误", e.exc_name
    assert "不能传文本" in e.message


def test_元素不是数字要点出第几个():
    e = _错('导入 向量\n打印(向量.和([1, "甲", 3]))\n')
    assert e.exc_name == "类型错误", e.exc_name
    assert "第 2 个" in e.message, e.message


def test_布尔不算数字():
    """`真` 在基石里是 `布尔` 类型 —— 别让它悄悄当 1 参与算术。"""
    e = _错("导入 向量\n打印(向量.和([1, 真]))\n")
    assert e.exc_name == "类型错误", e.exc_name
    assert "第 2 个" in e.message


def test_空向量的均值最大最小都报错():
    for 名 in ("均值", "最大", "最小"):
        e = _错(f"导入 向量\n打印(向量.{名}([]))\n")
        assert e.exc_name == "值错误", (名, e.exc_name)
        assert "空的" in e.message, (名, e.message)


def test_切片越界要报错不悄悄截断():
    e = _错("导入 向量\n打印(向量.切片([1, 2, 3], 1, 9))\n")
    assert e.exc_name == "值错误", e.exc_name
    assert "9" in e.message and "3" in e.message, e.message


def test_切片起大于止要报错():
    e = _错("导入 向量\n打印(向量.切片([1, 2, 3], 2, 1))\n")
    assert "不能大于" in e.message


def test_切片负数要报错():
    e = _错("导入 向量\n打印(向量.切片([1, 2, 3], -1))\n")
    assert "不能是负数" in e.message


def test_构造的个数要是自然数():
    e = _错("导入 向量\n打印(向量.构造(-1))\n")
    assert e.exc_name == "值错误", e.exc_name
    e2 = _错("导入 向量\n打印(向量.构造(1.5))\n")
    assert e2.exc_name == "类型错误", e2.exc_name


# ---------------------------------------------------------------------------
# 三、它就是普通列表（「不做新值类型」的可观测后果）
# ---------------------------------------------------------------------------

def test_向量就是列表能直接用列表的本事():
    出 = _跑(
        "导入 向量\n"
        "令 v = 向量.加([1, 2], [3, 4])\n"
        "打印(类型(v), 长度(v), v[0], v[-1])\n"      # 下标、负下标都是列表的
        "令 合 = 0\n"
        "遍历 项 在 v：\n"
        "    合 = 合 + 项\n"
        "打印(合)\n"
        "v.追加(9)\n"                                # 列表方法照旧可用
        "打印(v)\n"
    )
    assert 出 == "列表 2 4 6\n10\n[4, 6, 9]\n"


def test_不改变输入():
    出 = _跑(
        "导入 向量\n"
        "令 甲 = [1, 2]\n"
        "令 乙 = [10, 20]\n"
        "打印(向量.加(甲, 乙), 向量.标量乘(甲, 2))\n"
        "打印(甲, 乙)\n"
    )
    assert 出 == "[11, 22] [2, 4]\n[1, 2] [10, 20]\n"
