@pytest.mark.计时
def test_字符串拼接没有退化(tmp_path):
    """拼接 4 万次（每次 10 字节）：**< 6 秒**。

    ⚠️ 这个场景本身是 **O(n²)**（`合 = 合 + 段` 每次复制整个前缀），
    实测 M214 **~2.0 s**、M214b **~1.8 s**。上界给到 6 秒只抓「一个量级的退化」。
    """
    源 = '''
导入 时间
导入 文本 为 文本库
令 合 = ""
循环 40000 次：
    合 = 合 + "abcdefghij"
打印(长度(合))
'''
    import time as _t
    起 = _t.perf_counter()
    _跑(源, tmp_path, "perf拼接", 超时=300)
    用时 = (_t.perf_counter() - 起) * 1000
    assert 用时 < 6000, f"4 万次拼接用了 {用时:.0f} ms（含进程启动 ~20 ms）"
