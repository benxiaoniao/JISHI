# 四、引用计数：不泄漏、不提前释放
# ---------------------------------------------------------------------------

def test_长串反复创建不泄漏(tmp_path):
    """造 20 万个 8 KB 长串再丢弃。

    - **泄漏** ⇒ 进程一路涨到 1.6 GB（慢、甚至 OOM）；
    - **提前释放**（少加了计数就 free）⇒ 后面读到的是已释放内存（内容错 / 崩）。

    所以这条同时盯两件事：内容对 + 总时长在合理范围。
    """
    源 = '''
导入 时间
导入 文本 为 文本库
令 起 = 时间.高精度时间()
令 末 = ""
循环 200000 次：
    令 s = "x" * 8000
    如果 长度(s) != 8000：
        打印("错")
    末 = s[0:3]
打印(末, 文本库.小数位((时间.高精度时间()-起)*1000, 0))
'''
    出 = _跑(源, tmp_path, "泄漏", 超时=300).strip().split()
    assert 出[0] == "xxx", 出
    毫秒 = float(出[1])
    # 20 万次 8 KB 的 malloc+free：实测约 300~600 ms。
    # 放宽到 20 秒 —— 超过就是「泄漏把机器压垮」或「有二次方行为」。
    assert 毫秒 < 20000, f"20 万个 8KB 串用了 {毫秒} ms，像是泄漏了"


def test_共享长串内容不乱(tmp_path):
    """克隆出来的堆串，在原件释放之后仍然可读（引用计数没少加）。"""
    源 = '''
函数 造()：
    令 原 = "0123456789abcdef" * 100
    返回 [原, 原]
令 集 = 造()
遍历 s 在 集：
    如果 长度(s) != 1600：
        打印("长度错")
    如果 s[0:4] != "0123":
        打印("内容错")
打印("ok", 长度(集[0]), 长度(集[1]))
'''
    出 = _跑(源, tmp_path, "共享").strip()
    assert 出 == "ok 1600 1600", 出


def test_大量短串不泄漏(tmp_path):
    """短串走内联（不 malloc），200 万次创建不该有任何堆压力。"""
    源 = '''
导入 时间
令 起 = 时间.高精度时间()
令 n = 0
循环 2000000 次：
    令 s = "abcd"
    如果 s == "abcd":
        n = n + 1
导入 文本 为 文本库
'''
    源 += '''
打印(n, 文本库.小数位((时间.高精度时间()-起)*1000, 0))
'''
    出 = _跑(源, tmp_path, "短串", 超时=300).strip().split()
    assert 出[0] == "2000000", 出
    毫秒 = float(出[1])
    assert 毫秒 < 20000, f"200 万次短串用了 {毫秒} ms —— 内联没生效？"


