"""M214b：文本的 16 字节表示（SSO 内联 + 一次分配的堆串）与惰性文本迭代器。

## 这一站动的是什么

M214 把 `Val` 从 32 降到 24（整数换了对齐 8 的 `JInt`），但**文本那半被实测否决**：
`Rc<Heap>{Box<str>}` 是**两次分配**，字符串拼接 / 比较 / 切片 / 文本列表全掉 20~40%。
M214b 换了个形状 —— `jstr::JStr`：

- ≤7 字节的串**内联**在 16 字节槽里（不分配、不动引用计数）；
- 长串是**一次分配**的 thin pointer 堆串（头与字节连续，同 `Rc<str>` 的思路），
  带 `ascii` / 字符数缓存；
- 遍历文本从「materialize 成 Vec + 反转」改成 **`Val::StrIter` 惰性迭代**。

## 为什么这些判据是「契约」而不是「功能测试」

`JStr` 里有手写的 `alloc` / `dealloc` / 引用计数。这类代码**编译能过、单测能过、
大判据也能过**，只是偶尔 double free 或者泄漏 —— 所以要盯三件具体的事：

1. **尺寸**：`JStr` 涨到 24 ⇒ `Val` 回到 32，M214 白干。这条在 `test_m82` 与
   `jstr.rs` 的单测里各钉一道。
2. **内联/堆的边界行为必须一致**：7 字节走内联、8 字节走堆 —— 两边在
   「比较 / 长度 / 下标 / 拼接 / 切片 / 当字典键」上必须给**逐字相同**的结果。
   以前 `Rc<str>` 只有一条路，现在有两条，边界两侧不一致是最容易漏的 bug。
3. **引用计数不泄漏、不提前释放**：造 20 万个 8 KB 长串并丢弃，进程不能一路涨
   （泄漏）也不能崩（提前释放）。

## 性能判据为什么用绝对毫秒

同机 A/B 要编两个二进制（`git stash` 一轮），放进 CI 太重。这里用**宽松的绝对上界**
+ 注释里写清「M214 是多少、现在是多少」—— 抓到的是「退回去了」而不是「今天机器快不快」。
"""
import os
import subprocess
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent
EXE = ROOT / "rust" / "target" / "release" / (
    "jishi-rs.exe" if os.name == "nt" else "jishi-rs")


def _跑(源: str, tmp: Path, 名: str, 超时: int = 180) -> str:
    """真跑 `jishi-rs`，返回 stdout（统一成 LF）。"""
    if not EXE.is_file():
        pytest.skip(f"没有 {EXE}（先 `cargo build --release`）")
    文 = tmp / f"{名}-{os.getpid()}.jsh"
    文.write_text(源, encoding="utf-8", newline="\n")
    r = subprocess.run([str(EXE), str(文)], capture_output=True, text=True,
                       encoding="utf-8", timeout=超时)
    assert r.returncode == 0, f"[{名}] 退出码 {r.returncode}：{(r.stderr or '')[:600]}"
    return (r.stdout or "").replace("\r\n", "\n")


# ---------------------------------------------------------------------------
# 一、尺寸（M214 的成果不能被这次改动吃掉）
# ---------------------------------------------------------------------------

def test_Val还是24字节():
    """`JStr` 必须是 16 字节 —— 大一点 `Val` 就回到 32，M214 白做。"""
    if not EXE.is_file():
        pytest.skip("没有二进制")
    r = subprocess.run([str(EXE), "--dump-val-size"], capture_output=True,
                       text=True, encoding="utf-8", timeout=60)
    assert r.returncode == 0, r.stderr
    import json
    尺寸 = json.loads(r.stdout)
    assert 尺寸["val"] == 24, f"`Val` 现在是 {尺寸['val']} 字节（M214 降到 24）"


# ---------------------------------------------------------------------------
# 二、内联 / 堆两条路必须给出一样的结果
# ---------------------------------------------------------------------------

_边界源 = '''
# 1~7 字节走内联，8 字节起走堆 —— 两侧的每一种操作都要一样
令 串们 = ["", "a", "ab", "abc", "abcd", "abcde", "abcdef", "abcdefg",
           "abcdefgh", "abcdefghi", "中文", "中文ab", "中文abc", "一二三四五六七",
           "😀", "😀😀", "a中b文c"]
遍历 s 在 串们：
    打印(长度(s), s == s, s + "!")

# 字典键：短（内联）与长（堆）都要能当键，且**内容相同就是同一个键**
令 d = {}
d["abc"] = 1
d["abcdefgh"] = 2
d["中文"] = 3
d["一二三四五六七八"] = 4
打印(d["abc"], d["abcdefgh"], d["中文"], d["一二三四五六七八"])
打印(长度(d))

# 下标：内联与堆的边界两侧
令 八 = "abcdefgh"
打印(八[0], 八[7], 八[-1], 八[-8])
令 七 = "abcdefg"
打印(七[0], 七[6], 七[-1])

# 切片：结果可能落在内联侧，也可能落在堆侧
打印("abcdefgh"[0:3], "abcdefgh"[3:8], "abcdefgh"[0:8])

# 比较：跨边界（内联 vs 堆，内容相同）
打印("abcdefg" == "abcdefg", "abcdefg" == "abcdefgh")
打印("abcdefg" < "abcdefgh", "abcdefgh" > "abcdefg")
'''

_边界期望 = """0 真 !
1 真 a!
2 真 ab!
3 真 abc!
4 真 abcd!
5 真 abcde!
6 真 abcdef!
7 真 abcdefg!
8 真 abcdefgh!
9 真 abcdefghi!
2 真 中文!
4 真 中文ab!
5 真 中文abc!
7 真 一二三四五六七!
1 真 😀!
2 真 😀😀!
5 真 a中b文c!
1 2 3 4
4
a h h a
a g g
abc defgh abcdefgh
真 假
真 真"""


def test_内联与堆两条路结果一致(tmp_path):
    """7 字节（内联）/ 8 字节（堆）两侧，每种操作给同一份结果。"""
    出 = _跑(_边界源, tmp_path, "边界").strip()
    assert 出 == _边界期望, f"期望：\n{_边界期望}\n实得：\n{出}"


