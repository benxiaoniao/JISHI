def test_遍历文本逐字符且含空串(tmp_path):
    """遍历必须按**字符**（不是字节），空串给零次，超长串不丢不重。"""
    源 = '''
令 计 = 0
遍历 c 在 ""：
    计 = 计 + 1
打印("空串次数", 计)

令 段 = ""
遍历 c 在 "中文abc😀"：
    段 = 段 + c + "|"
打印(段)

令 长 = ""
循环 1000 次：
    长 = 长 + "中"
令 n = 0
遍历 c 在 长：
    n = n + 1
打印("一千中文", n, 长度(长))
'''
    出 = _跑(源, tmp_path, "遍历").strip().splitlines()
    assert 出[0] == "空串次数 0", 出
    assert 出[1] == "中|文|a|b|c|😀|", 出
    assert 出[2] == "一千中文 1000 1000", 出


def test_遍历文本不消耗原串(tmp_path):
    """遍历完文本还在（以前是快照，改成惰性迭代后**不能**把串走光）。"""
    源 = '''
令 甲 = "中文abc"
令 n = 0
遍历 c 在 甲：
    n = n + 1
遍历 c 在 甲：
    n = n + 1
打印(n, 长度(甲), 甲)
'''
    assert _跑(源, tmp_path, "两遍").strip() == "10 5 中文abc"


def test_嵌套遍历文本(tmp_path):
    """同一个串嵌套遍历（两个独立的迭代器，互不干扰）。"""
    源 = '''
令 计 = 0
遍历 a 在 "abc"：
    遍历 b 在 "xyz"：
        计 = 计 + 1
打印(计)
'''
    assert _跑(源, tmp_path, "嵌套").strip() == "9"


