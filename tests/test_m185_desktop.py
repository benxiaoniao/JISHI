# 三、剪贴板：写→读逐字相同（Windows）
# ---------------------------------------------------------------------------

@需要原生
def test_剪贴板写进去读得回来(tmp_path):
    """写一段带换行与中文的文本，再读回来 —— **逐字相同**。

    ⚠️ 这条会**改动开发机的剪贴板**（写完就覆盖了）。判据里这么做是权衡过的：
    不真写就读不到真结果；而「剪贴板里的旧内容」对开发机没有价值。
    """
    记号 = "M185 剪贴板往返 ABC\\n第二行 ①②③"
    源 = (
        "导入 剪贴板\n"
        f'打印("写", 剪贴板.写文本("{记号}"))\n'
        '令 回 = 剪贴板.读文本()\n'
        '打印("等", 回 == "' + 记号 + '")\n'
        '打印("读到", 长度(回))\n'
    )
    (tmp_path / "程序.jsh").write_text(源, encoding="utf-8", newline="\n")
    码, 出 = _跑([str(EXE), "程序.jsh"], tmp_path)
    assert 码 == 0, 出[:900]
    assert "写 真" in 出, f"写剪贴板失败：{出[:600]}"
    assert "等 真" in 出, f"读回来和写进去不一致：{出[:600]}"


