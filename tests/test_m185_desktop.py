# -*- coding: utf-8 -*-
"""M185：桌面深化 —— 几何 8 个 · 图标 · 进度 · 提示 · 托盘改 · 剪贴板 · `系统.打开`。

## 这一站的分工

| 组 | 谁能真做 | 这里怎么验 |
|---|---|---|
| 几何 8 个 / 图标 | 三个平台（tao） | **真开一个原生窗口**，设完 `读几何` **读回来**比 |
| `进度` / `提示` | **只有 Windows** | Windows 上验「返回真」；别处验「报的是那句平台错」 |
| `托盘.设菜单` / `设提示` | 三平台（tray-icon） | 没设托盘时**报一句中文**（不是静默返回假） |
| `剪贴板` | **只有 Windows** | 写一段 → 读回来**逐字相同** |
| `系统.打开` | 三平台 | **不存在的东西返回假、不许启动任何程序**（五执行器同一条规矩） |

## 为什么「读回来」这件事要单列

`设大小` 调用不报错，**不等于**窗口真的变了 —— 这正是本项目踩过的坑
（「能开窗 ≠ 窗口里有东西」）。所以几何类的每一条都：**设 → `读几何` → 比**，
而不是「调了没抛异常」。

⚠️ 真窗口那几条要求桌面环境（`JISHI_NO_GUI=1` 时跳过，CI 上就是跳过的）。
"""

import os
import subprocess
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
EXE = ROOT / "rust" / "target" / "release" / ("jishi-rs.exe" if os.name == "nt" else "jishi-rs")

无界面 = bool(os.environ.get("JISHI_NO_GUI"))
需要原生 = pytest.mark.skipif(
    无界面 or not sys.platform.startswith("win"),
    reason="真开原生窗口要桌面环境（CI 设 JISHI_NO_GUI=1）",
)

#: M185 在 `窗口` 上加的 11 个函数（顺序按语言卡）。
新函数 = ["设大小", "设位置", "居中", "最大化", "最小化", "设全屏", "设置顶", "读几何", "设图标", "进度", "提示"]

#: 这些函数在 Python / Node 宿主上的统一报错特征串。
做不到特征 = "没有原生窗口能力"


def _跑(命令, cwd, 超时=120, 环境=None):
    env = dict(os.environ)
    if 环境:
        env.update(环境)
    r = subprocess.run(命令, cwd=str(cwd), capture_output=True, text=True,
                       encoding="utf-8", errors="replace", env=env, timeout=超时)
    return r.returncode, (r.stdout or "") + (r.stderr or "")


def _页面(tmp_path, 名="p.html"):
    (tmp_path / 名).write_text(
        '<!DOCTYPE html><html><head><meta charset="utf-8"><title>M185</title></head>'
        "<body><p>M185</p></body></html>",
        encoding="utf-8", newline="\n")
    return 名


# ---------------------------------------------------------------------------
# 一、Python / Node 宿主：11 个函数必须**明确报错**（不许静默返回假）
# ---------------------------------------------------------------------------

def _生成报错脚本():
    源 = "导入 窗口\n"
    for 名 in 新函数:
        参数 = ('720, 540' if 名 == "设大小" else
                '180, 120' if 名 == "设位置" else
                '真' if 名 in ("设全屏", "设置顶") else
                '"x.png"' if 名 == "设图标" else
                '0.5' if 名 == "进度" else
                '"标题", "内容"' if 名 == "提示" else "")
        源 += (f"尝试：\n    窗口.{名}({参数})\n捕获 异常 为 e：\n"
               f'    打印("{名}: " + 文本(e))\n')
    return 源


def test_Python宿主十一个函数都明确报错(tmp_path):
    """Python 只有浏览器应用模式 —— 一个都做不到，而且必须**说清楚**。

    🔴 不许「静默返回假」：用户会以为设上了，跑起来才发现窗口没动
    —— 和 M174 那条「白窗口、零报错」是同一类坑。
    """
    (tmp_path / "程序.jsh").write_text(_生成报错脚本(), encoding="utf-8", newline="\n")
    码, 出 = _跑([sys.executable, "-m", "oracle.jishi.cli", "程序.jsh"], tmp_path)
    assert 码 == 0, 出[:900]
    for 名 in 新函数:
        assert f"{名}: " in 出, f"「窗口.{名}」在 Python 宿主上没报错（静默了）：{出[:900]}"
    assert 出.count(做不到特征) == len(新函数), f"报错文案不一致：{出[:900]}"


def test_Node宿主十一个函数都明确报错(tmp_path):
    (tmp_path / "程序.jsh").write_text(_生成报错脚本(), encoding="utf-8", newline="\n")
    字节 = tmp_path / "程序.bc.json"
    r = subprocess.run([sys.executable, "-m", "oracle.jishi.cli", "--dump-bytecode", "程序.jsh"],
                       cwd=str(tmp_path), capture_output=True)
    assert r.returncode == 0, r.stderr.decode("utf-8", "replace")
    字节.write_bytes(r.stdout)
    码, 出 = _跑(["node", str(ROOT / "oracle" / "node" / "index.js"), str(字节)], tmp_path)
    assert 码 == 0, 出[:900]
    for 名 in 新函数:
        assert f"{名}: " in 出, f"「窗口.{名}」在 Node 宿主上没报错：{出[:900]}"
    assert 出.count(做不到特征) == len(新函数), f"报错文案不一致：{出[:900]}"


# ---------------------------------------------------------------------------
# 二、真窗口：设完**读回来**（不是「调了没抛异常」）
# ---------------------------------------------------------------------------

_几何脚本 = """导入 窗口
导入 时间

令 h = 窗口.打开({"标题": "M185 几何", "页面": "%(页)s", "原生": 真, "宽": 420, "高": 320})
打印("打开", h > 0)
时间.睡眠(0.3)

窗口.设大小(720, 540, h)
令 甲 = 窗口.读几何(h)
打印("宽", 甲["宽"])
打印("高", 甲["高"])

窗口.设位置(180, 120, h)
令 乙 = 窗口.读几何(h)
打印("x", 乙["x"])
打印("y", 乙["y"])

窗口.最大化(h)
时间.睡眠(0.3)
打印("最大化", 窗口.读几何(h)["最大化"])

窗口.设全屏(真, h)
时间.睡眠(0.3)
打印("全屏", 窗口.读几何(h)["全屏"])
窗口.设全屏(假, h)
时间.睡眠(0.2)

窗口.设置顶(真, h)
窗口.关闭(h)
打印("done")
"""


@需要原生
def test_真窗口的几何设完能读回来(tmp_path):
    """🔴 每一条都**读回来**，不是「调了没报错」。

    这也是唯一能验 `读几何` 的地方：它和 `设大小`/`设位置` 必须**同一个口径**
    （逻辑像素），否则会出现「设 720 读回 900」这种看着像 bug 的东西。
    """
    页 = _页面(tmp_path)
    (tmp_path / "程序.jsh").write_text(_几何脚本 % {"页": 页}, encoding="utf-8", newline="\n")
    码, 出 = _跑([str(EXE), "程序.jsh"], tmp_path)
    assert 码 == 0, f"退出码 {码}：{出[-1200:]}"
    assert "打开 真" in 出, 出[:600]

    行 = {}
    for 段 in 出.splitlines():
        片 = 段.split()
        if len(片) == 2:
            行[片[0]] = 片[1]
    for 键 in ("宽", "高", "x", "y", "最大化", "全屏"):
        assert 键 in 行, f"脚本没打印「{键}」（读几何 没返回它？）：{出[:800]}"

    # 1) 设 720×540（逻辑），读回来必须是 720×540 —— 差一点点是取整，容差 8
    宽, 高 = float(行["宽"]), float(行["高"])
    assert abs(宽 - 720) <= 8, f"设 720 读回 {宽}（差太多，两边不是同一个口径？）"
    assert abs(高 - 540) <= 8, f"设 540 读回 {高}"

    # 2) 设位置 180,120 —— 窗口管理器可能微调，容差 12
    assert abs(float(行["x"]) - 180) <= 12, f"设位置 180 读回 {行['x']}"
    assert abs(float(行["y"]) - 120) <= 12, f"设位置 120 读回 {行['y']}"

    # 3) 最大化 / 全屏是布尔，没有容差问题
    assert 行["最大化"] == "真", f"最大化 没生效：{出[-600:]}"
    assert 行["全屏"] == "真", f"全屏 没生效：{出[-600:]}"
    # 4) 「设置顶」没有可读回的状态（tao 不给 getter）—— 只验它不炸：
    #    脚本走到 `done` 就是它没抛错。
    assert "done" in 出, "脚本没走完（中途抛错了）"
    assert "done" in 出, "脚本没走完（中途抛错了）"


@需要原生
def test_应用模式的窗口上设几何要报准话(tmp_path):
    """`原生: 假` 的窗口上调几何 ⇒ 报「应用模式…只有原生窗口能做」。

    不是静默返回假：那个窗口**确实存在**，只是没有我们能动的窗口对象 ——
    这两件事必须分开说，否则用户会以为是「窗口不存在」。
    """
    页 = _页面(tmp_path)
    源 = (
        "导入 窗口\n"
        f'令 h = 窗口.打开({{"标题": "M185 应用", "页面": "{页}", "原生": 假}})\n'
        "尝试：\n"
        "    窗口.设大小(600, 400, h)\n"
        "捕获 异常 为 e：\n"
        '    打印("拒绝: " + 文本(e))\n'
        "窗口.关闭(h)\n"
    )
    (tmp_path / "程序.jsh").write_text(源, encoding="utf-8", newline="\n")
    码, 出 = _跑([str(EXE), "程序.jsh"], tmp_path)
    assert 码 == 0, 出[:900]
    assert "拒绝: " in 出, f"应用模式上没有报错（静默了）：{出[:900]}"
    assert "应用模式" in 出 or "原生" in 出, f"报的话不对：{出[:900]}"


