# 五、系统.打开：不存在的目标 ⇒ 假，且**什么都不启动**
# ---------------------------------------------------------------------------

def test_系统打开_不存在就返回假(tmp_path):
    """五执行器同一条规矩（Python 侧 `系统.打开` 的文档写着）：

    不是网址、文件又不存在 ⇒ **返回假，连 ShellExecute / xdg-open 都不碰**。
    「路径打错却弹出一个空白窗口」是这条规矩要挡的那类事故。
    """
    源 = (
        "导入 系统\n"
        '打印("假", 系统.打开("这个文件一定不存在_zzz_185.txt"))\n'
        '打印("空", 系统.打开(""))\n'
    )
    (tmp_path / "程序.jsh").write_text(源, encoding="utf-8", newline="\n")
    码, 出 = _跑([str(EXE), "程序.jsh"], tmp_path)
    assert 码 == 0, 出[:900]
    assert "假 假" in 出, f"不存在的目标应当返回假：{出[:600]}"
    assert "空 假" in 出, f"空目标应当返回假：{出[:600]}"


