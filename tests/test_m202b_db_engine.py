def _写迁移(目录: Path) -> None:
    目录.mkdir(exist_ok=True)
    (目录 / "001_建表.sql").write_text(
        "CREATE TABLE 客户 (名字 TEXT, 城市 TEXT);\n", encoding="utf-8")
    (目录 / "002_加数据.sql").write_text(
        "-- 注释行：分号在注释里不该切句；'甲;乙' 里的分号也一样\n"
        "INSERT INTO 客户 (名字, 城市) VALUES ('甲', '北京');\n"
        "INSERT INTO 客户 (名字, 城市) VALUES ('乙', '上海');\n",
        encoding="utf-8")


def test_迁移按文件名顺序跑_跑过的跳过(tmp_path):
    迁移目录 = tmp_path / "迁移"
    _写迁移(迁移目录)
    出 = _跑(f"""导入 数据库
令 库 = 数据库.打开(":memory:")
打印(数据库.迁移(库, "{迁移目录.as_posix()}"))
打印(数据库.迁移(库, "{迁移目录.as_posix()}"))
打印(数据库.条数(库, "客户"))
打印(数据库.查询(库, "客户")[1]["城市"])
数据库.关闭(库)
""", tmp_path)
    assert 出 == "['001_建表.sql', '002_加数据.sql']\n[]\n2\n上海\n", repr(出)


