def test_回滚把没提交的改动全丢掉(tmp_path):
    出 = _跑("""导入 数据库
令 库 = 数据库.打开(":memory:")
数据库.建表(库, "账", ["金额"])
数据库.插入(库, "账", {"金额": 1})
数据库.开始(库)
数据库.插入(库, "账", {"金额": 2})
打印(数据库.条数(库, "账"))
数据库.回滚(库)
打印(数据库.条数(库, "账"))
数据库.关闭(库)
""", tmp_path)
    assert 出 == "2\n1\n", repr(出)


