def _基石源(库: Path) -> str:
    """子进程要跑的那段基石源码（路径按原样塞进去，免得 Windows 反斜杠作妖）。"""
    return (
        "导入 数据库\n"
        f'令 库 = 数据库.打开("{库.as_posix()}")\n'
        '数据库.建表(库, "账", ["金额"])\n'
        '数据库.插入(库, "账", {"金额": 7})\n'
        '数据库.插入(库, "账", {"金额": 8})\n'
    )


@pytest.mark.skipif(not sys.platform.startswith("win") and sys.platform != "linux",
                    reason="起子进程模拟崩溃；其它平台没验过就不假装验过")
def test_进程被杀之后数据还在(tmp_path):
    """🔴 这一条是 M202b 修掉的**真 bug** 的哨兵。

    来历：引擎原来把日志行**追加进快照文件**（`追加日志(状态["路径"], …)`），
    而重放读的是 `路径 + ".log"`。正常关闭时「紧凑」会把内存状态整份写成快照，
    所以日常用看不出来；**一旦进程没走完关闭**，那些行既不会被重放、又把快照的
    JSON 弄坏 ⇒ 下次打开报「不是有效的 JSON 文本」，数据没了。

    所以这里必须**真杀**：同一进程里怎么写都还在内存里，模拟不出「没关」。
    """
    库 = tmp_path / "崩.db"
    # 子脚本**写到文件里**再跑：内联 `-c` 里嵌三层引号（中英混着）太难读，
    # 出错时那个报错也看不懂（第一版就栽在这上面）。
    子 = tmp_path / "子.py"
    子.write_text(
        "import os, sys\n"
        f"sys.path.insert(0, {str(ROOT)!r})\n"
        "from oracle.jishi.interpreter import run_source\n"
        f"run_source({_基石源(库)!r}, filename='崩.jsh')\n"
        "# 不走 `关闭`：模拟「进程没了」（不紧凑、不清锁）\n"
        "os._exit(9)\n",
        encoding="utf-8")
    r = subprocess.run([sys.executable, str(子)], cwd=str(tmp_path),
                       capture_output=True, timeout=120)
    assert r.returncode == 9, (r.returncode, r.stdout[-300:], r.stderr[-800:])
    assert 库.is_file(), sorted(x.name for x in tmp_path.iterdir())

    # 快照文件本身必须还是**能读的**（首行 + 一段 JSON），别被日志写花了
    首行 = 库.read_text(encoding="utf-8").split("\n")[0]
    assert 首行 == "#基石数据库 快照 格式=1", 首行

    # 崩溃会留下 `.lock`（引擎的锁不做「查进程还在不在」的探活 —— 语言里没有
    # 这个能力，见 CHANGELOG）。所以重开之前要把它删掉：这正是**用户**在崩溃后
    # 要做的那一步，报错消息里给了路径与做法。
    锁 = 库.with_suffix(库.suffix + ".lock")
    assert 锁.is_file(), "崩溃后该留下锁文件（这是设计，不是 bug）"
    锁.unlink()

    出 = _跑(f"""导入 数据库
令 库 = 数据库.打开("{库.as_posix()}")
打印(数据库.条数(库, "账"))
打印(数据库.查询(库, "账"))
数据库.关闭(库)
""", tmp_path)
    assert 出 == "2\n[{'id': 1, '金额': 7}, {'id': 2, '金额': 8}]\n", repr(出)


