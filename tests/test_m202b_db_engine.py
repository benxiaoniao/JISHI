def test_模块里的错报在用户的调用行上(tmp_path):
    """`.jsh` 模块内部的报错，行号必须换成**用户写的那一行**。

    为什么值得单独钉：模块展开后行号整体抬进保留带（`库层行号带`），渲染时
    要换回调用点。换错了用户会拿着一个「在他文件里根本不存在」的行号去改代码
    —— M145（`参数` 那批）就为这件事写过一次。这里只钉树遍历（其余引擎在
    `check_engines` 里对拍）。
    """
    错 = _错("""导入 数据库
令 库 = 数据库.打开(":memory:")
数据库.查询(库, "没有这个表")
""", tmp_path)
    # ⚠️ `错.line` 本身是**字节码里的原始行号**（落在库层保留带上，1000000+）；
    #    换成调用点发生在**渲染时** —— 所以要看渲染出来的那段字，别看属性。
    文 = 错.render()
    assert "测.jsh:3:" in 文, 文
    # 列号要指到调用处（不是第 1 列）—— 源码行这里读不到（`测.jsh` 没落盘），
    # 所以只钉列号；源码行的渲染由 `check_engines` 的真语料对拍盯。
    assert not 文.split("测.jsh:3:")[1].startswith("1\n"), 文
