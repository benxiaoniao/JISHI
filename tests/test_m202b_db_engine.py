# -*- coding: utf-8 -*-
"""M202b：`数据库` 换成**纯基石引擎**（`基石数据库`）之后补的判据。

M112 那一份管的是「模块的语义没变」（句柄 / 顺序 / 类型 / 文案）；这一份管**新的**：

1. **事务四件**（`开始` / `提交` / `回滚` / `用事务`）—— 以前是转给 SQLite 的
   `BEGIN/COMMIT`，现在是引擎自己的「内存快照 + 日志起点」；
2. **`迁移`** —— 跑目录下的 `.sql`，跑过的不重跑；
3. **`查询到表格`** —— 一句 SELECT 直出 `表格`，**0 行也要有表头**；
4. 🔴 **崩溃恢复** —— 进程没走完关闭（被杀 / 报错退出）时，追加日志要靠得住。
   这一条**必须真起一个子进程再杀掉**：同一进程里怎么写都在内存里，「没关」这件事
   模拟不出来。（它也是 M202b 修掉的那条真 bug 的哨兵：日志曾经被写进快照文件。）
5. **报错指向用户的调用点**（`.jsh` 模块里的错不能报成模块内部的行号）。
"""

import io
import os
import subprocess
import sys
from contextlib import redirect_stdout
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from oracle.jishi.errors import JishiError            # noqa: E402
from oracle.jishi.interpreter import run_source       # noqa: E402


def _跑(源码: str, tmp: Path) -> str:
    buf = io.StringIO()
    cwd = os.getcwd()
    os.chdir(tmp)
    try:
        with redirect_stdout(buf):
            run_source(源码, filename="测.jsh")
    finally:
        os.chdir(cwd)
    return buf.getvalue()


def _错(源码: str, tmp: Path) -> JishiError:
    with pytest.raises(JishiError) as ei:
        _跑(源码, tmp)
    return ei.value


