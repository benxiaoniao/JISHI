# -*- coding: utf-8 -*-
"""M130：依赖闭包 / 冲突检测 / `jishi.lock`。

## 这一层解决什么

`安装` 以前**只装你点名的那个包**。装「数学工具」会拿到一个 `导入 基础库`
就报错的包 —— 而错误发生在**运行程序时**，离安装很远，用户很难把两件事联系起来。

补齐的两块：
1. **闭包**：装 A 就连它的依赖一起装，**依赖先装**（拓扑序）；
2. **lock**：把「当时装的那一份」钉住，索引变了也不变。

⚠️ 这里**全部用假索引**，不碰网络 —— 网络不通不该让这条判据红。
真实索引的形状由 `test_m22_packages.py` 和官网仓库的 `test_m49_distribution.py` 盯。
"""

from __future__ import annotations

import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from oracle.jishi import packages as PKG          # noqa: E402


def _包(版本="1.0.0", 依赖=None, 校验和=None):
    项 = {"版本": 版本}
    if 依赖:
        项["依赖"] = 依赖
    if 校验和:
        项["校验和"] = 校验和
    return 项


def _索引(**包) -> dict:
    return {"格式": PKG.INDEX_FORMAT, "版本": 1, "包": 包}


# ---------------------------------------------------------------------------
# 一、闭包与拓扑序
# ---------------------------------------------------------------------------

def test_装一个包会带出它的依赖():
    """这是 M130 的核心行为。"""
    idx = _索引(基础库=_包("1.0.0"), 数学工具=_包("2.0.0", {"基础库": ">=1.0.0"}))
    r = PKG.resolve_closure(idx, ["数学工具"])
    名们 = [n for n, _ in r["装序"]]
    assert 名们 == ["基础库", "数学工具"], f"装序不对：{名们}"
    assert not r["冲突"] and not r["缺"] and not r["环"]


def test_依赖排在前面():
    """拓扑序：**依赖先入列**，否则装到一半 `导入` 会失败。"""
    idx = _索引(
        甲=_包(依赖={"乙": ">=1.0.0"}),
        乙=_包(依赖={"丙": ">=1.0.0"}),
        丙=_包(),
    )
    r = PKG.resolve_closure(idx, ["甲"])
    名们 = [n for n, _ in r["装序"]]
    assert 名们 == ["丙", "乙", "甲"], f"应该是丙→乙→甲，实际 {名们}"


def test_菱形依赖只装一次():
    """A→B、A→C、B→D、C→D：D 只该出现一次（按包名判，不按链条判）。"""
    idx = _索引(
        甲=_包(依赖={"乙": ">=1.0.0", "丙": ">=1.0.0"}),
        乙=_包(依赖={"丁": ">=1.0.0"}),
        丙=_包(依赖={"丁": ">=1.0.0"}),
        丁=_包(),
    )
    r = PKG.resolve_closure(idx, ["甲"])
    名们 = [n for n, _ in r["装序"]]
    assert 名们.count("丁") == 1, f"丁装了 {名们.count('丁')} 次：{名们}"
    assert set(名们) == {"甲", "乙", "丙", "丁"}


def test_多个根包一起解析():
    idx = _索引(甲=_包(依赖={"丙": ">=1.0.0"}), 乙=_包(依赖={"丙": ">=1.0.0"}), 丙=_包())
    r = PKG.resolve_closure(idx, ["甲", "乙"])
    名们 = [n for n, _ in r["装序"]]
    assert 名们.count("丙") == 1
    assert 名们.index("丙") < 名们.index("甲")
    assert 名们.index("丙") < 名们.index("乙")


# ---------------------------------------------------------------------------
# 二、三种「装不上」，必须分开报
# ---------------------------------------------------------------------------

def test_缺依赖要说清是哪条链():
    """「索引里没这个包」和「版本冲突」是两回事，修法完全不同。"""
    idx = _索引(甲=_包(依赖={"不存在的包": ">=1.0.0"}))
    r = PKG.resolve_closure(idx, ["甲"])
    assert r["缺"], "没报缺依赖"
    项 = r["缺"][0]
    assert 项["包"] == "不存在的包"
    assert 项["来自"] == "甲"


def test_冲突不静默挑一个():
    """🔴 两种不相容的约束 ⇒ 报冲突，**不自动挑一个版本**。

    npm 早期那种「随便挑个高的」会让装出来的东西不可预测 —— 教学语言不能学。
    """
    idx = _索引(
        甲=_包(依赖={"丙": ">=2.0.0"}),
        乙=_包(依赖={"丙": "<2.0.0"}),
        丙=_包("1.5.0"),
    )
    r = PKG.resolve_closure(idx, ["甲", "乙"])
    assert r["冲突"], f"该报冲突，实际：{r}"
    项 = r["冲突"][0]
    assert 项["包"] == "丙"
    assert {项["甲"]["来自"], 项["乙"]["来自"]} == {"甲", "乙"}


def test_约束相容就不算冲突():
    """`>=1.0.0` 和 `>=0.5.0` 对 1.5.0 都成立 ⇒ 不该报冲突（别误报）。"""
    idx = _索引(
        甲=_包(依赖={"丙": ">=1.0.0"}),
        乙=_包(依赖={"丙": ">=0.5.0"}),
        丙=_包("1.5.0"),
    )
    r = PKG.resolve_closure(idx, ["甲", "乙"])
    assert not r["冲突"], f"误报冲突：{r['冲突']}"


def test_环能检测出来():
    idx = _索引(甲=_包(依赖={"乙": ">=1.0.0"}), 乙=_包(依赖={"甲": ">=1.0.0"}))
    r = PKG.resolve_closure(idx, ["甲"])
    assert r["环"], "成环没报出来"


