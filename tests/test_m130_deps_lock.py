def test_lock_往返一致():
    idx = _索引(基础库=_包("1.0.0", 校验和="sha256:aa"),
                数学工具=_包("2.0.0", {"基础库": ">=1.0.0"}, 校验和="sha256:bb"))
    r = PKG.resolve_closure(idx, ["数学工具"])
    lock = PKG.lock_from_closure(r)
    文本 = PKG.lock_to_text(lock)
    再读 = PKG.parse_lock(文本)
    assert 再读 == lock
    assert 再读["格式"] == "jishi-lock"
    # 包名排序 ⇒ 同样的闭包永远产出同样的文本（可 diff、可提交）
    assert list(再读["包"]) == sorted(再读["包"])


def test_lock_格式不对要说清():
    """格式错了别让人猜。"""
    with pytest.raises(ValueError, match="格式"):
        PKG.parse_lock('{"格式": "别的", "包": {}}')
    with pytest.raises(ValueError, match="包"):
        PKG.parse_lock('{"格式": "jishi-lock"}')
    with pytest.raises(ValueError, match="JSON"):
        PKG.parse_lock('不是 json')


def test_按_lock_装时版本变了要拦下():
    """索引升版了，lock 锁的是旧的 ⇒ **不能装**（地址指向新版，装了就是错的）。"""
    idx = _索引(数学工具=_包("3.0.0", 校验和="sha256:new"))
    lock = {"格式": "jishi-lock", "版本": 1,
            "包": {"数学工具": {"版本": "2.0.0", "校验和": "sha256:old"}}}
    计划 = PKG.plan_from_lock(lock, idx)
    assert 计划["变"], "版本变了没报"
    assert 计划["变"][0]["锁版本"] == "2.0.0"


def test_按_lock_装时校验和变了要拒绝():
    """🔴 最严重的一种：内容被换过。"""
    idx = _索引(数学工具=_包("2.0.0", 校验和="sha256:被改过"))
    lock = {"格式": "jishi-lock", "版本": 1,
            "包": {"数学工具": {"版本": "2.0.0", "校验和": "sha256:原来的"}}}
    计划 = PKG.plan_from_lock(lock, idx)
    assert 计划["改"], "校验和变了没报"
    assert 计划["改"][0]["包"] == "数学工具"


def test_按_lock_装时索引里没有要报缺():
    idx = _索引()
    lock = {"格式": "jishi-lock", "版本": 1,
            "包": {"已撤下": {"版本": "1.0.0", "校验和": "sha256:x"}}}
    计划 = PKG.plan_from_lock(lock, idx)
    assert 计划["缺"], "缺包没报"


def test_按_lock_装全靠就照单全收():
    idx = _索引(甲=_包("1.0.0", 校验和="sha256:a"), 乙=_包("2.0.0", 校验和="sha256:b"))
    lock = {"格式": "jishi-lock", "版本": 1, "包": {
        "甲": {"版本": "1.0.0", "校验和": "sha256:a"},
        "乙": {"版本": "2.0.0", "校验和": "sha256:b"},
    }}
    计划 = PKG.plan_from_lock(lock, idx)
    assert [n for n, _ in 计划["装序"]] == ["甲", "乙"]
    assert not 计划["缺"] and not 计划["变"] and not 计划["改"]
