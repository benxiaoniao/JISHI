def test_内建方法没被用户方法拆分影响(tmp_path):
    """`Val::UserMethod` 是从 `BoundMethod` 里拆出来的 ——
    内建类型的方法（列表/文本/字典/集合）必须一条不少、位置照旧。"""
    源 = '''
令 列 = [3, 1]
列.追加(2)
列.排序()
打印(列, 列.索引(2), 列.计数(1))
令 文 = " 甲 乙 "
打印(文.去空白(), 文.拆分(" "), 文.包含("甲"))
令 d = {"a": 1}
d.更新({"b": 2})
打印(d.获取("c", 9), d 在 [])
令 集 = 集合([1, 2])
集.添加(3)
打印(长度(集), 3 在 集)
尝试：
    列.没有的方法()
捕获 异常 为 e：
    打印(e.类型)
'''
    出 = _跑(源, tmp_path, "内建").strip().splitlines()
    assert 出[0] == "[1, 2, 3] 1 1", 出
    assert 出[1] == "甲 乙 ['', '甲', '乙', ''] 真", 出
    assert 出[2] == "9 假", 出
    assert 出[3] == "3 真", 出
    assert 出[4] == "类型错误", 出


def test_属性读写的快路径不改变语义(tmp_path):
    """GET_ATTR 的「实例字段命中」内联快路径绕开了 `get_attr` 的分发 ——
    字段 / 类变量 / 方法三者的**优先级**不能因此变。"""
    源 = '''
类 甲：
    同名的 = "类变量"
    函数 初始化(自己)：
        自己.字段 = "实例字段"

令 a = 甲()
打印(a.字段, a.同名的, 甲.同名的)
a.追加的 = 1
打印(a.追加的)
a.追加的 = 2
打印(a.追加的)
# 实例字段盖住同名类变量
a.同名的 = "盖住"
打印(a.同名的, 甲.同名的)
'''
    出 = _跑(源, tmp_path, "属性").strip().splitlines()
    assert 出 == ["实例字段 类变量 类变量", "1", "2", "盖住 类变量"], 出


def test_实例字段表换成快表后多字段仍然对(tmp_path):
    """`Instance.fields` 从 SipHash 换成 FxHash —— 增删改查、键顺序无关的结果要一致。"""
    源 = '''
类 袋：
    函数 初始化(自己)：
        遍历 i 在 范围(50)：
            自己["加" + 文本(i)] = i * 2

令 g = 袋()
令 和 = 0
遍历 i 在 范围(50)：
    令 k = "加" + 文本(i)
    和 = 和 + g.读字段(k)
打印(和)
'''
    # ⚠️ 基石没有「按名字动态读字段」的语法，所以这里改成直接读固定字段
    源 = '''
类 袋：
    函数 初始化(自己)：
        自己.a = 1
        自己.b = 2
        自己.c = 3
        自己.d = 4
        自己.e = 5

令 g = 袋()
打印(g.a + g.b + g.c + g.d + g.e)
遍历 i 在 范围(30)：
    g.a = g.a + 1
打印(g.a)
'''
    出 = _跑(源, tmp_path, "字段").strip().splitlines()
    assert 出 == ["15", "31"], 出


