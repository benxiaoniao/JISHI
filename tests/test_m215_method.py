"""M215：方法调用的四条热路径优化（`实例.方法()` 632 → 347 ns）。

## 这一站动的是什么

19 个基准里**唯一慢于 CPython** 的是「方法调用密集」（0.42x）。拆开量，一次
`c.取()` 花 632 ns，其中跟「语义」有关的只有一点点，其余全是**白花的堆操作与查找**：

| 白花在哪 | 多少 | 改法 |
|---|---|---|
| `CALL` 里 `stack[fn_base].clone()` —— 对 `Box<BoundMethod>` 是**深拷贝**（Box 分配 + `name: String` 分配） | ~100 ns | 改成 `truncate + pop`（move） |
| `BoundMethod::User.name` —— 只为树遍历的一句内部报错服务，VM 全用 `..` | ~30 ns | 删掉（名字在 `Func.name`） |
| `GET_ATTR` 里 `module.names[a].clone()` —— 每次属性访问克隆一个 `String` | ~36 ns | 借常量池 |
| `Box<BoundMethod>` 装用户方法 | ~53 ns | 拆成 `Val::UserMethod`（内联，零分配） |
| `Class.methods` / `Instance.fields` 用默认 SipHash | ~25 ns | 换 `fasthash::快表` |
| `GET_ATTR` 进那个几百行的分发函数 | ~9 ns | 实例字段命中的内联快路径 |

## 判据为什么这么写

这条路径**没有新语法**，风险全在「看起来对、某些形状下错」。所以要钉的是：

1. **语义逐字**：继承 / 覆盖 / `超()` / 方法当值 / 缺属性 / 类变量 / 链式返回，
   一份输出的**每一行**都要对（不是「跑完不报错」）。
2. **`JISHI_JIT=0` 与默认逐字相同**：这次改动不碰 JIT，但方法调用会经过 CALL 的
   JIT 试函数分支（只认 `Val::Func`）—— 开关两侧必须给同一份答案。
3. **性能上界**：不是「比 CPython 快」（没做到，见 CHANGELOG），而是
   「没退回去」：M215 实测 347 ns/次，判据给 1200 ns 的上界。
"""

import os
import subprocess
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent
EXE = ROOT / "rust" / "target" / "release" / (
    "jishi-rs.exe" if os.name == "nt" else "jishi-rs")


def _跑(源: str, tmp: Path, 名: str, 环境: dict | None = None, 超时: int = 180) -> str:
    if not EXE.is_file():
        pytest.skip(f"没有 {EXE}（先 `cargo build --release`）")
    文 = tmp / f"{名}-{os.getpid()}.jsh"
    文.write_text(源, encoding="utf-8", newline="\n")
    env = dict(os.environ)
    env["PYTHONIOENCODING"] = "utf-8"
    if 环境:
        env.update(环境)
    r = subprocess.run([str(EXE), str(文)], capture_output=True, text=True,
                       encoding="utf-8", timeout=超时, env=env)
    assert r.returncode == 0, f"[{名}] 退出码 {r.returncode}：{(r.stderr or '')[:600]}"
    return (r.stdout or "").replace("\r\n", "\n")


