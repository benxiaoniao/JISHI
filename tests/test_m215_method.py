_性能源 = '''
导入 时间
导入 文本 为 文本库
类 计数器：
    函数 初始化(自己, 起)：
        自己.值 = 起
    函数 取(自己)：
        返回 自己.值
令 c = 计数器(3)
令 和 = 0
遍历 i 在 范围(2000)：
    和 = 和 + c.取()
令 起 = 时间.高精度时间()
令 n = 40000
遍历 i 在 范围(n)：
    和 = 和 + c.取()
打印(和, 文本库.小数位((时间.高精度时间() - 起) * 1000000000 / n, 1))
'''


@pytest.mark.计时
def test_方法调用的单次成本(tmp_path):
    """一次 `c.取()` **< 800 ns**。

    实测演进：M214b **632 ns** → M215 **347 ns**（−45%）。同机 CPython 约 105 ns。
    上界给 800 是抓「退回去了」，不是「追上 CPython」——
    剩下的差距在**解释器每步 ~21 ns 的派发**（CPython 约 8 ns/步），
    要靠 JIT 编对象/方法调用，那是 0.4.x 的事（见 CHANGELOG 与 D120）。
    """
    出 = _跑(_性能源, tmp_path, "perf方法", 超时=300).strip().split()
    assert len(出) == 2, 出
    ns = float(出[1])
    assert ns < 800, f"一次方法调用 {ns} ns（M215 实测 347）"
