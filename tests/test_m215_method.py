def test_方法调用语义逐字一致(tmp_path):
    出 = _跑(_语义源, tmp_path, "语义").strip()
    assert 出 == _语义期望, f"期望：\n{_语义期望}\n实得：\n{出}"


def test_JIT开关两侧给同一份答案(tmp_path):
    """`JISHI_JIT=0` 与默认必须逐字相同 —— 方法调用会经过 CALL 的 JIT 试函数分支。"""
    默认 = _跑(_语义源, tmp_path, "jit开").strip()
    关掉 = _跑(_语义源, tmp_path, "jit关", 环境={"JISHI_JIT": "0"}).strip()
    assert 默认 == 关掉, f"JISHI_JIT=0 的答案不同：\n开：{默认}\n关：{关掉}"


