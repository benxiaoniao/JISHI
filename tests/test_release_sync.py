# -*- coding: utf-8 -*-
"""`tools/sync_release.py` 的唯一语义点：**清单合并**。

🔴 为什么单独钉它：清单是**全历史**的索引，同步时如果「覆盖」而不是「合并」，
老版本的用户就**没法回退**了 —— 而这种错在同步当场看不出来（页面一切正常），
只有等某个用户想装回旧版时才会发现。

（脚本的其余部分全是 I/O：下载 / scp / sudo mv / 读回来验证，那些由实际部署验。
 这里只钉那个「错了也不会立刻响」的地方。）
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))

from sync_release import 合并清单  # noqa: E402


def _清单(最新, 版本们):
    return {
        "格式": "jishi-release-index",
        "格式版本": 1,
        "最新": 最新,
        "版本": {v: {"日期": "2026-10-18", "平台": {}} for v in 版本们},
    }


def test_合并保留历史版本():
    """老版本**一个都不能丢**。"""
    旧 = _清单("0.2.4", ["0.2.4"])
    新 = _清单("0.2.5", ["0.2.5"])
    合 = 合并清单(旧, 新)
    assert sorted(合["版本"]) == ["0.2.4", "0.2.5"]
    assert 合["最新"] == "0.2.5"


def test_最新跟着新清单走():
    旧 = _清单("0.2.4", ["0.2.4"])
    新 = _清单("0.2.5", ["0.2.5"])
    assert 合并清单(旧, 新)["最新"] == "0.2.5"


def test_远端还没有清单时按新的来():
    """第一次部署（远端没有清单）不能崩，也不能产出半截结构。"""
    新 = _清单("0.2.5", ["0.2.5"])
    合 = 合并清单({}, 新)
    assert 合["最新"] == "0.2.5" and list(合["版本"]) == ["0.2.5"]
    assert 合["格式"] == "jishi-release-index"


def test_同一个版本再来一次是幂等的():
    """重复部署同一版本（例如上次传到一半失败重跑）不该产生第二个条目。"""
    旧 = _清单("0.2.5", ["0.2.4", "0.2.5"])
    新 = _清单("0.2.5", ["0.2.5"])
    合 = 合并清单(旧, 新)
    assert sorted(合["版本"]) == ["0.2.4", "0.2.5"]
