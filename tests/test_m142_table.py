# -*- coding: utf-8 -*-
"""M142 · `文本.对齐表`：一列值 / 一张表 → 对齐的文本。

## 为什么是这一个函数（而不是计划里那串「补零 / 左右对齐 / 居中…」）

那一串**本来就有**（M50 就补齐了：`补零` `左对齐` `右对齐` `居中` `填充`
`显示宽度` `按行拆分` `去前缀` `去后缀`）。写 M142 前先照「真实需求驱动」试了一遍：
把向量/矩阵打成对齐的表，用现有函数要写**三十行**（扫两遍算列宽、再补空格、
还要记得中文算 2 列）。真缺的是**这一件事**，不是再补几个单点函数。

## 这个文件钉什么

1. **五引擎逐字节一致**（格式化最容易在「舍入 / 宽度」上分叉）；
2. **四舍五入是确定的**：`4.25` 保留 1 位必须给 `4.3`。
   ⚠️ 宿主自带的定点格式化在这里**不一致**（Python `format` 给 `4.2`、JS `toFixed` 给 `4.3`），
   所以实现走的是「十进制字符串进位」，与宿主无关；
3. **中文按 2 列算**（`显示宽度` 的口径），否则表格立刻歪；
4. **数字列右对齐、文本列左对齐**，行尾不留空格。
"""

import io
import sys
from contextlib import redirect_stdout
from pathlib import Path

import pytest

sys.path.insert(0, ".")
sys.path.insert(0, str(Path(__file__).resolve().parent))

from test_m52_jishilib import _engines                    # noqa: E402

from oracle.jishi.errors import JishiError                 # noqa: E402
from oracle.jishi.interpreter import run_source            # noqa: E402


def _跑(源码: str) -> str:
    out = io.StringIO()
    with redirect_stdout(out):
        run_source(源码)
    return out.getvalue()


def _错(源码: str) -> JishiError:
    with pytest.raises(JishiError) as 捕:
        _跑(源码)
    return 捕.value


_用例 = """\
导入 文本 为 文本工具
打印(文本工具.对齐表([1, 22, 333]))
打印("|")
打印(文本工具.对齐表([[1, 2], [40, 500], [7, 6000]]))
打印("|")
打印(文本工具.对齐表([[1.5, 2], [3, 4.25]], 1))
打印("|")
打印(文本工具.对齐表([["名字", "分数"], ["小明", 90], ["小红", 100]]))
打印("|")
"""


def test_五引擎逐字节一致():
    base_label, base = None, None
    for label, run in _engines("m142"):
        ok, out = run(_用例)
        assert ok, f"{label} 本该正常退出却报错：{out[:300]}"
        if base is None:
            base_label, base = label, out
        else:
            assert out == base, (
                f"{label} 与 {base_label} 输出不一致\n{base_label}: {base!r}\n{label}: {out!r}")
    assert base


# ---------------------------------------------------------------------------
# 一、排得对
# ---------------------------------------------------------------------------

def test_一列值就是一行():
    assert _跑("导入 文本\n打印(文本.对齐表([1, 22, 333]))\n") == "1  22  333\n"


def test_列宽自适应():
    出 = _跑("导入 文本\n打印(文本.对齐表([[1, 2], [40, 500], [7, 6000]]))\n")
    assert 出 == " 1     2\n40   500\n 7  6000\n", 出


def test_中文按两列算():
    """「名字」占 4 列 —— 按字符数补的话，下面这行会歪一格。"""
    出 = _跑('导入 文本\n打印(文本.对齐表([["名字", "分"], ["小明", 9]]))\n')
    assert 出 == "名字  分\n小明  9\n", 出


def test_数字列右对齐文本列左对齐():
    出 = _跑('导入 文本\n打印(文本.对齐表([["甲", 1], ["乙乙", 100]]))\n')
    # 第一列是文本 → 左对齐；第二列全是数字 → 右对齐
    # 第一列宽 4（「乙乙」占 4 列）→ 甲 右侧补 2 空格；第二列宽 3 → 1 右对齐补 2 空格
    assert 出 == "甲      1\n乙乙  100\n", 出


def test_行尾不留空格():
    """每行末尾不留空格 —— 这样能直接比对，也能干净地重定向到文件。"""
    行们 = _跑("导入 文本\n打印(文本.对齐表([[1, 2000], [33, 4]]))\n").splitlines()
    assert 行们, "没输出"
    assert all(not 行.endswith(" ") for 行 in 行们), 行们
    # 中间那一列**该留**的空格不能被顺手抹掉（否则就不对齐了）
    assert 行们[0] == " 1  2000", 行们
    assert 行们[1] == "33     4", 行们


# ---------------------------------------------------------------------------
# 二、小数位（确定性四舍五入）
# ---------------------------------------------------------------------------

def test_四舍五入是确定的():
    """`4.25` 保留 1 位 → `4.3`（远离零）。宿主自带格式化会分叉，所以不许用它。"""
    出 = _跑("导入 文本\n打印(文本.对齐表([[4.25, 2.5, 9.99]], 1))\n"
             "打印(文本.对齐表([[0.999]], 2))\n"
             "打印(文本.对齐表([[5]], 2))\n")
    assert 出 == "4.3  2.5  10.0\n1.00\n5.00\n", 出


def test_负数与进位链条():
    出 = _跑("导入 文本\n打印(文本.对齐表([[-4.25, -0.05]], 1))\n")
    assert 出 == "-4.3  -0.1\n", 出


def test_小数位只影响数字():
    """文本格子原样，不会被「补零」成 `甲.00`。"""
    出 = _跑('导入 文本\n打印(文本.对齐表([["甲", 1.5]], 2))\n')
    assert 出 == "甲  1.50\n", 出


# ---------------------------------------------------------------------------
# 三、真实场景：向量与矩阵（这才是它存在的理由）
# ---------------------------------------------------------------------------

def test_矩阵与向量都能直接打():
    出 = _跑(
        "导入 文本\n"
        "导入 矩阵\n"
        "导入 向量\n"
        "打印(文本.对齐表(矩阵.乘([[1, 2], [3, 4]], [[5, 6], [7, 8]])))\n"
        '打印("|")\n'
        "打印(文本.对齐表([向量.加([1, 2, 3], [10, 20, 30])]))\n"
    )
    assert 出 == "19  22\n43  50\n|\n11  22  33\n", 出


# ---------------------------------------------------------------------------
# 四、报错要说清
# ---------------------------------------------------------------------------

def test_空表要报错():
    e = _错("导入 文本\n打印(文本.对齐表([]))\n")
    assert e.exc_name == "值错误", e.exc_name
    assert "空的" in e.message, e.message


def test_传文本要报错():
    e = _错('导入 文本\n打印(文本.对齐表("甲乙"))\n')
    assert e.exc_name == "类型错误", e.exc_name
    assert "不能传文本" in e.message, e.message


def test_行不等长要说清第几行():
    e = _错("导入 文本\n打印(文本.对齐表([[1, 2], [3]]))\n")
    assert e.exc_name == "值错误", e.exc_name
    assert "第 2 行" in e.message, e.message


def test_小数位要合法():
    e = _错("导入 文本\n打印(文本.对齐表([[1]], -1))\n")
    assert e.exc_name == "值错误", e.exc_name
    e2 = _错('导入 文本\n打印(文本.对齐表([[1]], "两位"))\n')
    assert e2.exc_name == "类型错误", e2.exc_name
