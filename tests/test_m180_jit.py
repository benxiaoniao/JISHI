@需要jit
@pytest.mark.parametrize("名", list(用例))
def test_开关jit的输出逐字节相同(名):
    src = 用例[名]
    开 = _跑(src, 开=True)
    关 = _跑(src, 开=False)
    assert 开[0] == 0, f"开 JIT 退出码 {开[0]}（崩了？）\n{开[2][:600]}"
    assert 开 == 关, f"「{名}」两种模式不一致：\n开 {开}\n关 {关}"


@需要jit
def test_六种比较都正确():
    """`< > <= >= == !=` 六种比较各自编一遍，结果必须与解释器一致。

    为什么单列一条：比较码在机器码里是**六个不同的 `Jcc`**（`jl/jg/jle/jge/je/jne`），
    写反一个就是「循环多转一圈」或「一圈都不转」—— 而那种错在小数据上很容易
    看起来是对的（差值恰好被别的运算吃掉）。所以六个都跑，并且**比的是完整输出**。
    """
    src = """
函数 小(n)：
    令 i = 0
    令 s = 0
    当 i < n：
        s = s + 1
        i = i + 1
    返回 s
函数 大(n)：
    令 i = n
    令 s = 0
    当 i > 0：
        s = s + 1
        i = i - 1
    返回 s
函数 小等(n)：
    令 i = 0
    令 s = 0
    当 i <= n：
        s = s + 1
        i = i + 1
    返回 s
函数 大等(n)：
    令 i = n
    令 s = 0
    当 i >= 0：
        s = s + 1
        i = i - 1
    返回 s
函数 相等(n)：
    令 i = 0
    令 s = 0
    当 i == n：
        s = s + 1
        i = i + 1
    返回 s
函数 不等(n)：
    令 i = 0
    令 s = 0
    当 i != n：
        s = s + 1
        i = i + 1
    返回 s
打印(小(3000), 大(3000), 小等(3000), 大等(3000), 相等(0), 不等(3000))
"""
    开 = _跑(src, 开=True)
    关 = _跑(src, 开=False)
    assert 开[0] == 0, 开[2][:600]
    assert 开 == 关, f"不一致：\n开 {开}\n关 {关}"
    # `相等(0)`：i=0、n=0 时 `i == n` 成立 ⇒ 会转一圈（s=1），不是 0 圈
    assert 开[1].split() == ["3000", "3000", "3001", "3001", "1", "3000"], 开[1]


