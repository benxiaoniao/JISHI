# -*- coding: utf-8 -*-
"""M180：JIT v0（整数 `当` 循环编成机器码）。

## 这一组判据守的是什么

JIT 出错的方式和别的功能不一样：**算错个值是最轻的**，重的是进程直接崩
（`0xC0000005` / SIGSEGV）。所以这里的每一条都：

* 用 `subprocess` 带 **timeout** 跑（挂住就是失败，不许拖死整轮）；
* 断言**退出码**（崩了会是非零甚至负数）；
* 把「JIT 开」和「JIT 关」的输出**逐字节比**（多空格都算不一致）。

## 「JIT 真编了」怎么验

不能只看「结果对不对」—— 编不出来时解释器也会给出正确结果，那种判据永远绿。
所以用 `JISHI_JIT=调试` 让宿主把「编好了 / 编不了 / 去优化」打到 stderr，
判据读那几行。**一个从来没编过的 JIT 也能过全部语义判据**，这就是为什么必须
单独盯它。
"""

import os
import platform
import re
import subprocess
import sys
import time
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
EXE = ROOT / "rust" / "target" / "release" / ("jishi-rs.exe" if os.name == "nt" else "jishi-rs")

#: x86-64 才有后端（ARM 上是空操作，见 `rust/src/jit.rs` 的模块文档）。
# 🔴 **M184 起 JIT 有两个后端**（x86-64 / ARM64）⇒ 判据在两种架构上都要真跑。
# CI 的 `macos-latest` 是 arm64 —— 那边跑的是**真的 ARM 机器码**，
# 这是「ARM 后端到底对不对」唯一的一锤定音（本机 x86-64 只能验编码）。
是已知架构 = platform.machine().lower() in ("amd64", "x86_64", "arm64", "aarch64")
需要jit = pytest.mark.skipif(
    not 是已知架构 or not EXE.is_file(),
    reason="JIT 只在 x86-64 / ARM64 上（先在目标机上 cargo build --release）",
)


def _跑(源码: str, 开=True, 调试=False, 参数=(), 超时=120):
    """把源码写进临时文件跑一次 → `(退出码, 标准输出, 标准错误)`。

    ⚠️ **超时是必须的**：JIT 生成的代码如果跳错地方就是一个死循环，
    没有超时会把整轮测试挂死（而不是给一条红色的判据）。
    """
    # 🔴 **文件名由源码内容决定**，两次调用用的是**同一个文件**。
    # 为什么：报错信息里带文件路径（`┌─ /tmp/xxx.jsh:5:15`），用 `NamedTemporaryFile`
    # 的话「开 JIT」和「关 JIT」两次的路径不同 ⇒ 逐字节比较永远失败，
    # 而那是假失败（错误内容其实一模一样）。
    import hashlib
    import tempfile

    路径 = str(
        Path(tempfile.gettempdir())
        / f"jishi_m180_{hashlib.md5(源码.encode('utf-8')).hexdigest()[:12]}.jsh"
    )
    Path(路径).write_text(源码, encoding="utf-8", newline="\n")
    env = dict(os.environ)
    if not 开:
        env["JISHI_JIT"] = "0"
    elif 调试:
        env["JISHI_JIT"] = "调试"
    try:
        r = subprocess.run(
            [str(EXE), 路径, *参数], capture_output=True, env=env,
            timeout=超时, cwd=str(ROOT),
        )
        return r.returncode, r.stdout.decode("utf-8", "replace"), r.stderr.decode("utf-8", "replace")
    except subprocess.TimeoutExpired:
        pytest.fail(f"跑超时（{超时} 秒）—— JIT 生成的代码很可能跳错地方了")
    finally:
        pass


