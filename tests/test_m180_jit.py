@需要jit
def test_溢出会去优化_结果与解释器一致():
    """i64 溢出 → 机器码不写回、直接返回 → 解释器用 i128 从头重跑这个循环。

    🔴 这是整个设计里最容易写错的一处：只要写回了一半，解释器就会拿着
    「跑到中间」的状态从抬头重跑 —— 已经做过的加法会被做第二遍，
    结果偏大，而且**看起来像个正常的数**。

    构造：每次加 1e12，跑 1000 万次 ⇒ 约第 922 万次越过 i64，还在 i128 里。
    """
    src = """
函数 加(n)：
    令 i = 0
    令 s = 0
    当 i < n：
        s = s + 1000000000000
        i = i + 1
    返回 s
打印(加(10000000))
"""
    开 = _跑(src, 开=True, 调试=True, 超时=300)
    关 = _跑(src, 开=False, 超时=300)
    assert 开[0] == 0, f"退出码 {开[0]}\n{开[2][:600]}"
    assert "去优化" in 开[2], f"i64 溢出没触发去优化？\n{开[2][:600]}"
    assert 开[1] == 关[1], f"溢出之后结果不一致：{开[1]!r} vs {关[1]!r}"
    # 10000000 × 1000000000000
    assert 开[1].strip() == "10000000000000000000", 开[1]


@需要jit
def test_i128越界仍然报原来那个错():
    """JIT 只管 i64；真正的 i128 越界该由解释器报，**错误文本与位置一个字不差**。"""
    src = """
函数 翻倍(n)：
    令 s = 1
    令 i = 0
    当 i < n：
        s = s * 2
        i = i + 1
    返回 s
打印(翻倍(400))
"""
    开 = _跑(src, 开=True)
    关 = _跑(src, 开=False)
    assert 开 == 关, f"报错不一致：\n开 {开}\n关 {关}"
    assert 开[0] != 0, "i128 越界应当报错"


