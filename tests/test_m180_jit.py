@需要jit
def test_循环体里有函数调用就不编():
    """⚠️ **这条判据的契约变了两次**，两次都是真变化，不是放宽：

    - **M190**：函数级 JIT 会把被调用的函数编掉 ⇒ 调试输出里多了
      `[jit-func] 加一 编好了`。所以改成**只看循环那一行**。
    - **M191**：**能内联的小函数，循环现在会被编**（那正是 M191 的目标）。
      所以判据换成「**内联不了**的函数调用 ⇒ 循环仍然不编」——
      这里用一个带局部变量的函数（`令 y = …` 产生 `STORE_FAST`），
      它不在内联范围（内联只认「一条 `返回 <纯表达式>`」）。
      「能内联的会被编」由 `test_m191_inline_call.py` 正面钉着。
    """
    src = """
函数 复杂(x)：
    令 y = 1
    返回 x + y
函数 主(n)：
    令 i = 0
    令 s = 0
    当 i < n：
        s = 复杂(s)
        i = i + 1
    返回 s
打印(主(3000))
"""
    开 = _跑(src, 开=True, 调试=True)
    关 = _跑(src, 开=False)
    循环行 = [行 for 行 in 开[2].splitlines() if 行.startswith("[jit] 代码") and "编好了" in 行]
    assert not 循环行, f"内联不了的函数调用，循环不该被编：{循环行}"
    assert 开[:2] == 关[:2], f"不一致：{开[:2]} vs {关[:2]}"


@需要jit
def test_带分支或中断的循环结果对():
    """循环体里有 `如果` / `中断` 时，**结果**必须和解释器一模一样。

    ⚠️ **契约变了**（M182）：v0 那会儿这两个形态不编，所以这里原来还断言
    `"编好了" not in 错`；M182 起它们**会**被编（这是那一站的主菜），
    「编不编」改由 `tests/test_m182_jit_v1.py` 盯。这条现在只守结果。
    """
    分支 = """
函数 带如果(n)：
    令 i = 0
    令 s = 0
    当 i < n：
        如果 i - i / 2 * 2 == 0：
            s = s + i
        否则：
            s = s - i
        i = i + 1
    返回 s
打印(带如果(4000))
"""
    中断 = """
函数 早停(n)：
    令 i = 0
    令 s = 0
    当 i < n：
        如果 i > 100：
            中断
        s = s + i
        i = i + 1
    返回 s
打印(早停(4000))
"""
    for 名, src in (("如果", 分支), ("中断", 中断)):
        a = _跑(src, 开=True, 调试=True)
        b = _跑(src, 开=False)
        assert a[:2] == b[:2], f"「{名}」结果不一致"


