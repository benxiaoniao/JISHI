@需要jit
def test_整数循环明显更快():
    """2 千万次：JIT 必须**显著**快于解释器。

    ⚠️ 阈值取 5x 是**保守**的：本机实测 160x（2 亿次，见 CHANGELOG）。留这么宽
    是因为 CI 机器负载不可控 —— 这条要抓的是「JIT 根本没生效」（那会是 1.0x），
    不是「快得够不够」。
    """
    src = """
函数 累加(n)：
    令 i = 0
    令 s = 0
    当 i < n：
        s = s + i
        i = i + 1
    返回 s
打印(累加(20000000))
"""
    def 量(开):
        最好 = float("inf")
        for _ in range(2):
            t0 = time.perf_counter()
            rc, 出, 错 = _跑(src, 开=开, 超时=300)
            assert rc == 0, 错[:600]
            最好 = min(最好, time.perf_counter() - t0)
        return 最好, 出

    快, 出快 = 量(True)
    慢, 出慢 = 量(False)
    assert 出快 == 出慢, "结果都不一样了"
    倍 = 慢 / 快
    print(f"\n[JIT] 2 千万次整数循环：解释器 {慢 * 1000:.0f} ms → JIT {快 * 1000:.0f} ms "
          f"（{倍:.1f}x）")
    assert 倍 >= 5.0, f"JIT 只快了 {倍:.2f}x —— 它是不是根本没生效？"
