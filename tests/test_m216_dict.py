def test_查询与汇总的语义逐字节(tmp_path):
    """加速不许改语义：空值 / 码点序 / 跨整浮 / 分组口径 / 副本 / 报错。

    ⚠️ 「分组数 2」是**既有行为**（不是 M216 引入的）：契约里 3 行分别是
    整数 1 / 小数 1.0 / 文本 "1"，内部组键是三个（I1 / F1 / S1），但
    `汇总` 的**结果字典**用组值本身当键 —— 整数 1 与小数 1.0 在字典里是同一个键
    ⇒ 后写的覆盖先写的，所以只剩 2 个键。M214b 与 M216 两个二进制逐字一致。
    """
    got = _跑(_语义库源, tmp_path, "dbsem").strip().splitlines()
    assert got[0] == "空值 0 5 1", got          # 空值不命中；非空真=5；非空假=1
    assert got[1] == "大于类1 3 ['丁', '乙', '戊']", got
    assert got[2] == "3==3.0 1 2", got          # 金额 3.0 命中整数 3；< 3 有两条
    assert got[3] == "分组数 2", got            # 见上面的说明（既有行为，未变）
    assert got[4] == "副本 0", got
    assert got[5] == "符号错 值错误", got
    assert got[6] == "字段错 值错误", got


