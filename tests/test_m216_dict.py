# -*- coding: utf-8 -*-
"""M216 · 字典墓碑删除 + 数据库「扫描/打开」热路径。

## 这一站改了什么

| # | 项 | 改前 | 改后 |
|---|---|---|---|
| ① | 字典删 n 个（8000 键删一半） | 91 ms（**O(n²)**） | **6 ms**（O(n)） |
| ② | 字典写入密集（vs CPython） | 1.01x | **1.56x** |
| ③ | 字典查找密集（vs CPython） | 1.26x | **1.59x** |
| ④ | 库 `打开` 20k 行 | 75.7 ms | **23.1 ms** |
| ⑤ | 库 `查询`（带条件，全表扫 20k 行） | 139 ms | **22.2 ms** |
| ⑥ | 库 `汇总` 20k 行 | 149.8 ms | **67.3 ms** |
| ⑦ | 库 `查询`（无条件，返回 20k 行副本） | 41.6 ms | **19.9 ms** |

## 判据为什么这么写

- **① 抓的是复杂度**，不是绝对时间：删一半的耗时随 n 翻倍时只翻倍（线性），
  而不是翻 4 倍（平方）。所以判据是「8000 / 4000 的比值 < 3」+ 绝对上界。
- **②③ 抓的是字典本身**，都在 `tools/bench_vs_python.py` 里逐场景跑（比值抗负载）。
- **④⑤⑥⑦ 抓的是「白花的活」**：打开时读了两遍文件、每行都重新校验条件、
  每行都 `json.转文本` 造分组键 —— 这些都不是「语义必须花的钱」。
  全部是**上界**（绝对值随机器变），并且都留了一倍以上余量。
- **语义**那几条（顺序、长度、删除后插入、浅拷贝、条件报错、分组口径）
  是「加速不许改语义」的底线，逐字节比对。
"""

from __future__ import annotations

import os
import subprocess
import sys
from pathlib import Path

import pytest

sys.path.insert(0, ".")

from conftest import ROOT, rust_exe_path, tmp_bc_path  # noqa: E402

RUST_EXE = rust_exe_path()


def _跑(源: str, tmp: Path, 名: str) -> str:
    文件 = tmp / f"{名}-{os.getpid()}.jsh"
    文件.write_text(源, encoding="utf-8", newline="\n")
    if RUST_EXE.is_file():
        r = subprocess.run([str(RUST_EXE), str(文件)], capture_output=True,
                           text=True, encoding="utf-8", timeout=900)
    else:
        r = subprocess.run([sys.executable, "-m", "oracle.jishi.cli", str(文件)],
                           capture_output=True, text=True, encoding="utf-8",
                           timeout=900, cwd=str(ROOT))
    assert r.returncode == 0, (r.stdout or "") + (r.stderr or "")
    return (r.stdout or "").replace("\r\n", "\n")


