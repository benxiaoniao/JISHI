def test_坏日志仍然按行报错并截掉尾部残行(tmp_path):
    """重放改成「整批解析」之后，**坏库的两条规矩不许变**：

    ① 尾部残行（写到一半崩了）⇒ 打开成功、把残行截掉；
    ② 中间有一行坏了 ⇒ 报 `文件错误`，且消息里带**行号**（不许静默跳过）。

    做法是「先整批解析，失败再退回逐行」——整批那条路只服务正常库，
    坏库走的还是原来那段代码（所以文案一个字都没动）。
    """
    got = _跑(_坏日志源, tmp_path, "badlog").strip().splitlines()
    assert got[0] == "尾部残行后 5", got
    assert got[1] == "中间坏行 文件错误", got
