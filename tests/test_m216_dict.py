_删除源 = '''导入 时间
导入 文本 为 文本库

函数 量删(n)：
    令 d = {}
    遍历 i 在 范围(n)：
        d["键" + 文本(i)] = i
    令 起 = 时间.高精度时间()
    遍历 i 在 范围(n // 2)：
        d.弹出("键" + 文本(i * 2))
    令 删 = (时间.高精度时间()-起)*1000
    令 和 = 0
    遍历 k 在 d.键()：
        和 = 和 + d[k]
    打印(文本库.小数位(删, 3), 长度(d), 和)

量删(4000)
量删(8000)
'''


@pytest.mark.计时
def test_字典删除是线性的不是平方(tmp_path):
    """删除 8000 里的 4000 个：**≤30 ms**，且 8000/4000 的比值 < 3。

    改前是 `Vec::remove`（O(n) 搬移）+ **再遍历整个 index 修正下标**（又一遍 O(n)），
    于是删 n 个 = O(n²)：8000 键删一半实测 **91 ms**，而且斜率是 4 倍。
    现在打墓碑、空洞过半才压一次：**6 ms**、斜率 2 倍。
    """
    出 = _跑(_删除源, tmp_path, "del").strip().splitlines()
    四, 八 = [line.split() for line in 出]
    慢小, 慢大 = float(四[0]), float(八[0])
    assert 慢大 <= 30, f"8000 键删一半用了 {慢大} ms（M216 实测 6；回到 90 就是又搬移了）"
    assert 慢大 / max(慢小, 0.001) < 3.0, (
        f"耗时 4000→{慢小} ms、8000→{慢大} ms，比值 {慢大 / 慢小:.1f}x（>3 说明又回到 O(n²)）")
    # 语义：剩一半、和是偶数项之和
    assert 四[1] == "2000" and 八[1] == "4000", (四, 八)


_语义源 = '''令 d = {"a": 1, "b": 2, "c": 3, "d": 4}
d.弹出("b")
d.弹出("c")
打印(d.键(), d.值(), 长度(d))
# 删了再插：新键接在**末尾**（不是补进空洞）
d["e"] = 5
d["f"] = 6
打印(d.键(), 长度(d))
# 删到触发压缩（空洞过半）
令 大 = {}
遍历 i 在 范围(20)：
    大["k" + 文本(i)] = i
遍历 i 在 范围(15)：
    大.弹出("k" + 文本(i))
打印(大.键(), 长度(大))
# 不可哈希的键（列表）也能删
令 l = {[1]: "甲", [2]: "乙", [3]: "丙"}
l.弹出([2])
打印(l, 长度(l))
# 相等与顺序无关
打印({"a": 1, "b": 2} == {"b": 2, "a": 1}, {"a": 1} == {"a": 2})
# 空字典的边界（`弹出` 缺键是抛错，不是返回空 —— 与 Python 的 pop 不同）
令 无 = {}
打印(长度(无), "x" 在 无)
'''


def test_删除后顺序与长度逐字节(tmp_path):
    """墓碑删除**不许改语义**：剩余顺序是插入序、删后再插接末尾、压缩后仍按序。"""
    got = _跑(_语义源, tmp_path, "sem")
    want = (
        "['a', 'd'] [1, 4] 2\n"
        "['a', 'd', 'e', 'f'] 4\n"
        "['k15', 'k16', 'k17', 'k18', 'k19'] 5\n"
        "{'[1]': None}\n"  # 占位，下面按实际内容断言
    )
    # 列表键那几行的显示形态由 display 决定，别把它钉死；只钉它「删对了」
    lines = got.strip().splitlines()
    assert lines[0] == "['a', 'd'] [1, 4] 2", lines
    assert lines[1] == "['a', 'd', 'e', 'f'] 4", lines
    assert lines[2] == "['k15', 'k16', 'k17', 'k18', 'k19'] 5", lines
    assert "[2]" not in lines[3] and "甲" in lines[3] and "丙" in lines[3] and lines[3].endswith(" 2"), lines
    assert lines[4] == "真 假", lines
    assert lines[5] == "0 假", lines
    assert want  # 保留上面的期望形状说明


