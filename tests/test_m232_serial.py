# -*- coding: utf-8 -*-
"""M232 · `串口`（L-4）—— 能力在 Rust 宿主上，判据只能验到「不炸 + 说人话」。

## 为什么这些判据长得不一样

串口是**硬件**。CI 的 runner 上一个串口都没有，本机也未必有 —— 所以**不能**
把「打开一个口、发几个字节、读回来」当成判据，那在干净环境里必红。

这份文件因此分几层，越往下越弱，但每一层都是**真的**：

| 层 | 验什么 | 环境要求 |
|---|---|---|
| ① 参数校验 | 波特率 0 / 数据位 9 / 校验写错 → 说得清的 `E2005` | 无（三平台都跑） |
| ② 「口不存在」 | `打开("COM99")` → `E2000` + 「没有这个串口」+ 提示 `列出()` | 无（三平台都跑） |
| ③ `列出()` 的形状 | 是列表，每项有 `口` / `描述` / `设备` 三个字段 | 无（三平台都跑） |
| ④ 平台事实 | 非 Windows **不许**再报「还没实现」（D133 把 termios 两端补上了） | Linux / macOS runner |
| ⑤ 真往返 | 发一行、读回来 | **要有真串口**（`JISHI_SERIAL_PORT=COM3` 才跑） |

⚠️ **第 ⑤ 层是空白**（作者本机没有串口/虚拟串口对，Linux/macOS 也没有真机）——
如实标着，不假装验过。有 com0com 虚拟对 / 回环线的机器上设 `JISHI_SERIAL_PORT`
就能跑起来。

📌 三平台"同一句话"是**判据本身要守的东西**：口不存在时 Windows（查注册表）和
Linux/macOS（查路径）的判定方式完全不同，但给用户的错必须长一样 —— 同一条错误在
两台机器上措辞不同，最容易让人怀疑「是不是我环境坏了」。

## 为什么用 `jishi-rs` 子进程而不是 Python 侧

`串口` **故意**不在 Python 宿主上实现（见 `oracle/jishi/stdlib/串口.py` 的说明：
要引 `pyserial`，而本项目第三方依赖已清零）。所以判据统一跑**发行版那个可执行
文件**，这也是真实用户跑的那条路。
"""

import os
import subprocess
import sys
import time
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from oracle.jishi.tokenizer import rust_available                    # noqa: E402

#: 发行版引擎（与本文件同一种找法，和 `test_m230` / `test_m94` 一致）
EXE = ROOT / "rust" / "target" / "release" / (
    "jishi-rs.exe" if os.name == "nt" else "jishi-rs")

_需要引擎 = pytest.mark.skipif(
    not (rust_available() and EXE.is_file()),
    reason="没编 jishi-rs（先 `cargo build --release`）")

def _平台跑不了() -> bool:
    """wasm/别的平台不算 —— 但 Linux / macOS / Windows 都**有实现**（D133）。"""
    return not (sys.platform.startswith("win")
                or sys.platform.startswith("linux")
                or sys.platform == "darwin")


#: 2026-11-25 起 Linux / macOS 也做了（用户定「补上，免得少一部分东西」）⇒
#: 这些参数类判据**三平台都该跑**，不再拿 `_需要win` 排除。
_三平台 = pytest.mark.skipif(_平台跑不了(), reason="这个平台没有串口实现（只有 wasm 类）")


def _跑(src: str, tmp_path: Path) -> tuple[int, str]:
    """跑一段基石源码，返回 `(退出码, stdout+stderr)`。"""
    文件 = tmp_path / f"探针_{os.getpid()}_{abs(hash(src)) % 100000}.jsh"
    文件.write_text(src, encoding="utf-8", newline="\n")
    r = subprocess.run([str(EXE), str(文件)], capture_output=True, timeout=120)
    return r.returncode, (r.stdout + r.stderr).decode("utf-8", "replace")


