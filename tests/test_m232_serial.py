# ⑦ 沙箱里**不许**放行（这条是"故意的拒绝"，不是缺失）
# ---------------------------------------------------------------------------

@_需要引擎
def test_沙箱里导入串口被拒(tmp_path):
    """`--sandbox` 下 `导入 串口` → `E2000`「沙箱不允许导入模块」。

    🔴 沙箱是给 **wasm 页面 / playground** 用的。放行串口等于让一个网页能直接
    打开并读写用户机器上的串口设备 —— 这是硬件访问，跟「读个文件」不是一个量级。
    所以 `串口` **故意不在白名单里**，而且两个宿主（Python / Rust）都必须拒。

    这条判据守两件事：① 别哪天有人顺手把 `串口` 加进白名单；
    ② 两个宿主的口径不许分叉（同一句话、同一个码）。
    """
    文件 = tmp_path / f"沙箱_{os.getpid()}.jsh"
    文件.write_text("导入 串口\n打印(串口.列出())\n", encoding="utf-8", newline="\n")
    r = subprocess.run([str(EXE), str(文件), "--sandbox"],
                       capture_output=True, timeout=120)
    出 = (r.stdout + r.stderr).decode("utf-8", "replace")
    assert r.returncode != 0, f"沙箱里居然放行了串口：\n{出[:400]}"
    assert "沙箱不允许导入模块" in 出, f"拒了，但理由不对：\n{出[:400]}"
    assert "串口" in 出, f"没说清是哪个模块被拒：\n{出[:400]}"
