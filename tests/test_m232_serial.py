# -*- coding: utf-8 -*-
"""M232 · `串口`（L-4）—— 能力在 Rust 宿主上，判据只能验到「不炸 + 说人话」。

## 为什么这些判据长得不一样

串口是**硬件**。CI 的 runner 上一个串口都没有，本机也未必有 —— 所以**不能**
把「打开一个口、发几个字节、读回来」当成判据，那在干净环境里必红。

这份文件因此分三层，越往下越弱，但每一层都是**真的**：

| 层 | 验什么 | 环境要求 |
|---|---|---|
| ① 参数校验 | 波特率 0 / 数据位 9 / 校验写错 → 说得清的 `E2005` | 无 |
| ② 「口不存在」 | `打开("COM99")` → `E2000` + 「没有这个串口」+ 提示 `列出()` | 无 |
| ③ `列出()` 的形状 | 是列表，每项有 `口` / `描述` / `设备` 三个字段 | 无 |
| ④ 真往返 | 发一行、读回来 | **要有真串口**（`JISHI_SERIAL_PORT=COM3` 才跑，默认跳过） |

⚠️ **第 ④ 层在这台机器上是空白**（作者本机没有串口/虚拟串口对）—— 如实标着，
不假装验过。有 com0com 虚拟对的机器上设 `JISHI_SERIAL_PORT` 就能跑起来。

## 为什么用 `jishi-rs` 子进程而不是 Python 侧

`串口` **故意**不在 Python 宿主上实现（见 `oracle/jishi/stdlib/串口.py` 的说明：
要引 `pyserial`，而本项目第三方依赖已清零）。所以判据统一跑**发行版那个可执行
文件**，这也是真实用户跑的那条路。
"""

import os
import subprocess
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from oracle.jishi.tokenizer import rust_available                    # noqa: E402

#: 发行版引擎（与本文件同一种找法，和 `test_m230` / `test_m94` 一致）
EXE = ROOT / "rust" / "target" / "release" / (
    "jishi-rs.exe" if os.name == "nt" else "jishi-rs")

_需要引擎 = pytest.mark.skipif(
    not (rust_available() and EXE.is_file()),
    reason="没编 jishi-rs（先 `cargo build --release`）")

_需要win = pytest.mark.skipif(
    not sys.platform.startswith("win"),
    reason="串口这一版只做了 Windows（Linux/mac 明确未实现，见 D133）")


def _跑(src: str, tmp_path: Path) -> tuple[int, str]:
    """跑一段基石源码，返回 `(退出码, stdout+stderr)`。"""
    文件 = tmp_path / f"探针_{os.getpid()}_{abs(hash(src)) % 100000}.jsh"
    文件.write_text(src, encoding="utf-8", newline="\n")
    r = subprocess.run([str(EXE), str(文件)], capture_output=True, timeout=120)
    return r.returncode, (r.stdout + r.stderr).decode("utf-8", "replace")


# ---------------------------------------------------------------------------
# ① 参数校验：写错要说人话（不依赖硬件）
# ---------------------------------------------------------------------------

#: `(说明, 源码, 期望片段, 期望错误码)`
#:
#: 📌 **错误码分两类，别混**：给错**类型**（波特率传文本）是 `E2002`；
#: 类型对了但**值**不合法（波特率 0、数据位 9）是 `E2005`。这是全语言统一的口径，
#: 串口没另立规矩。
_参数错例 = [
    ("波特率 0", "串口.打开(\"COM1\", 0)", "波特率要是正整数", "E2005"),
    ("波特率负数", "串口.打开(\"COM1\", -9600)", "波特率要是正整数", "E2005"),
    ("数据位 9", "串口.打开(\"COM1\", 115200, 9)", "数据位只能是 5 到 8", "E2005"),
    ("数据位 4", "串口.打开(\"COM1\", 115200, 4)", "数据位只能是 5 到 8", "E2005"),
    ("停止位 4", "串口.打开(\"COM1\", 115200, 8, 4)", "停止位只能是 1 / 2 / 3", "E2005"),
    ("校验写错", "串口.打开(\"COM1\", 115200, 8, 1, \"随便\")", "认不出校验方式", "E2005"),
    ("波特率给文本", "串口.打开(\"COM1\", \"快\")", "要传整数", "E2002"),
    ("数据位给文本", "串口.打开(\"COM1\", 115200, \"八\")", "要传整数", "E2002"),
]


@_需要引擎
@_需要win
@pytest.mark.parametrize("名, 调用, 期望, 码", _参数错例,
                         ids=[c[0] for c in _参数错例])
def test_参数写错要说人话(名, 调用, 期望, 码, tmp_path):
    """参数错 → 有码、有位置，而且**说清合法的取值范围**（不是「参数错误」四个字）。"""
    rc, 出 = _跑(f"导入 串口\n{调用}\n", tmp_path)
    assert rc != 0, f"{名}：居然没报错\n{出[:300]}"
    assert 码 in 出, f"{名}：期望 {码}，实际\n{出[:300]}"
    assert 期望 in 出, f"{名}：没说清怎么改（期望含「{期望}」）\n{出[:300]}"


@_需要引擎
@_需要win
def test_校验写错要列出可用名字(tmp_path):
    """校验认不出来时，**把可用写法列出来** —— 串口参数写错最恶心的是静默用默认值。"""
    rc, 出 = _跑("导入 串口\n串口.打开(\"COM1\", 115200, 8, 1, \"随便\")\n", tmp_path)
    assert rc != 0
    for 名字 in ("无", "奇", "偶", "标记", "空格"):
        assert 名字 in 出, f"提示里少了「{名字}」：\n{出[:400]}"


# ---------------------------------------------------------------------------
# ② 「口不存在」：这条是 CI 上最有价值的（不依赖硬件）
# ---------------------------------------------------------------------------

@_需要引擎
@_需要win
def test_打开不存在的口要说清楚(tmp_path):
    """`打开("COM99")` → 「没有这个串口」+ 提示去看 `列出()`。

    🔴 这里是踩过坑的地方：Windows 对不存在的 COM 名给的是 `ACCESS_DENIED(5)`，
    **不是** `FILE_NOT_FOUND` —— 只看错误码会把「没这个口」报成「被别的程序占着」，
    用户照那句话去关串口助手，永远关不出结果。所以实现改成**查注册表**判断存在性
    （`serial.rs` 的 `打开错误`）。
    """
    rc, 出 = _跑("导入 串口\n串口.打开(\"COM99\")\n", tmp_path)
    assert rc != 0, f"居然打开了 COM99？\n{出[:300]}"
    assert "E2000" in 出, f"错误码不对：\n{出[:300]}"
    assert "没有这个串口" in 出, f"没说「口不存在」：\n{出[:300]}"
    assert "串口.列出()" in 出, f"没告诉用户下一步怎么办：\n{出[:300]}"


@_需要引擎
@_需要win
def test_打开不存在的口不会说成被占用(tmp_path):
    """反面对照：别把「没这个口」说成「被占用」（**上面那个坑的直接判据**）。"""
    rc, 出 = _跑("导入 串口\n串口.打开(\"COM99\")\n", tmp_path)
    assert rc != 0
    assert "被别的程序占着" not in 出, (
        f"把「口不存在」误报成了「被占用」—— 这正是 2026-11-25 修掉的那个坑：\n{出[:400]}")


# ---------------------------------------------------------------------------
# ③ `列出()` 的形状（本机可能空列表，但类型与字段必须对）
# ---------------------------------------------------------------------------

@_需要引擎
@_需要win
def test_列出给的是列表_每项三个字段(tmp_path):
    """`列出()` → 列表；有口的话每项都得有 `口` / `描述` / `设备`。

    ⚠️ **不断言「至少有一个口」** —— CI 的 runner 上一个串口都没有，那是对的。
    这条只验形状：一个都没有时给 `[]`，有的话字段齐全。
    """
    rc, 出 = _跑(
        "导入 串口\n"
        "令 口们 = 串口.列出()\n"
        "打印(类型(口们))\n"
        "遍历 项 在 口们：\n"
        "    打印(类型(项[\"口\"]), 类型(项[\"描述\"]), 类型(项[\"设备\"]))\n",
        tmp_path)
    assert rc == 0, f"列出() 不该报错：\n{出[:400]}"
    行们 = 出.strip().splitlines()
    assert 行们[0] == "列表", f"返回的不是列表：{行们[:2]}"
    for 行 in 行们[1:]:
        assert 行 == "文本 文本 文本", f"字段类型不对：{行!r}"


@_需要引擎
@_需要win
def test_列出不会报错(tmp_path):
    """空机器上 `列出()` 也必须正常返回（把「没有」报成「出错」会让调用方以为环境坏了）。"""
    rc, 出 = _跑("导入 串口\n打印(串口.列出())\n", tmp_path)
    assert rc == 0, f"空机器上 列出() 报错了：\n{出[:400]}"


# ---------------------------------------------------------------------------
# ④ 平台事实：非 Windows 明确报「还没实现」（不是崩、不是静默给空）
# ---------------------------------------------------------------------------

@_需要引擎
@pytest.mark.skipif(sys.platform.startswith("win"),
                    reason="这条验的是**非 Windows** 的行为")
def test_别的平台明确说还没实现(tmp_path):
    """Linux / macOS 上调用 `串口.列出()` → 一句明确的中文错 + 指向路线图。

    📌 这不是「缺失」，是**选择了不写没验证过的 FFI**（termios 的布局在两平台上
    不一样，本机只有 Windows）。见 `serial.rs` 文件头。
    """
    rc, 出 = _跑("导入 串口\n串口.列出()\n", tmp_path)
    assert rc != 0
    assert "还没实现" in 出, f"没说清是「还没实现」：\n{出[:400]}"
    assert "M232" in 出, f"没指向路线图：\n{出[:400]}"


# ---------------------------------------------------------------------------
# ⑤ 真往返（**默认跳过** —— 要有真串口）
# ---------------------------------------------------------------------------

@_需要引擎
@pytest.mark.skipif(not os.environ.get("JISHI_SERIAL_PORT"),
                    reason="没有真串口：设 JISHI_SERIAL_PORT=COM3（或 /dev/ttyUSB0）才跑")
def test_真串口往返(tmp_path):
    """打开一个**真的**串口，写一行、读回来（回环线 / com0com 虚拟对）。

    ⚠️ 这块在作者本机、以及 CI 上都是**空白**（没有串口设备）。算法很简单
    （`打开 → 写文本 → 读行`），但**没被验证过就是没被验证过** —— 写在 CHANGELOG 里。
    有回环线的机器上：把 TX/RX 短接，设环境变量就能跑。
    """
    口 = os.environ["JISHI_SERIAL_PORT"]
    rc, 出 = _跑(
        f"导入 串口\n"
        f"令 句柄 = 串口.打开(\"{口}\")\n"
        f"句柄.写文本(\"基石 M232\\n\")\n"
        f"令 行 = 句柄.读行(2)\n"
        f"句柄.关闭()\n"
        f"打印(行)\n",
        tmp_path)
    assert rc == 0, f"往返失败：\n{出[:500]}"
    assert "基石 M232" in 出, f"读回来的不是发出去的内容：\n{出[:500]}"
