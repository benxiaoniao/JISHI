# ---------------------------------------------------------------------------
# ⑥ Linux PTY 假串口往返（**这是 POSIX 侧唯一的真验证入口**）
# ---------------------------------------------------------------------------
#
# 为什么用 PTY：作者没有 Linux 机器，也没有串口回环线 —— 但 Linux 上「pty 从端」
# 就是一个**真的 tty 设备**（/dev/pts/N），termios / poll / read / write 走的全是
# 同一套系统调用。于是「打开 → 设参数 → 读一行 → 写一行 → 关」这条路**能在 CI 的
# Linux runner 上真跑通**，不需要任何硬件。
#
# ⚠️ 它验不了的：真实 UART 的波特率是否真的生效、DTR/RTS 电平、拔线时的错误 ——
# 那些只能上真设备。这条只证明"协议层的代码是对的"。

@_需要引擎
@pytest.mark.skipif(not sys.platform.startswith("linux"),
                    reason="pty 是 Linux 的东西（Windows 没有；macOS 的 pty 走 /dev/ttys* 另说）")
def test_pty_假串口真往返(tmp_path):
    """用一个 PTY 从端当「串口」：引擎写一行、我们从主端读回来；我们再发一行、引擎读回来。

    🔴 这条覆盖的是 POSIX 实现的**全部关键路径**：`open(O_NONBLOCK|O_NOCTTY)` →
    `ioctl(TCGETS/TCSETS)` 设 termios → `poll` 等数据 → `read`/`write` → `close`。
    本机（Windows）跑不了，**CI 的 linux runner 一推就会跑**——那是这两端第一次
    真被验证。
    """
    import select
    import time

    主, 从 = os.openpty()
    try:
        从名 = os.ttyname(从)
        # ⚠️ **不能先写再打开**：`串口.打开` 会 `tcflush(TCIOFLUSH)` 清掉驱动里
        #    残留的旧字节（那是防"上一次会话的脏数据"的必要动作），提前写的会一起被丢掉。
        #    所以先起进程，等它打开并设好参数，再从主端发一行。
        脚本 = (
            f"导入 串口\n"
            f"令 板 = 串口.打开(\"{从名}\", 115200)\n"
            f"打印(\"opened\")\n"
            f"令 行 = 板.读行(8)\n"
            f"打印(\"读到: \" + 行)\n"
            f"板.写文本(\"PONG\\n\")\n"
            f"板.关闭()\n"
        )
        文件 = tmp_path / f"pty_{os.getpid()}.jsh"
        文件.write_text(脚本, encoding="utf-8", newline="\n")
        进程 = subprocess.Popen([str(EXE), str(文件)],
                                stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
        # 等它打开 + 设完参数（固定 1.2 秒；`open` 在 pty 上是毫秒级的，足够）
        time.sleep(1.2)
        os.write(主, "PING\n".encode())
        输出, _ = 进程.communicate(timeout=30)
        rc = 进程.returncode
        出 = 输出.decode("utf-8", "replace")
        assert rc == 0, f"PTY 上打开/读/写真失败了：\n{出[:600]}"
        assert "读到: PING" in 出, f"引擎没从「串口」读到我们发的那行：\n{出[:600]}"

        # ② 引擎往「串口」写的那行，我们从主端应该收到
        收到 = b""
        截止 = time.time() + 5
        while time.time() < 截止 and b"PONG" not in 收到:
            r, _, _ = select.select([主], [], [], 0.5)
            if r:
                收到 += os.read(主, 4096)
        assert b"PONG\n" in 收到, f"没从 PTY 主端收到引擎写出的字节：{收到!r}"
    finally:
        os.close(主)
        os.close(从)


