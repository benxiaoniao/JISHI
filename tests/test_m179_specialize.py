# 二、缓存不许泄漏（M179 判据里的硬要求）
# ---------------------------------------------------------------------------

def test_交替类型十万次不崩也不塌(tmp_path):
    """同一个循环里**交替**走「文本下标 / 字典 / 列表 / 内建 / 用户函数」十万轮。

    这是「缓存不许泄漏」那条判据：
    - **不崩**：缓存命中/失效的边界不能踩到借用冲突或越界；
    - **不塌**：交替类型会让所有单态缓存反复失效，但**不能因此慢一个量级** ——
      所以除了正确性，还给一个**很宽松**的墙上时间上限（这台机器上约 3 秒，
      上限放到 60 秒；真出现「每次失效都重建整张表」那种退化会远远超过它）。
    """
    起 = time.perf_counter()
    出 = _跑('''
函数 加一(x)：
    返回 x + 1

令 文 = "一二三四五"
令 甲 = [1, 2, 3]
令 字 = {}
令 和 = 0
令 i = 0
当 i < 100000：
    令 j = i % 5
    和 = 和 + 长度(文[j])          # 文本下标（单字符缓存）
    字[j] = j                      # 字典写
    和 = 和 + 字[j]                # 字典读
    甲.追加(j)                     # 列表方法
    和 = 和 + 长度(甲)             # 内建调用
    和 = 加一(和)                  # 用户函数调用
    如果 j == 4：
        甲 = [1, 2, 3]
    i = i + 1
打印(和)
''', tmp_path, timeout=120)
    用时 = time.perf_counter() - 起
    # 每一轮：1 + j + 1 + 长度(甲) + 1 累加；甲 每 5 轮清一次
    assert 出.strip().splitlines()[-1].isdigit(), 出[-200:]
    assert 用时 < 60, f"交替类型十万轮用了 {用时:.1f} 秒（超过 60 秒上限，缓存可能退化了）"


def test_实参缓冲在嵌套调用里不串(tmp_path):
    """`f(g(1), h(2))`、默认值、命名参数、方法调用混在一起 —— 实参不能串。

    🔴 `VM.arg_buf` 是**复用**的缓冲：外层调用的实参还在缓冲里时，
    内层调用（`g(1)`）会把它取走。这条就是盯住「取走之后外层还能不能拿到对的值」。

    ⚠️ 期望值是**手算**的，写在注释里 —— 第一版我把最后一个写成 77（应该是 84），
    于是顺手加了一条「逐值」判据；这次直接一次写对，不再留一条专门纠错的测试。
    """
    出 = _跑('''
函数 合(甲, 乙)：
    返回 甲 * 10 + 乙

函数 加倍(x, 倍数 = 2)：
    返回 x * 倍数

类 盒：
    函数 初始化(自身, 值)：
        自身.值 = 值
    函数 拿(自身)：
        返回 自身.值

打印(合(加倍(1), 加倍(2)))            # 合(2, 4)   = 24
打印(合(合(1, 2), 合(3, 4)))          # 合(12, 34) = 154
打印(加倍(5), 加倍(5, 3), 加倍(5, 倍数 = 4))
令 b = 盒(7)
打印(合(b.拿(), 加倍(b.拿())))        # 合(7, 14)  = 84
''', tmp_path)
    assert "24" in 出, 出
    assert "154" in 出, 出
    assert "10 15 20" in 出, 出
    assert "84" in 出, 出


