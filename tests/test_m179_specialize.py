def test_原生Rust尺子的每对程序都等价(tmp_path):
    """`tools/bench_vs_rust.py` 的 8 对程序：**同一道题、同一个输出**。

    这条不验快慢（机器差异太大，那是给人看的），只验**等价性** ——
    尺子的前提是「两边在算同一件事」。尺子一旦不等价，报出来的倍数就是假的
    （第一次写的时候 Rust 那份被 LLVM 折掉了整段循环，差 43.9x，就是这条该拦住的）。

    ⚠️ 需要 `rustc`；没有就跳过（它是开发期工具，不参与构建）。
    """
    import importlib.util

    if not __import__("shutil").which("rustc"):
        pytest.skip("没有 rustc —— 这把尺子量不了（工具本身会提示）")

    规格 = importlib.util.spec_from_file_location(
        "bench_vs_rust", ROOT / "tools" / "bench_vs_rust.py")
    工具 = importlib.util.module_from_spec(规格)
    规格.loader.exec_module(工具)

    exe = rust_exe_path()
    if not exe.is_file():
        pytest.skip("没有 jishi-rs")

    d = tmp_path
    坏 = []
    for 名, (jsh, rs源, _建议) in 工具.场景.items():
        可执行 = 工具.编一个(名, rs源, 1)
        (d / f"{名}.jsh").write_text(jsh, encoding="utf-8", newline="\n")
        a = subprocess.run([str(exe), f"{名}.jsh"], cwd=str(d), capture_output=True,
                           timeout=180, input=b"")
        b = subprocess.run([str(可执行)], cwd=str(d), capture_output=True,
                           timeout=180, input=b"")
        oa = (a.stdout + a.stderr).decode("utf-8", "replace").replace("\r\n", "\n").strip()
        ob = (b.stdout + b.stderr).decode("utf-8", "replace").replace("\r\n", "\n").strip()
        if oa != ob:
            坏.append(f"{名}：基石 {oa[:40]!r} vs Rust {ob[:40]!r}")
    断言 = "这些对的输出不一样（尺子比的不是同一件事）：\n" + "\n".join(坏)
    assert not 坏, 断言
