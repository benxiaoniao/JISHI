# 一、单字符缓存：不许改变语义
# ---------------------------------------------------------------------------

def test_字符缓存放宽了也不能出错(tmp_path):
    """ASCII / 中文 / emoji（代理对）/ 组合字符 / 空文本 —— 取出来的都必须是**一个码点**。

    🔴 缓存按「码点低 8 位」直接映射，所以 ASCII 之间会互相顶掉槽位、
    emoji 这种 4 字节码点也一样。这条判据就是盯住「顶掉之后返回的还是不是对的那个」——
    缓存写错最典型的表现是「第一个字符对了，后面几个全变成它」。
    """
    出 = _跑('''
令 甲 = "abc"
令 乙 = "一二三"
令 丙 = "😀😁😂"
令 丁 = "éàü"
打印(甲[0], 甲[1], 甲[2])
打印(乙[0], 乙[1], 乙[2])
打印(丙[0], 丙[1], 丙[2])
打印(丁[0], 丁[1], 丁[2])
打印(长度(丙[0]), 长度(丙[2]))
打印(甲[-1], 乙[-1], 丙[-1])
打印(乙[0] == "一", 丙[0] == "😀", 甲[0] == "b")
''', tmp_path)
    assert "a b c" in 出, 出
    assert "一 二 三" in 出, 出
    assert "😀 😁 😂" in 出, 出
    assert "é à ü" in 出, 出
    # emoji 是 4 字节 / 1 个码点：长度必须是 1（不是 2、不是 4）
    assert "1 1" in 出, 出
    assert "c 三 😂" in 出, 出
    assert "真 真 假" in 出, 出


def test_字符缓存被顶掉之后仍然正确(tmp_path):
    """一次走过 **超过 256 个不同字符**（缓存槽位全被顶掉），结果仍要正确。

    直接映射只有 256 个槽，字符一多就互相顶。这条把「顶掉」放大到必然发生：
    取 300 个不同字符，再回头读前几个 —— 缓存里早没了，不能返回错的值。
    """
    出 = _跑('''
令 文 = ""
令 i = 0
当 i < 300：
    文 = 文 + 文本(字符(65 + i % 26)) + 文本(i % 10)
    i = i + 1
打印(长度(文))
令 首 = 文[0]
令 尾 = 文[长度(文) - 1]
打印(首, 尾)
令 对 = 0
遍历 c 在 文：
    如果 c == "A"：
        对 = 对 + 1
打印(对)
''', tmp_path)
    # 300 轮、每轮 2 个字符
    assert "600" in 出, 出
    assert "A 9" in 出, 出        # 首字符 "A"、末字符 "9"
    assert "12" in 出, 出         # 26 个字母循环 300 次 → A 出现 12 次（300/26 上取整）


def test_遍历文本与下标给的是同一个值(tmp_path):
    """`遍历`（快照迭代器）和 `文[i]`（下标）走的是**两条路**，但必须给出一样的值。

    两条路现在共用 `单字符` 缓存 —— 这条钉住「共用没把谁弄坏」。
    """
    出 = _跑('''
令 文 = "甲a乙b😀c"
令 从遍历 = ""
遍历 c 在 文：
    从遍历 = 从遍历 + c
令 从下标 = ""
令 i = 0
当 i < 长度(文)：
    从下标 = 从下标 + 文[i]
    i = i + 1
打印(从遍历 == 从下标, 从遍历 == 文)
''', tmp_path)
    assert "真 真" in 出, 出


