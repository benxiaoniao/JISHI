# -*- coding: utf-8 -*-
"""M179：单态特化（内联缓存思路）+ 「vs 原生 Rust」那把尺子。

## 这一站做了什么（三处，都是**先量后改**）

微探针（同一条循环只换循环体那一条，量每条指令的边际成本）先量出贵的地方：

| 操作 | 改之前 | 改之后 |
|---|---|---|
| 文本下标 `文[i]` | 179 ns | **103 ns** |
| 内建调用 `长度(甲)` | 146 ns | **89 ns** |
| 函数调用 `加一(i)` | 266 ns | **224 ns** |
| 属性取 `甲.追加`（不出现在基准里） | 187 ns | 175 ns |

1. **单字符 `Val` 缓存**（`单字符`）：`文[i]` 与 `遍历 字 在 文` 每取一个字符都要
   `to_string()` + `Rc<str>` 两次堆分配。现在同一个字符只造一次（256 槽直接映射）。
2. **实参复用缓冲**（`VM.arg_buf`）：`CALL` 原来每次 `to_vec()` 一次 malloc/free。
3. **命名参数那条路少一次拷贝**：`map_kwargs` 在**没有命名参数**时也会
   `args.to_vec()` —— 每次内建调用两次堆分配变成一次。

## 判据分两类

- **语义**：缓存是「记住上次的结果」，它最危险的失败模式是**改变语义**
  （缓存命中却给了不一样的值）和**泄漏**（无限增长 / 交替类型时崩）。
  这两类都要有判据，而且要在**没有桌面**的环境也能跑。
- **尺子**：`tools/bench_vs_rust.py` 的 8 对程序必须**输出逐字相同** ——
  那是「比的同一件事」的前提。这条不验数字（机器差异太大），只验等价性。
"""

import os
import subprocess
import sys
import time
from pathlib import Path

import pytest

sys.path.insert(0, ".")

from conftest import rust_exe_path  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
EXE = ROOT / "rust" / "target" / "release" / (
    "jishi-rs.exe" if os.name == "nt" else "jishi-rs")


def _跑(源: str, tmp_path, timeout=180, 参数=None) -> str:
    p = tmp_path / "程序.jsh"
    p.write_text(源, encoding="utf-8", newline="\n")
    exe = rust_exe_path()
    if not exe.is_file():
        pytest.skip("没有 jishi-rs（先 cargo build --release）")
    cmd = [str(exe), "程序.jsh"] + (参数 or [])
    r = subprocess.run(cmd, cwd=str(tmp_path), capture_output=True, timeout=timeout,
                       input=b"")
    out = (r.stdout + r.stderr).decode("utf-8", "replace")
    assert r.returncode == 0, f"退出码 {r.returncode}：{out[:800]}"
    return out


