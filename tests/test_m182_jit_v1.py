# -*- coding: utf-8 -*-
"""M182：JIT v1（抽出 IR + 循环体分支 + `遍历` + `//` `%`）。

## 这一组判据守的是什么

v0 只会编「一个 `当` 循环 + 一个比较」。v1 多了三种**会改变控制流**的东西：

| 新编的 | 出错时的样子 |
|---|---|
| 循环体里的 `如果 / 否则 / 否则如果` | 分支失效 ⇒ **数字不对但不报错**（M182 第一版就撞过） |
| `中断` / `继续` | 跳错地方 ⇒ 死循环（`中断` 落到回跳上） |
| `遍历` 整数列表 | 少弹一个迭代器 / 摊平错位 ⇒ 后面的代码全乱 |
| `//` `%` | 截断当成向下取整 ⇒ `-7 // 3` 给 `-2`（应当是 `-3`） |

所以这里的每一条都：

* 用 `subprocess` 带 **timeout**（挂住 = 失败，别拖死整轮）；
* 断言**退出码**（段错误是非零甚至负数）；
* 「开 JIT / 关 JIT」的输出**逐字节比**（多一个字符都算不一致）；
* 单独盯「**真的编了**」—— 编不出来时解释器也会给出正确结果，那种判据永远绿。

⚠️ **故意不编的必须验**：`x = (a < b)`（布尔值不在 JIT 的类型里）、浮点、文本、
调用、下标。它们「没编」才是对的；哪天悄悄编了，语义就变了。
"""

import hashlib
import os
import platform
import re
import subprocess
import tempfile
import time
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
EXE = ROOT / "rust" / "target" / "release" / ("jishi-rs.exe" if os.name == "nt" else "jishi-rs")

# 🔴 **M184 起 JIT 有两个后端**（x86-64 / ARM64）⇒ 判据在两种架构上都要真跑。
# CI 的 `macos-latest` 是 arm64 —— 那边跑的是**真的 ARM 机器码**，
# 这是「ARM 后端到底对不对」唯一的一锤定音（本机 x86-64 只能验编码）。
是已知架构 = platform.machine().lower() in ("amd64", "x86_64", "arm64", "aarch64")
需要jit = pytest.mark.skipif(
    not 是已知架构 or not EXE.is_file(),
    reason="JIT 只在 x86-64 / ARM64 上（先在目标机上 cargo build --release）",
)


def _跑(源码: str, 开=True, 调试=False, 超时=120):
    """把源码写进临时文件跑一次 → `(退出码, 标准输出, 标准错误)`。

    🔴 文件名由**源码内容**决定：报错文本里带路径，两次用不同路径的话
    逐字节比较永远假失败（M180 用血换的）。
    """
    路径 = str(
        Path(tempfile.gettempdir())
        / f"jishi_m182_{hashlib.md5(源码.encode('utf-8')).hexdigest()[:12]}.jsh"
    )
    Path(路径).write_text(源码, encoding="utf-8", newline="\n")
    env = dict(os.environ)
    if not 开:
        env["JISHI_JIT"] = "0"
    elif 调试:
        env["JISHI_JIT"] = "调试"
    try:
        r = subprocess.run([str(EXE), 路径], capture_output=True, env=env,
                           timeout=超时, cwd=str(ROOT))
    except subprocess.TimeoutExpired:
        pytest.fail(f"跑超时（{超时} 秒）—— 生成的机器码很可能跳错地方了")
    return (r.returncode,
            r.stdout.decode("utf-8", "replace"),
            r.stderr.decode("utf-8", "replace"))


