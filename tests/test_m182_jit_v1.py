@需要jit
def test_去优化以后结果仍然对():
    """i64 溢出 ⇒ 去优化（不写回）⇒ 解释器用 i128 从头重跑。

    为什么要这一条：如果机器码「写回一半」再退出，解释器会把已经做过的
    乘法再做一遍 —— 结果是**一个看似正常、其实翻倍的数**。3^49 是能精确
    对上的（超过 i64 但在 i128 里）。
    """
    源 = """
令 i = 0
令 s = 1
当 i < 1600：
    如果 i > 1550：
        s = s * 3
    i = i + 1
打印(s)
"""
    码, 出, _ = _跑(源)
    assert 码 == 0
    assert 出.strip() == str(3 ** 49), f"得 {出.strip()}，应当是 3^49 = {3 ** 49}"
    _, _, 错 = _跑(源, 调试=True)
    assert "去优化" in 错, f"没走上去优化的路（那这条判据就白测了）：{错[-400:]}"


