@需要jit
@pytest.mark.parametrize("名", list(用例))
def test_语义逐字节相同(名):
    """开 JIT / 关 JIT 的输出与退出码必须**一字不差**。"""
    源 = 用例[名]
    码1, 出1, 错1 = _跑(源, 开=True)
    码2, 出2, 错2 = _跑(源, 开=False)
    assert 码1 == 码2 == 0, f"退出码不同：{码1} vs {码2}\n{错1[-600:]}"
    assert 出1 == 出2, f"输出不同：\nJIT：[{出1}]\n解释：[{出2}]"
    assert 错1 == 错2, f"stderr 不同：\nJIT：{错1[-400:]}\n解释：{错2[-400:]}"


