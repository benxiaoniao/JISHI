# ---------------------------------------------------------------------------
# 六、M182 修的老缺陷：编好的循环要能**反复进**
# ---------------------------------------------------------------------------

@需要jit
@pytest.mark.计时
def test_同一段循环反复调用也走JIT():
    """🔴 M180 的缺陷：`记一步` 只在计数**刚好到阈值**那一次返回真 ⇒ 编好之后
    这个循环**再也没进过 JIT**。函数被调用 N 次，只有跨阈值那一次受益。

    M182 把「已编好」钉成计数里的哨兵，每次回边都进。这条用**时间**验。

    ⚠️ **规模要够大**：进程启动固定约 20 ms，60×3000 圈那种量级下
    「关」也就 44 ms，「开」21 ms —— 比值被启动开销压到 2x 左右（实测过一次
    1.85x 假红）。所以这里用 60×40000，让循环本身远超启动。
    """
    源 = """
函数 累加(n)：
    令 i = 0
    令 s = 0
    当 i < n：
        s = s + i
        i = i + 1
    返回 s
令 总 = 0
令 k = 0
当 k < 60：
    总 = 总 + 累加(40000)
    k = k + 1
打印(总)
"""

    def 量(开: bool) -> float:
        最好 = 1e9
        for _ in range(3):
            t0 = time.perf_counter()
            码, 出, _ = _跑(源, 开=开)
            assert 码 == 0
            最好 = min(最好, time.perf_counter() - t0)
        return 最好

    关 = 量(False)
    开 = 量(True)
    assert 开 < 关 * 0.3, (
        f"反复调用没吃到 JIT：开 {开 * 1000:.0f} ms / 关 {关 * 1000:.0f} ms"
        f"（比值 {关 / 开:.2f}x，要求 ≥3.3x）")
