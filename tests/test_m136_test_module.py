#: 五引擎共用的那段程序：**必须退出码 0**（`_five` 的 Node/Rust 那两路会断言 returncode）。
一致程序 = """导入 测试

函数 前()：
    打印("前")

函数 后()：
    打印("后")

函数 检查(组)：
    测试.相等(组[0] + 组[1], 组[2])

函数 不适用()：
    测试.跳过("造出来的：这个平台没有")

测试.每例前(前)
测试.每例后(后)
测试.用例们("加法", [[1, 1, 2], [2, 3, 5]], 检查)
测试.用例("平台相关", 不适用)
测试.汇总()
"""


def test_五引擎逐字一致_用例们加跳过加前后置():
    """树遍历 / Python VM / C VM / Node / Rust —— 五个执行器输出必须一模一样。

    ⚠️ **Node 以前连 `测试` 模块都没有**（`导入 测试` → E0302），这条同时也钉住
    「补齐之后三边语义真的一样」，而不只是「能导入」。
    """
    if not RUST.is_file():
        pytest.skip(f"没构建 {RUST.name}（cd rust && cargo build --release）")
    基准 = _five(一致程序, RUST)
    # 顺带核一下内容：别五个都错成一样（那就不是「一致」而是「一起错」）
    assert 基准.count("前") == 3, f"前后置该跑 3 次：\n{基准}"
    assert "全部通过" in 基准, 基准
    assert "3 个用例，跳过 1" in 基准, 基准


def test_三宿主_失败明细与错误码一致():
    """失败路径也要一致：`✗ 名字[2] · 相等：期望 …` 与末尾 `错误 E2008`。

    ⚠️ 必须**分开收两条流**（`_five` 只比 stdout）：失败明细走 stderr。
    """
    源 = """导入 测试

函数 检查(组)：
    测试.相等(组[0] + 组[1], 组[2])

测试.用例们("加法", [[1, 1, 2], [3, 4, 9]], 检查)
测试.汇总()
"""
    文件 = tmp_bc_path(Path(tempfile.gettempdir()) / "m136_fail.jsh")
    文件.write_text(源, encoding="utf-8", newline="\n")
    字节 = tmp_bc_path(Path(tempfile.gettempdir()) / "m136_fail.json")
    字节.write_text(serialize.dumps(compile_source(源, "<t>")),
                    encoding="utf-8", newline="\n")

    结果 = {}
    for 名, 命令 in (
        ("python", [PY, "-m", "oracle.jishi.cli", str(文件)]),
        ("rust", [str(RUST), str(文件)]),
        ("node", ["node", str(ROOT / "oracle" / "node" / "index.js"), str(字节)]),
    ):
        if 名 == "rust" and not RUST.is_file():
            pytest.skip(f"没构建 {RUST.name}")
        r = subprocess.run(命令, cwd=str(ROOT), capture_output=True, text=True,
                           encoding="utf-8", errors="replace", timeout=180)
        assert r.returncode == 1, f"{名}：有失败就该退 1，实际 {r.returncode}"
        结果[名] = (r.stdout, r.stderr)

    # ⚠️ **只比 stderr 的前两行**（明细 + 错误首行），不逐字比整段：
    #    错误横幅下面那段「┌─ 文件:行:列 + 源码行 + 脱字符」本来就有**既有分叉** ——
    #    字节码里**不带源码文本**，所以 Node / Rust 那两路画不出 `7 │ 测试.汇总()`
    #    这行（`check_engines` 早就把「报错渲染」单列一类，就是这件事）。
    #    这里要钉的是**「说了什么」**（哪条用例、期望什么、什么错误码），不是画得像不像。
    基准 = 结果["python"]
    for 名 in ("rust", "node"):
        出, 错 = 结果[名]
        assert 出 == 基准[0], f"{名} 的 stdout 与 python 不一致：{出!r} != {基准[0]!r}"
        assert 错.splitlines()[:2] == 基准[1].splitlines()[:2], (
            f"{名} 的失败明细与 python 不一致\n"
            f"  期望：{基准[1].splitlines()[:2]}\n  实际：{错.splitlines()[:2]}")
    assert "加法[2]" in 基准[1], 基准[1]
    assert "错误 E2008" in 基准[1], "末尾必须是断言错误（E2008），不是 E2000"
