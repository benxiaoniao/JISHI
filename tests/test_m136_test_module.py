# -*- coding: utf-8 -*-
"""M136：`测试` 模块补三件事 —— **参数化、跳过、前后置**。

## 为什么要补

`测试` 原来只有「一条用例 = 一个函数」。真要写一整套测试，会立刻撞上三堵墙：

| 撞墙 | 症状 | 现在 |
|---|---|---|
| 同一件检查要喂十组数据 | **为每组写一个函数**（十份一样的函数体） | `测试.用例们("加法", 数据们, 检查加法)` |
| 某个用例在当前环境测不了 | 要么删掉它、要么让它红 —— **两种都在撒谎** | `测试.跳过("这个平台没有……")` |
| 每个用例都要建临时目录/开连接 | 每个函数开头结尾抄一遍，**漏一个就污染后面的用例** | `测试.每例前` / `测试.每例后` |

## 四条语义（每一条都有判据）

1. **`用例们` 每组一条用例**，名字带序号 `加法[1]`（从 1 数）；**单独一组失败不连累其它**；
2. **整组作为一个参数**传进去（不展开）—— 展开的话「一组两个元素」和「两个参数」就分不清了；
3. **`跳过` 不算通过、也不算失败**：单独计数、单独打印 `⏭`，且**后面的断言不再执行**
   （它的意思是「这条不适用」，不是「跳过一小段」）；**在用例外面调它直接报错**
   （否则等于把整份脚本静默跳过）；
4. **后置一定跑**（用例失败也跑）；**后置出错算这条用例出错**（它污染的是后面的用例，
   吞掉等于把「一半没清理」藏起来）。**前置出错则函数体不跑**（前提都没做成），
   但后置照跑。

## 顺带补上一个**本来就漏掉的宿主**

改这个模块时才发现：**Node 宿主根本没有 `测试` 模块**（`导入 测试` 直接 E0302）。
`测试` 是「自己测自己」那整套计划的地基（D91），缺一个宿主等于地基有洞 ——
所以这轮把整个模块（含原有 11 个函数）在 Node 上补齐，语义与 Python 侧逐条对齐。

⚠️ Node 的模块是**单例**，而 `测试` 要求「每次导入一份干净状态」
（Python 的 `__基石新建__`、Rust 在 `module()` 里重置）⇒ 给 `Module` 加了
`onImport` 钩子，`_doImport` 时触发。不加的话，同一脚本里 `导入 测试` 两次
会看到累积的记录，和另外两个宿主对不上。
"""

from __future__ import annotations

import subprocess
import sys
import tempfile
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parent))

from conftest import rust_exe_path, tmp_bc_path          # noqa: E402
from test_m41_stdlib import _five                        # noqa: E402

from oracle.jishi import serialize                        # noqa: E402
from oracle.jishi.compiler import compile_source          # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
PY = sys.executable
RUST = rust_exe_path()


def _跑(源: str, 名: str = "m136") -> tuple[int, str, str]:
    """用 CLI 跑一段程序（树遍历），返回 (退出码, stdout, stderr)。"""
    文件 = tmp_bc_path(Path(tempfile.gettempdir()) / f"{名}.jsh")
    文件.write_text(源, encoding="utf-8", newline="\n")
    r = subprocess.run([PY, "-m", "oracle.jishi.cli", str(文件)], cwd=str(ROOT),
                       capture_output=True, text=True, encoding="utf-8",
                       errors="replace", timeout=180)
    return r.returncode, r.stdout, r.stderr


