def test_每例前每例后_每条都跑():
    码, 出, 错 = _跑("""导入 测试

函数 前()：
    打印("前")

函数 后()：
    打印("后")

函数 好的()：
    测试.相等(1, 1)

测试.每例前(前)
测试.每例后(后)
测试.用例("甲", 好的)
测试.用例("乙", 好的)
""")
    assert 码 == 0, 出 + 错
    assert 出.count("前") == 2 and 出.count("后") == 2, f"前后置不是每条都跑：\n{出}"
    assert 出.index("前") < 出.index("后"), "顺序必须是先前后后"


def test_每例后_用例失败也照样跑():
    """清理不跑 = 污染后面的用例。这条盯着 `finally` 语义。

    ⚠️ 必须调 `测试.汇总()` 才会让脚本失败 —— **记录失败**和**报告失败**是两件事
    （`用例` 只记录，`汇总` 才抛错）。这不是 bug，是模块本来的契约；
    但「忘了写 汇总 于是静默全绿」确实是个坑，所以这里顺便把它钉住。
    """
    码, 出, 错 = _跑("""导入 测试

函数 后()：
    打印("清理了")

函数 会失败()：
    测试.相等(1, 2)

测试.每例后(后)
测试.用例("失败例", 会失败)
测试.汇总()
""")
    assert 码 == 1, "断言失败 + 汇总，必须退 1"
    assert "清理了" in 出, f"用例失败了，后置没跑：\n{出}"


def test_忘了汇总就是静默全绿_这是契约不是bug():
    """只 `用例` 不 `汇总` ⇒ 退出码 0（失败被记着，但没人报告）。

    写成判据是**故意**的：这样哪天模块改成「自动报告」，这条会红，
    逼着人去看「是不是要顺手改文档和调用方」。
    """
    码, 出, 错 = _跑("""导入 测试

函数 会失败()：
    测试.相等(1, 2)

测试.用例("失败例", 会失败)
""")
    assert 码 == 0, "现在的契约是「只 用例 不 汇总 ⇒ 不报错」"
    assert "✗" not in 出 and "✗" not in 错, "连明细也不打（没人问它）"


