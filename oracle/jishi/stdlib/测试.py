# -*- coding: utf-8 -*-
"""基石标准库：测试。极简的「用例 + 断言 + 汇总」三件套（M136 补了参数化/跳过/前后置）。

内建 `断言` 够用但有两个缺口：① 报错只说「条件不成立」，看不出**期望什么、
实际什么**；② 一个断言失败就中断整个脚本，跑不了下一组。

```jsh
导入 测试

函数 加法用例()：
    测试.相等(1 + 1, 2)
    测试.为真(1 < 2)

函数 字符串用例()：
    测试.相等("ab".长度(), 2)

测试.用例("加法", 加法用例)
测试.用例("字符串", 字符串用例)

测试.汇总()          # 打印「通过 / 失败」；有失败就报错（CLI 退出码 1）
```

**M136 补的三件事**（写一整批测试时立刻会缺的）：

```jsh
# ① 同一件检查喂多组数据 —— 不用为每组写一个函数
函数 检查加法(组)：
    测试.相等(组[0] + 组[1], 组[2])

测试.用例们("加法", [[1, 1, 2], [2, 2, 4]], 检查加法)   # 名字是 加法[1] / 加法[2]

# ② 这条用例在当前环境测不了 —— 记为「跳过」（不算通过，也不算失败）
函数 平台相关()：
    测试.跳过("这个平台没有那个能力")

# ③ 每条用例前后的准备/收尾（失败也收尾；收尾出错算这条用例出错）
测试.每例前(建临时目录)
测试.每例后(删临时目录)
```

⚠️ **用例要写成「具名函数 + 传函数名」**。别写成
`测试.用例("加法", 函数()：` 换行接多行 —— 匿名函数（`函数(x)：…`）的
函数体**只能是一个表达式**（见 `ast_nodes.Lambda`），多行会直接语法错。
（这段文档以前就是错的样子，2026-10-05 写 Rust 侧时照着抄才发现的。）

每个 `用例` 里的断言失败**不会**中断其它用例——`用例` 会接住断言错误、
记一笔、继续跑。块里其它异常（比如除零）也算这个用例失败，并把错误摘要留下。

🔴 **`用例` 只「记录」，`汇总` 才「报告」** —— 忘了写 `汇总()`，失败不会让脚本失败
（退出码还是 0）。这不是 bug，是模块的契约，但确实是个坑：写测试时**每份文件末尾
都要有 `汇总()`**（`tests/test_m136_test_module.py` 把这个契约也钉住了）。

**状态按「每次导入」隔离**（见 `__基石新建__`）：用例记录不挂模块级全局，
否则同一进程里跑第二个执行器会累积（M41 的五路对拍测试暴露过）。
"""

from __future__ import annotations

import sys as _sys

from ..errors import RunError, RunAssertionError
from ..runtime import jishi_repr

__all__ = [
    "用例", "用例们", "相等", "不等", "为真", "为假", "近似", "包含",
    "抛出", "跳过", "每例前", "每例后", "汇总", "重置", "统计",
]


class _跳过用例(RunError):
    """`测试.跳过(...)` 用的**内部控制流**，不是给用户捕获的错误类型。

    ⚠️ **为什么必须是 `JishiError` 的子类**（2026-10-25，五引擎对拍抓到的）：
    一开始它继承的是 `BaseException`（「控制流不是错误」），树遍历 / Python VM /
    Node / Rust 都对；**C VM 直接红**——因为宿主回调只放行 `JishiError`，
    别的异常会被包成「内部错误（宿主回调）：_跳过用例: …」，
    于是 `用例` 认不出它是跳过，只能记成「用例出错」。

    ⇒ 想跨 C 边界，就得是 `JishiError`。它**永远不会漏给用户**：
    `用例` 一定在内部接住它（接不到就是本模块的 bug，不是用户的错）。

    📌 三个宿主靠**类型名 `跳过用例`** 对齐（`exc_name`）；Rust / Node 那边
    只能走 JishiError 通道，用 `type_name == "跳过用例"` 认，两边对外表现一致。
    """

    #: 与 Rust / Node 对齐的**类型名**（对拍靠它，不是靠类名）。
    exc_name = "跳过用例"


def __基石新建__() -> dict:
    """每次 `导入 测试` 造一份独立状态（见模块文档末段）。"""
    记录: list[dict] = []
    当前: dict = {"条目": None}
    #: 前后置（`每例前` / `每例后` 各一个函数；没设就是 None）。
    钩子: dict = {"前": None, "后": None}

    def 重置() -> None:
        """清空已记录的用例（写多批测试时用）。

        ⚠️ **不动前后置钩子**：钩子是「怎么跑」，不是「跑过什么」。
        清了记录还把钩子留着，是刻意的 —— 写第二批用例时不想再设一遍。
        """
        记录.clear()

    def _是断言(e: BaseException) -> bool:
        return (getattr(e, "exc_name", "") == "断言错误"
                or type(e).__name__ == "RunAssertionError")

    def _是跳过(e: BaseException) -> bool:
        return isinstance(e, _跳过用例) or getattr(e, "exc_name", "") == "跳过用例"

    def _摘要(e: BaseException) -> str:
        名 = getattr(e, "title", None) or type(e).__name__
        消息 = getattr(e, "message", None) or str(e)
        return f"{名}（{消息}）" if 消息 else 名

    def _跑一条(名字, 函数, 参数们) -> dict:
        """跑一条用例（`用例` 和 `用例们` 共用），带上前后置。"""
        条 = {"名字": str(名字), "失败": [], "异常": None, "跳过": None}
        记录.append(条)
        旧 = 当前["条目"]
        当前["条目"] = 条
        try:
            前 = 钩子["前"]
            if 前 is not None:
                try:
                    前()
                except BaseException as e:          # noqa: BLE001
                    if _是跳过(e):
                        条["跳过"] = _跳过原因(e)
                        return 条
                    条["异常"] = "前置出错 —— " + _摘要(e)
                    return 条          # 前置就崩了，函数体不跑（后置在 finally 里照跑）
            try:
                函数(*参数们)
            except BaseException as e:              # noqa: BLE001 - 用例里什么都接
                if _是跳过(e):
                    条["跳过"] = _跳过原因(e)
                elif not _是断言(e):
                    # 断言失败已经由 `相等` 等记过了，这里只记「用例本身崩了」
                    条["异常"] = _摘要(e)
        finally:
            try:
                后 = 钩子["后"]
                if 后 is not None:
                    后()
            except BaseException as e:              # noqa: BLE001
                # 🔴 **后置里出错一定要算这条例失败**：清理没做成会污染后面的用例，
                #    静默吞掉等于把「一半没清理」藏起来。
                尾巴 = "后置出错 —— " + _摘要(e)
                条["异常"] = 尾巴 if 条["异常"] is None else 条["异常"] + "；" + 尾巴
            finally:
                当前["条目"] = 旧
        return 条

    def _跳过原因(e: BaseException) -> str:
        消息 = getattr(e, "message", None)
        if 消息:
            return str(消息)
        文 = str(e)
        # Python 的 `str(异常)` 会带「错误…（原因）」的壳；这里只取原因那一段。
        return 文

    def 用例(名字, 函数=None):
        """跑一个用例：`测试.用例("名字", 函数()：…)`。

        块里的断言失败会记进这个用例、**不中断**其它用例。
        """
        if 函数 is None:
            raise RunError("「测试.用例」要一个函数，"
                           "写成 测试.用例(\"名字\", 函数()：…)")
        return _跑一条(名字, 函数, ())

    def 用例们(名字, 数据们, 函数=None):
        """同一件检查，喂**多组数据**各跑一遍 —— 不用为每组写一个函数。

        ```jsh
        函数 检查加法(组)：
            测试.相等(组[0] + 组[1], 组[2])

        测试.用例们("加法", [[1, 1, 2], [2, 2, 4], [-1, 1, 0]], 检查加法)
        ```

        - 每一组**整组**作为一个参数传给函数（不是展开成多个参数）——
          展开的话「一组两个元素」和「两个参数」就分不清了；
        - 用例名带序号：`加法[1]` `加法[2]` `加法[3]`（从 **1** 数，跟人说话一致）；
        - 单独一组失败**不影响**其它组（和 `用例` 一样）。
        """
        if 函数 is None:
            raise RunError("「测试.用例们」要一个函数，"
                           "写成 测试.用例们(\"名字\", 数据们, 函数)")
        if isinstance(数据们, (str, bytes)) or not isinstance(数据们, (list, tuple)):
            raise RunError("「测试.用例们」的第二个参数（数据们）要是一个列表，"
                           f"得到了「{type(数据们).__name__}」")
        结果 = []
        序 = 1
        for 组 in 数据们:
            结果.append(_跑一条(f"{名字}[{序}]", 函数, (组,)))
            序 += 1
        return 结果

    def 每例前(函数) -> None:
        """设一个「每条例都要先跑一遍」的函数（建临时目录、开连接…）。

        ⚠️ 它**在用例外面跑**，所以里面出的错算**这条用例出错**（不是整个脚本崩），
        并且这条用例的**函数体不会跑** —— 前提都没做成，跑下去只会得到一堆假失败。
        """
        钩子["前"] = 函数

    def 每例后(函数) -> None:
        """设「每条例都要收尾一遍」的函数（删临时文件、关连接…）。

        🔴 **用例失败也照样跑**（finally 语义）；**后置里出错算这条用例失败**，
        因为它污染的是后面的用例。
        """
        钩子["后"] = 函数

    def 跳过(原因: str = "") -> None:
        """**这个用例不适用**，后面的断言别再跑了（记为「跳过」，不是通过也不是失败）。

        什么时候用：这条用例要的能力当前环境没有（比如某个平台没这个 API），
        或者前置条件不成立。**不要用它掩盖失败** —— 跳过会单独计数、单独打印。
        """
        if 当前["条目"] is None:
            raise RunError("「测试.跳过」只能在用例里用"
                           "（在用例外面调它等于把整份脚本静默跳过，那不是它的意思）")
        raise _跳过用例(原因)

    def _失败(说明: str, 详: str) -> None:
        """记一次失败：在用例里就记进用例，否则直接抛（独立用断言时）。"""
        if 当前["条目"] is not None:
            当前["条目"]["失败"].append((说明, 详))
            return
        raise RunAssertionError(f"{说明}：{详}")

    def _文本(v) -> str:
        return jishi_repr(v, top=True)

    def 相等(实际, 期望, 说明: str = "") -> None:
        """断言 实际 == 期望（失败时把两边都打出来）。"""
        if not (实际 == 期望):
            _失败(说明 or "相等", f"期望 {_文本(期望)}，实际 {_文本(实际)}")

    def 不等(实际, 不该等于, 说明: str = "") -> None:
        """断言 实际 != 不该等于。"""
        if 实际 == 不该等于:
            _失败(说明 or "不等",
                  f"不该等于 {_文本(不该等于)}，但实际就是它")

    def 为真(条件, 说明: str = "") -> None:
        """断言条件为真。"""
        if not 条件:
            _失败(说明 or "为真", f"期望为真，实际是 {_文本(条件)}")

    def 为假(条件, 说明: str = "") -> None:
        """断言条件为假。"""
        if 条件:
            _失败(说明 or "为假", f"期望为假，实际是 {_文本(条件)}")

    def 近似(实际, 期望, 误差: float = 1e-9, 说明: str = "") -> None:
        """断言 实际 与 期望 的差不超过 误差（浮点数比较用它）。"""
        try:
            差 = abs(实际 - 期望)
        except TypeError:
            _失败(说明 or "近似",
                  f"「{_文本(实际)}」与「{_文本(期望)}」不能比大小")
            return
        if not (差 <= 误差):
            _失败(说明 or "近似",
                  f"期望 {_文本(期望)}（±{_文本(误差)}），实际 {_文本(实际)}")

    def 包含(容器, 元素, 说明: str = "") -> None:
        """断言容器里有这个元素。"""
        try:
            有 = 元素 in 容器
        except TypeError:
            _失败(说明 or "包含", f"「{_文本(容器)}」不能判包含")
            return
        if not 有:
            _失败(说明 or "包含", f"{_文本(容器)} 里没有 {_文本(元素)}")

    def 抛出(函数, 说明: str = ""):
        """断言这段代码会报错，返回那个异常（可以再看它的类型）。

        例：`测试.抛出(函数()：1 / 0)`。
        """
        try:
            函数()
        except BaseException as e:              # noqa: BLE001 - 就是来看错误的
            return e
        _失败(说明 or "抛出", "期望报错，但它正常跑完了")
        return None

    def 统计() -> dict:
        """返回汇总数据：`{"用例", "通过", "失败", "出错", "跳过"}`。

        - `失败` 是**断言的条数**（一条用例可以失败好几处）；
        - `出错` 是**用例的条数**（崩在函数体/前后置里）；
        - `跳过` 是**用例的条数**（`测试.跳过` 过的，**不算通过**）。
        """
        失败 = sum(len(条["失败"]) for 条 in 记录)
        出错 = sum(1 for 条 in 记录 if 条["异常"])
        跳过 = sum(1 for 条 in 记录 if 条["跳过"] is not None and not 条["异常"])
        通过 = sum(1 for 条 in 记录
                   if not 条["失败"] and not 条["异常"] and 条["跳过"] is None)
        return {"用例": len(记录), "通过": 通过, "失败": 失败,
                "出错": 出错, "跳过": 跳过}

    def 汇总() -> bool:
        """打印汇总；**有任何失败就报错**（CLI 于是以退出码 1 结束）。

        返回是否全过。⚠️ **跳过不算失败**（那是「这个环境测不了」），
        但它会**单独计数、单独打印** —— 不许静默混进通过里。
        """
        数 = 统计()
        for 条 in 记录:
            if 条["异常"]:
                print(f"✗ {条['名字']}：用例里出错 —— {条['异常']}",
                      file=_sys.stderr)
            for 说明, 详 in 条["失败"]:
                print(f"✗ {条['名字']} · {说明}：{详}", file=_sys.stderr)
        # ⏭ 明细走**输出流**（跳过不是错误），汇总行之前打，顺序才稳
        for 条 in 记录:
            if 条["跳过"] is not None and not 条["异常"]:
                因 = f"：{条['跳过']}" if 条["跳过"] else ""
                print(f"⏭ {条['名字']}{因}")
        全过 = 数["失败"] == 0 and 数["出错"] == 0
        标记 = "✅" if 全过 else "❌"
        尾巴 = f"（{数['用例']} 个用例"
        if 数["跳过"]:
            尾巴 += f"，跳过 {数['跳过']}"
        尾巴 += "）"
        if 全过:
            print(f"{标记} 全部通过 {尾巴}")
        else:
            print(f"{标记} 通过 {数['通过']} / 失败 {数['失败']}"
                  f" / 出错 {数['出错']} {尾巴}")
        if not 全过:
            # 🔴 **抛错前必须把两个流刷出去**（2026-10-23，M127 由 `check_engines` 抓到）：
            #    失败明细走 stderr、汇总行走 stdout，两行都已经 `print` 过了，
            #    但**抛异常会让进程直接结束、缓冲区不刷新** ⇒ 用户只看到
            #    「错误 E2008」，看不到**到底哪条用例挂了**（`✗ … 期望 3，实际 2` 丢了）。
            #    实测：Rust 宿主有那行（它自己 flush 过），树遍历没有 —— 五引擎对拍红。
            _sys.stdout.flush()
            _sys.stderr.flush()
            # 用「抛断言错误」表达失败——脚本里没法直接设进程退出码，
            # 但抛出去 CLI 会以 1 退出，正好接进 CI。
            raise RunAssertionError(
                f"测试没全过：失败 {数['失败']} 项、出错 {数['出错']} 项")
        return True

    return {"用例": 用例, "用例们": 用例们, "相等": 相等, "不等": 不等, "为真": 为真,
            "为假": 为假, "近似": 近似, "包含": 包含, "抛出": 抛出,
            "跳过": 跳过, "每例前": 每例前, "每例后": 每例后,
            "汇总": 汇总, "重置": 重置, "统计": 统计}
