"""标准库 `浏览器`（M167）—— **只在 wasm（网页）里能用**。

## 这个文件在做什么

命令行 / Node 上**每个函数都报同一条中文错**。这不是「占位」，是**平台边界**：

> 同步 VM 没有事件循环，浏览器那套异步 API 塞不进来（D81 就是因为这条，
> 把 `HTTP服务端` 在 Node 上判成不支持的）。

**为什么要写这 13 个函数**（而不是让模块根本不存在）：
`test_m51_consistency` 要求「Python 侧有的模块与函数，三个宿主一个都不能少」。
让模块**存在、但调用时报平台错**，这条检测就不用开豁免；
用户在命令行上 `导入 浏览器` 也不会得到一个「找不到模块」的误导性错误。

## 文案是契约

`无浏览器` 这一串在**三个宿主上逐字相同**（`tests/test_m167_browser.py` 盯着）。
改一个字就要三处一起改 —— 否则同一条错在三个引擎上长得不一样。

## 真正的实现在哪

- wasm（网页）：`rust/src/stdlib/browser.rs` 的 `host` 模块 + `site/jishi-wasm.js`；
- 设计（「一次事件 = 一次完整执行」）：见那个文件的模块头。
"""

