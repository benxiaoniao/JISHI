# -*- coding: utf-8 -*-
"""基石标准库：并发。把**一批互相独立的 IO** 同时做，结果顺序与输入一致。

⚠️ **这不是「语言级的线程 / 锁 / 队列」** —— 基石**不做**那个
（见 `docs/路线图.md` 第四节「不做清单」与 `docs/设计决策.md` D80）。
这里是**标准库的实现细节**：一批互不相干的 IO（读文件 / 算摘要 / 取网址）
在**宿主**里同时做，省掉「排队干等」那部分时间。

## 三条硬规矩

1. **返回顺序 = 输入顺序**（严格一一对应）。所以并发**不影响可复现性** ——
   五个引擎的输出仍然逐字节一致（`tests/cases/33_标准库_M114.jsh` 就是这条的证据）。
2. **任何一项失败就整体报错**，错误取**输入顺序里最靠前**的那一项 ——
   不让「谁先跑完」影响报的是哪一句。
3. 线程数 ≤ 1、或**平台没有线程**（浏览器试玩页的 wasm）⇒ **顺序执行**：
   结果一模一样，只是不重叠等待。

## 📌 它只在「大量小 IO」上划算（先量再判）

绕道探针《并发批量》实测（同一份逻辑）：

| 场景 | 顺序 | 本模块 | 结论 |
|---|---|---|---|
| 2000 个 4 KB 小文件（8 MB）算摘要 | 2.245 秒 | **0.814 秒** | **快 2.76 倍** ✅ |
| 40 MB 一个大文件算摘要 | **0.087 秒** | 1.717 秒 | 慢 20 倍 ❌ |

⇒ **大文件、纯计算（算数 / 字符串处理）不要用它**：那是 CPU 活，
线程只是白加调度与内存，反而更慢。真正的收益来自
**「大量小任务各自在等 IO」** —— 等待被打叠起来。

⚠️ ⚠️ **共享状态这件事这里管不了**：本模块的函数都只碰**宿主**（读文件 / 发请求），
不跑基石代码，所以没有「两个线程同时改一个列表」的风险。
这也是它**只能是这几个批量函数**、而不是通用「把任意函数并发跑」的原因 ——
后者要动整个值表示（基石里的容器是引用类型），代价见 D80。
"""

from __future__ import annotations

from ..errors import RunTypeError, RunValueError
from ..runtime import type_name
from .加密 import _归一摘要算法, 文件摘要 as _文件摘要
from .文件 import 读字节 as _读字节

__all__ = ["批量摘要", "批量读", "并行取"]

#: 线程数上限（护栏）：`并发.批量读(路径们, 100000)` 会当场把机器打死。
_最大线程数 = 32


def _线程数(值) -> int:
    """校验并收敛线程数（≤0 报错、超上限收到上限）。"""
    if isinstance(值, bool) or not isinstance(值, (int, float)):
        raise RunTypeError(f"线程数要是正整数，得到了「{type_name(值)}」")
    n = int(值)
    if n < 1:
        # ⚠️ 报的是**取整之后**的 n（与 Rust / Node 侧同字）—— 三个宿主
        # 都不许把「原始值」的格式差异漏进这句文案里
        raise RunValueError(f"线程数要是正整数，现在是 {n}")
    return min(n, _最大线程数)


def _列出(值, 谁: str) -> list:
    """把「一串东西」统一成列表。文本/集合不收 —— 顺序这事必须说得清。"""
    if isinstance(值, str):
        raise RunTypeError(f"{谁}要给一个列表，不能直接给文本")
    if isinstance(值, (list, tuple)):
        return list(值)
    raise RunTypeError(f"{谁}要给一个列表，得到了「{type_name(值)}」")


def _并行做(项们: list, 线程数: int, 做一项):
    """把 `做一项` 依次作用到每一项上，**结果严格按输入顺序**返回。

    ⚠️ **这是全模块唯一的并发点** —— 三个函数都走它，
    所以「顺序确定」「首个错胜出」这两条规矩只在这里写一次。
    """
    n = len(项们)
    if n == 0:
        return []
    if 线程数 <= 1 or n == 1:
        return [做一项(x) for x in 项们]
    from concurrent.futures import ThreadPoolExecutor
    # ⚠️ `max_workers` 取 `min(线程数, 项数)`：任务比线程少时不用多开
    with ThreadPoolExecutor(max_workers=min(线程数, n)) as pool:
        未来们 = [pool.submit(做一项, x) for x in 项们]
        # 按**输入顺序**取结果 —— 谁先跑完不影响输出（五引擎能对拍的前提）
        出 = []
        首个错 = None
        for fut in 未来们:
            try:
                出.append(fut.result())
            except Exception as e:      # noqa: BLE001 —— 原样收集，最后抛
                if 首个错 is None:
                    首个错 = e
        if 首个错 is not None:
            raise 首个错
        return 出


def 批量摘要(路径们, 算法: str = "sha256", 线程数: int = 4) -> list:
    """**同时**算一批文件的摘要，返回的列表**与输入一一对应**（同一顺序）。

    与 `加密.文件摘要` 同一个算法表、同一句报错；`路径们` 是列表（路径文本）。
    """
    # ⚠️ 校验顺序（算法 → 线程数 → 列表）要与 Rust / Node 侧**逐条一致**：
    #    两处都不合法时，三个引擎得报同一句
    算法名 = _归一摘要算法(算法)
    k = _线程数(线程数)
    项们 = _列出(路径们, "「批量摘要」的第一个参数（路径们）")
    return _并行做(项们, k, lambda p: _文件摘要(p, 算法名))


def 批量读(路径们, 线程数: int = 4) -> list:
    """**同时**读一批文件的内容，每一项是 `字节`（顺序与输入一致）。

    与 `文件.读字节` 同一个口径（连报错都一样）。
    """
    k = _线程数(线程数)
    项们 = _列出(路径们, "「批量读」的第一个参数（路径们）")
    return _并行做(项们, k, _读字节)


def 并行取(网址们, 线程数: int = 4) -> list:
    """**同时**取一批网址的正文（GET），顺序与输入一致。

    与 `网络.获取` 同一个口径（默认 10 秒超时、非 2xx 报错）。
    """
    from .网络 import 获取 as _获取
    k = _线程数(线程数)
    项们 = _列出(网址们, "「并行取」的第一个参数（网址们）")
    return _并行做(项们, k, _获取)
