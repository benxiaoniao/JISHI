# -*- coding: utf-8 -*-
"""基石标准库：HTTP 路由（M122）。

`HTTP服务端` 给了四个零件（解析请求 / 构造响应 / 启动 / 空闲端口），但**没有路由** ——
真写网站时只能手写一串 `如果 请求["路径"] == "/a" 那么 …`，路径一多就变成一坨。
这个模块把「哪条路走哪个函数」单独拎出来。

**纯逻辑，五个引擎都能跑**（只是字符串和列表的处理，不碰 socket）⇒ 全程进语料对拍。

## 典型用法

```python
导入 HTTP服务端
导入 HTTP路由

函数 首页(请求, 参数):
    返回 HTTP服务端.构造响应(200, "<h1>你好</h1>", "text/html; charset=utf-8")

函数 文章(请求, 参数):
    返回 HTTP服务端.构造响应(200, "第 " + 参数["id"] + " 篇")

令 表 = HTTP路由.路由表()
HTTP路由.加路由(表, "GET", "/", 首页)
HTTP路由.加路由(表, "GET", "/文章/:id", 文章)

HTTP服务端.启动(8000, 函数(请求):
    令 命中 = HTTP路由.匹配(表, 请求["方法"], 请求["路径"])
    如果 命中 == 空 那么
        返回 HTTP服务端.构造响应(404, "没有这一页")
    返回 命中["处理"](请求, 命中["参数"])
)
```

## 匹配规则（**三个宿主必须一模一样**，语料逐字节盯着）

| 情形 | 行为 |
|---|---|
| 路径 | 按 `/` 切成段，逐段比；**末尾斜杠严格区分**（`/a` 与 `/a/` 是两条路） |
| 参数段 | 路由里以 `:` 开头的段（`/文章/:id`）匹配**任意一段**，值进 `参数` |
| 方法 | **大写后**比较（`get` 与 `GET` 等价）；写 `"*"` 表示任何方法都收 |
| 多条都匹配 | 取**参数段最少**的那条（静态优先）；再相同 ⇒ 取**先注册**的 |
| 没匹配上 | `匹配` 返回 `空`（**不抛错** —— 404 是正常流程，不是异常） |
| 参数值 | 已经是百分号解码后的文本（`解析请求` 先解过） |

⚠️ **已知边界**：`解析请求` 是把整条路径一起解码的，所以路径里的 `%2F`
会**变成一个真的 `/`**，于是多出一段 —— 这种路径做不了参数匹配。
（要修得改 `解析请求` 的口径，属于破坏性变更，见 `docs/设计决策.md` D86。）
"""

from __future__ import annotations

from ..errors import RunTypeError, RunValueError

__all__ = ["路由表", "加路由", "匹配", "路径们"]


def _要文本(值, 名: str) -> str:
    if not isinstance(值, str):
        raise RunTypeError(f"「{名}」要是文本，现在是 {type(值).__name__}")
    return 值


def _要列表(值, 名: str):
    if not isinstance(值, (list, tuple)):
        raise RunTypeError(f"「{名}」要是路由表（用 `路由表()` 造），"
                           f"现在是 {type(值).__name__}")
    return 值


def _切段(路径: str) -> list[str]:
    """把路径切成段。`/` 本身 → 空列表（首页）；`/a/b` → `["a", "b"]`。

    ⚠️ **末尾斜杠严格区分**：`/a/` 切成 `["a", ""]`（多一个空段），
    所以它跟 `/a` 不会互相匹配。这是**故意**的 —— 宽容匹配会让
    「`/a/` 和 `/a` 到底是不是一页」变成猜谜。
    """
    if 路径 == "/":
        return []
    return 路径.lstrip("/").split("/")


def 路由表() -> list:
    """造一张空路由表。

    返回的就是一个**列表**，所以 `长度(表)` 就是注册了几条路由。
    ⚠️ 它会被 `加路由` **原地修改**（与 `表格.追加` 同一套习惯）。
    """
    return []


def 加路由(表, 方法: str, 路径: str, 处理) -> list:
    """往表里加一条路由。返回这张表本身（方便连着写）。

    - `方法`：`"GET"` / `"POST"`…，**不分大小写**；写 `"*"` 表示什么方法都收；
    - `路径`：以 `/` 开头；某一段写成 `:名字` 就是参数（`/文章/:id`）；
    - `处理`：会被调成 `处理(请求, 参数)`。

    ⚠️ 重复注册（同方法 + 同路径）**不报错**，但**先注册的那条先生效**
    —— 后加的那条永远轮不到。这比抛错温和，但要在文档里说清楚。
    """
    表 = _要列表(表, "表")
    方法 = _要文本(方法, "方法").strip().upper()
    if not 方法:
        raise RunValueError("「方法」不能是空文本（要「什么方法都收」请写 \"*\"）")
    路径 = _要文本(路径, "路径")
    if not 路径.startswith("/"):
        raise RunValueError(f"路径要以 / 开头（现在是「{路径}」）")
    if not callable(处理):
        raise RunTypeError(f"「处理」要是函数，现在是 {type(处理).__name__}")

    段们 = _切段(路径)
    for 段 in 段们:
        if 段 == "":
            raise RunValueError(f"路径「{路径}」里有空段（是不是多写了一个 /）")
    if 段们 and any(s.startswith(":") and len(s) == 1 for s in 段们):
        raise RunValueError(f"路径「{路径}」里有光秃秃的 `:`，参数要有名字（比如 `:id`）")

    表.append({"方法": 方法, "路径": 路径, "处理": 处理})
    return 表


def 匹配(表, 方法: str, 路径: str):
    """在表里找一条能接住的。命中返回 `{"处理": 函数, "参数": {…}}`，否则 `空`。

    ⚠️ **没命中返回 `空`，不抛错** —— 404 是网站的**正常流程**，不是异常。
        用 `如果 命中 == 空 那么 …` 接住它。
    """
    表 = _要列表(表, "表")
    方法 = _要文本(方法, "方法").strip().upper()
    路径 = _要文本(路径, "路径")
    段们 = _切段(路径)

    最佳 = None          # (路由, 参数, 参数数)
    for 路由 in 表:
        if 路由["方法"] != "*" and 路由["方法"] != 方法:
            continue
        模式们 = _切段(路由["路径"])
        if len(模式们) != len(段们):
            continue
        参数 = {}
        能匹配 = True
        for 模式, 实际 in zip(模式们, 段们):
            if 模式.startswith(":"):
                # ⚠️ **空段不算参数值**：`/文章/` 不能匹配 `/文章/:id`
                #    —— 否则 `参数["id"]` 是空串，用户拿着它去查库只会一脸问号。
                #    （这正是「末尾斜杠严格区分」的落地方式。）
                if 实际 == "":
                    能匹配 = False
                    break
                参数[模式[1:]] = 实际
            elif 模式 != 实际:
                能匹配 = False
                break
        if not 能匹配:
            continue
        # 静态优先：参数段更少的那条更「确切」；一样则保留**先注册**的（不覆盖）
        参数数 = sum(1 for s in 模式们 if s.startswith(":"))
        if 最佳 is None or 参数数 < 最佳[2]:
            最佳 = (路由, 参数, 参数数)

    if 最佳 is None:
        return None
    return {"处理": 最佳[0]["处理"], "参数": 最佳[1]}


def 路径们(表) -> list:
    """表里注册过的路径（按注册顺序，带方法前缀）。

    给 404 页面用：**告诉用户有哪些路**，比一句「没有这一页」有用得多。
    例：`["GET /", "GET /文章/:id"]`
    """
    表 = _要列表(表, "表")
    return [f'{r["方法"]} {r["路径"]}' for r in 表]
