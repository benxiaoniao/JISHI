def 图集切分(图宽, 图高, 帧宽, 帧高):
    """M197：按图集尺寸算出**有多少帧**，返回 `{"列数","行数","帧数","帧们"}`。

    例（一张 128×96 的图，每帧 32×32）::

        令 切 = 精灵.图集切分(128, 96, 32, 32)
        # {"列数": 4, "行数": 3, "帧数": 12, "帧们": [0, 1, …, 11]}
        精灵.播(主角, "走", {"帧们": 切["帧们"], "速度": 8})

    📌 **要自己给图宽高**（不给句柄）：句柄的尺寸只有画布才知道，
    而命令行没有画布 —— 那样这个函数在命令行上就没法用，也没法测。
    图宽高本来就是 `读图` 之前你自己定的事，写出来最省事。
    📌 除不尽的部分**丢掉**（`128×96` 配 `48×48` 只有 2×2=4 帧，右边和下边
    的残条不算一帧）—— 半帧的图放出来是错的。
    """
    图宽 = _数(图宽, "图集切分", "图宽")
    图高 = _数(图高, "图集切分", "图高")
    帧宽 = _数(帧宽, "图集切分", "帧宽")
    帧高 = _数(帧高, "图集切分", "帧高")
    for 名, v in (("图宽", 图宽), ("图高", 图高), ("帧宽", 帧宽), ("帧高", 帧高)):
        if v <= 0:
            raise RunValueError(f"「图集切分」的{名}必须大于 0，现在是 {v}")
    if 帧宽 > 图宽 or 帧高 > 图高:
        raise RunValueError(
            f"「图集切分」的帧（{帧宽}×{帧高}）比图（{图宽}×{图高}）还大")
    列数 = int(图宽 // 帧宽)
    行数 = int(图高 // 帧高)
    帧数 = 列数 * 行数
    return {"列数": 列数, "行数": 行数, "帧数": 帧数,
            "帧们": list(range(帧数))}


def 动画完成(精灵):
    """M197：**非循环**动画是不是播完了（`循环=假` 的那次 `播`）。

    📌 它是**边沿**：播完就一直是 `真`，直到再次 `播` 才清回 `假` ——
    这样「打完一套放个技能」这类逻辑只在 frame 循环里判断一次就行，
    不会漏（读一次就清的边沿更容易写错）。

    📌 循环动画**永远返回 `假`**：它没有「播完」这回事。
    """
    d = _字典(精灵, "动画完成")
    return bool(d.get("完成", False))


def 设原点(精灵, x=0.5, y=0.5):
    """M197：设锚点（**比例** 0–1），之后 `画(精灵, x, y)` 就把这个点对到 (x, y)。

    例（让精灵中心对准坐标）::

        精灵.设原点(主角, 0.5, 0.5)
        精灵.画(主角, 玩家x, 玩家y)    # 现在玩家坐标是「精灵中心」

    ⚠️ **不调这个函数时原点是 (0, 0)**（左上角）—— 这是 M187 就有的行为，
    为的是不改老代码的画法。要「以中心为准」得显式写 `设原点(精灵, 0.5, 0.5)`。
    """
    d = _字典(精灵, "设原点")
    ox = _数(x, "设原点", "x")
    oy = _数(y, "设原点", "y")
    if not 0.0 <= ox <= 1.0 or not 0.0 <= oy <= 1.0:
        raise RunValueError(
            f"「设原点」的两个比例要在 0–1 之间，现在是 {ox} / {oy}")
    d["原点x"] = ox
    d["原点y"] = oy
    return 精灵
