# -*- coding: utf-8 -*-
"""基石标准库：精灵（M187）—— 图集切帧 + 动画。

精灵就是一个**字典**（`精灵.新建` 造的），里面放着图集句柄、帧尺寸与动画进度。
`画` 最后落到 `图形.画子图`，所以**画的时候要有画布**。

⚠️ 与 Rust / Node 三份实现逐字对齐（键名、报错口径、动画推进规则）。
"""

from ..errors import RunTypeError, RunValueError

__all__ = ["新建", "播", "停", "设帧", "更新", "画", "当前帧"]


def _字典(v, 名):
    if not isinstance(v, dict):
        raise RunTypeError(f"「{名}」的第一个参数要精灵（`精灵.新建` 造的），给的是{type(v).__name__}")
    return v


def _要(精灵, 键):
    if 键 not in 精灵:
        raise RunValueError(f"这个字典里缺「{键}」——精灵应当由 `精灵.新建` 造出来")
    return 精灵[键]


def _数(v, 名, 参):
    if isinstance(v, bool) or not isinstance(v, (int, float)):
        raise RunTypeError(f"「{名}」的「{参}」要数字，给的是{type(v).__name__}")
    return float(v)


def 新建(图, 选项):
    """M187：按图集建一个精灵。`选项` 必填 `宽`/`高`（一帧多大），可选 `列数`/`行数`。"""
    宽 = _数(_要(选项, "宽"), "新建", "宽")
    高 = _数(_要(选项, "高"), "新建", "高")
    if 宽 <= 0 or 高 <= 0:
        raise RunValueError("「精灵.新建」的宽高必须大于 0")
    return {
        "图": 图, "帧宽": 宽, "帧高": 高,
        "列数": int(选项.get("列数", 1)) or 1,
        "行数": int(选项.get("行数", 1)) or 1,
        "当前": 0, "在播": "", "累计": 0.0, "动画": {},
    }


def 播(精灵, 名, 选项=None):
    """M187：播一个动画（`选项` = `{"帧们","速度","循环"}`）。"""
    d = _字典(精灵, "播")
    o = 选项 or {}
    帧们 = [int(x) for x in o.get("帧们", [])]
    速度 = _数(o.get("速度", 12), "播", "速度")
    if 速度 <= 0:
        raise RunValueError("「播」的速度必须大于 0（单位：帧/秒）")
    if not 帧们:
        帧们 = list(range(max(1, d["列数"] * d["行数"])))
    d["动画"][名] = {"帧们": 帧们, "速度": 速度, "循环": bool(o.get("循环", True))}
    d["在播"] = 名
    d["累计"] = 0.0
    d["当前"] = 帧们[0]
    return 精灵


def 停(精灵):
    """M187：停下动画（停在当前帧）。"""
    _字典(精灵, "停")["在播"] = ""
    return True


def 设帧(精灵, 号):
    """M187：直接跳到第 `号` 帧（`0` 起）。"""
    _字典(精灵, "设帧")["当前"] = int(号)
    return True


def 更新(精灵, 间隔毫秒):
    """M187：按走过的毫秒数推进动画（有个上限：间隔再大也只走 1000 步）。"""
    d = _字典(精灵, "更新")
    间隔 = _数(间隔毫秒, "更新", "间隔")
    名 = d.get("在播", "")
    if not 名 or 间隔 <= 0:
        return False
    项 = d["动画"].get(名)
    if not 项 or not 项["帧们"] or 项["速度"] <= 0:
        return False
    每帧 = 1000.0 / 项["速度"]
    d["累计"] = d.get("累计", 0.0) + 间隔
    帧们 = 项["帧们"]
    try:
        位 = 帧们.index(d["当前"])
    except ValueError:
        位 = 0
    变 = False
    次 = 0
    while d["累计"] >= 每帧 and 次 < 1000:
        d["累计"] -= 每帧
        次 += 1
        if 位 + 1 < len(帧们):
            位 += 1
        elif 项["循环"]:
            位 = 0
        else:
            d["累计"] = 0.0
            break
        d["当前"] = 帧们[位]
        变 = True
    return 变


def 画(精灵, x, y, 选项=None):
    """M187：把当前帧画到 (x, y)。**要有画布**（走 `图形.画子图`）。"""
    from . import 图形 as _图形

    d = _字典(精灵, "画")
    x = _数(x, "画", "x")
    y = _数(y, "画", "y")
    帧宽, 帧高, 列数 = d["帧宽"], d["帧高"], d["列数"]
    列 = d["当前"] % 列数 if 列数 > 0 else 0
    行 = d["当前"] // 列数 if 列数 > 0 else 0
    return _图形.画子图(
        d["图"], 列 * 帧宽, 行 * 帧高, 帧宽, 帧高, x, y, 帧宽, 帧高, 选项)


def 当前帧(精灵):
    """M187：现在是第几帧（`0` 起）。"""
    return _字典(精灵, "当前帧")["当前"]
