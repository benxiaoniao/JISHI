# -*- coding: utf-8 -*-
"""`串口`（M232 / L-4）：和硬件说几句话。

## 为什么 Python 侧全是「做不到」

串口是**平台硬件交互**，而 Python 宿主在本项目里的定位是「参考实现 / 判据基准」
（M185 起定的原则：Python / Node 宿主**故意不做**硬件相关的那几层，
比如剪贴板、托盘、文件关联）。

要在这儿真做，就得引入 `pyserial` —— **第三方依赖**。本项目的标准库到 0.3.5
收口时第三方依赖已经清零（`encoding_rs` 换成了自带码表、`rusqlite` 换成了
纯基石实现），不值得为一个「只有 Rust 宿主能验」的模块重新引进来。

所以：**能力在 Rust 宿主上（Windows 裸 Win32 / Linux·macOS 裸 termios，零依赖）；
Python 侧明确报错，不假装。** `工具/判据` 跑的是 Rust 宿主那一侧
（见 `tests/test_m232_serial.py`）。

## 接口（与 Rust 侧一致）

```python
串口.列出()                                             # [{口, 描述, 设备}]
串口.打开(口, 波特率=115200, 数据位=8, 停止位=1, 校验="无")  # → 句柄
句柄.写文本(文本) / 写字节(字节)
句柄.读行(超时=空) / 读可用()
句柄.关闭()
```

⚠️ 三条硬事实（与 Rust 侧文件头同一份口径）：
① **一次打开独占** —— 同一个口被别的程序占着就打不开，所以 `关闭()` 是必须的收尾；
② 口名写法三平台不同：Windows `COM3`（自动补前缀）/ Linux `/dev/ttyUSB0` /
   macOS `/dev/cu.*`（**不要 `/dev/tty.*`**，那个会等载波、插拔时挂住）；
③ `读行` 按 `\\n` 分帧，**二进制协议用 `读可用` / `写字节`**，别按行读。
"""

