def 截断(文本, 宽度: int, 省略号: str = "…") -> str:
    """超长就截断并加省略号，否则原样返回（`宽度` 含省略号本身）。

    例：`文本.截断("这是一段很长的话", 6)` → `"这是一段很…"`（6 个字符位）。
    做日志摘要、表格列宽时用；`宽度` 小于省略号长度就只返回省略号。
    """
    s = str(文本)
    w = int(宽度)
    if w < 0:
        raise RunTypeError(f"「截断」的宽度不能是负数，得到了 {宽度}")
    if len(s) <= w:
        return s
    if w <= len(省略号):
        return 省略号[:w]
    return s[:w - len(省略号)] + 省略号


def 填充(文本, 宽度: int, 填充字符: str = " ") -> str:
    """把文本**居中**填充到指定**显示宽度**（两侧补同样的字符）。

    与 `左对齐` / `右对齐` 是一组：那三个是「靠一边」，这个是「居中」。
    例：`文本.填充("abc", 7, "-")` → `"--abc--"`。
    """
    return _补齐(str(文本), int(宽度), 填充字符, "中")


# -- M142：把一列 / 一张表排成对齐的文本 -------------------------------------


def _是不是数(v) -> bool:
    return not isinstance(v, bool) and isinstance(v, (int, float))


def 对齐表(行们, 小数位=None) -> str:
    """把**一列值**或**一整张表**排成对齐的文本（列宽自适应，中文按 2 列算）。

    ```jishi
    打印(文本.对齐表([1, 22, 333]))                       # 一行，右对齐
    打印(文本.对齐表([[1, 2], [40, 500]]))                # 一张表
    打印(文本.对齐表([[1.5, 2], [3, 4.25]], 1))           # 小数点后 1 位
    ```

    **为什么要它**（M142）：`右对齐` / `左对齐` 这些是「按**指定**宽度补」，
    可表格里每列该多宽**事先不知道** —— 手写就得扫两遍（先算列宽、再补空格），
    还要记得中文算 2 列。这块肉在 0.2.9 之前每打一次表就要重写一遍
    （向量/矩阵的示例里能看见）。这里一次做掉。

    规则（写死，不留歧义）：
    - 传**一列值**就是一行；传**列表的列表**就是多行（每行长度必须相同）；
    - **该列全是数字就右对齐**（数字右看个位才顺），否则左对齐；
    - `小数位` 只影响**数字**（文本原样），不给就按 `文本(值)` 显示；
    - 列之间空 **两个空格**；每行**末尾不留空格**（这样能直接比对、也能干净地重定向到文件）。
    """
    if isinstance(行们, (str, bytes)):
        raise RunTypeError("「对齐表」要传一列值或一张表（列表），不能传文本")
    try:
        原始 = list(行们)
    except TypeError:
        raise RunTypeError("「对齐表」要传一列值或一张表（列表）")
    if not 原始:
        raise RunValueError("「对齐表」要至少有一个值，现在是空的")

    if isinstance(原始[0], (list, tuple)):
        表 = [list(行) for 行 in 原始]
        宽 = len(表[0])
        for i, 行 in enumerate(表, 1):
            if len(行) != 宽:
                raise RunValueError(
                    f"「对齐表」每行的列数要相同：第 1 行有 {宽} 列，第 {i} 行有 {len(行)} 列")
    else:
        表 = [原始]

    if 小数位 is not None:
        if isinstance(小数位, bool) or not isinstance(小数位, int):
            raise RunTypeError(f"「对齐表」的小数位要是不给或整数，给的是 {小数位}")
        if 小数位 < 0 or 小数位 > 10:
            raise RunValueError(f"「对齐表」的小数位要在 0 到 10 之间（给的是 {小数位}）")

    格子 = [[_格子文本(v, 小数位) for v in 行] for 行 in 表]
    列数 = len(格子[0])
    列宽 = [max(显示宽度(行[j]) for 行 in 格子) for j in range(列数)]
    数字列 = [all(_是不是数(行[j]) for 行 in 表) for j in range(列数)]

    行们出来 = []
    for 行 in 格子:
        片 = []
        for j, 格 in enumerate(行):
            片.append(右对齐(格, 列宽[j]) if 数字列[j] else 左对齐(格, 列宽[j]))
        行们出来.append("  ".join(片).rstrip())
    return "\n".join(行们出来)


def _格子文本(v, 小数位):
    """一格怎么显示：数字给了小数位就按位补，其余按 `文本(值)` 的口径。"""
    if 小数位 is not None and _是不是数(v):
        return _定点(v, 小数位)
    return jishi_repr(v, top=True)


def _定点(v, 位: int) -> str:
    """把数字写成**固定小数位**的文本：**四舍五入（远离零）**。

    🔴 为什么不用宿主的定点格式化（`format(v, ".2f")` / `toFixed`）：
    正好一半时三个宿主**结论不同** —— `4.25` 保留 1 位，Python 给 `4.2`
    （半偶）、JS 给 `4.3`（半远离零）。而「三执行器语义一致」是本项目的硬约束，
    所以这里**在十进制字符串上做进位**：先取 `文本(值)`（这个显示口径本来就
    已经五引擎对拍过），再按位四舍五入。结果只取决于十进制写法，与宿主无关。
    """
    s = jishi_repr(v, top=True)
    if "e" in s or "E" in s:          # 科学计数法少见，原样给（见文档的已知边界）
        return s
    负 = s.startswith("-")
    纯 = s[1:] if 负 else s
    if "." in 纯:
        整数部, 小数部 = 纯.split(".")
    else:
        整数部, 小数部 = 纯, ""
    整数部 = 整数部 or "0"
    小数部 = 小数部 + "0" * 位
    保留, 丢弃 = 小数部[:位], 小数部[位:]
    结果 = 整数部 + (("." + 保留) if 位 > 0 else "")
    if 丢弃 and 丢弃[0] >= "5":
        结果 = _进一(结果)
    return ("-" if 负 else "") + 结果


def _进一(s: str) -> str:
    """十进制字符串加一（带小数点）：`9.9` → `10.0`。"""
    位们 = list(s)
    走 = len(位们) - 1
    while 走 >= 0:
        if 位们[走] == ".":
            走 -= 1
            continue
        if 位们[走] == "9":
            位们[走] = "0"
            走 -= 1
            continue
        位们[走] = str(int(位们[走]) + 1)
        return "".join(位们)
    return "1" + "".join(位们)
