# -*- coding: utf-8 -*-
"""`包`（M237 / L-8）：**运行期**按需加载一个已安装的本地包。

## 为什么只做「包加载」，不做「任意 eval」

L-8 原来写的是「运行期加载包 + 任意求值」两半。**任意 eval 明确不做**（D138）：

- 语言卡与产物必须对得上（`jishi.lock` 是**编译期展开**的产物）；
- 任意源码求值会让「卡里写的」和「真跑的」脱钩 —— 与「便于模型调用」直接冲突；
- 想要动态行为，正确的做法是**把逻辑放进一个包**，运行时 `包.加载` 它。
  包仍是「一份 `.jsh` 按语言规则跑一遍顶层」，卡上说得清。

## 用法

```python
导入 包

令 插件 = 包.加载("我的插件")     # → {函数名: 函数值, …}（包门面，**字典**）
打印(插件["处理"](数据))           # 与 `导入 我的插件 从 本地包` 后的 `我的插件.处理(数据)` 同义
```

- 返回的是**门面字典**（不是模块对象）：`插件["处理"]`。理由：运行期加载的名字
  是**变量**，用下标才和「拿一个字典」这件事对得上；而 `导入` 那条路拿的是模块，
  用 `.` 访问 —— 两者语义一致（同一套导出规则），只是形状跟着来源走。
- **不卸载**（加载即常驻）；**同名重复加载**返回同一份门面（缓存）。
- 包内顶层名字**不会污染**主程序：外壳函数跑完就退，只有导出的名字进字典
  （与 `导入` 展开成函数调用同一套隔离规则）。

## 两条明确的边界（写清楚，不静默）

| 情况 | 行为 |
|---|---|
| 包在 `包.json` 里声明了 `依赖` | 报错，指向编译期的 `导入 … 从 本地包`（那条路支持依赖链） |
| 包体里又写了 `导入 X 从 本地包` | 同上 |
| 沙箱（`--sandbox`） | `导入 包` 就被拒（不在白名单里）—— 沙箱本来就不允许动态导入 |
| wasm 页面 | 报错：页面里没有文件系统，读不到包 |

## 实现要点：为什么必须「编进调用者的执行器」

包的导出是**函数**，而函数绑定在创建它的执行器上（`Code` 里的常量/名字下标
都是相对本模块的）。所以 `包.加载` 必须把包编进**调用者自己的**表里 ——
换一个执行器代劳就会「拿到错误的常量表」（M145 踩过，`localpkg.rs` 文件头记着）。
`runtime._执行器栈` 就是为这件事存在的。
"""

from ..errors import RunTypeError, RunValueError

__all__ = ["加载"]


def _走C(执行器, 名, 结果名):
    """C VM 分支：`CvmRunner.加载本地包` 已含缓存外的全部逻辑。

    缓存由调用方（`加载`）负责 —— 这里只负责「把包追加进这个 C VM 并跑」。
    """
    return 执行器.加载本地包(名, 结果名)


def 加载(名字):
    """`包.加载(名字)` → 门面字典 `{导出名: 值, …}`。名字是**字符串**（可以来自变量）。"""
    from .. import localpkg as LP
    from .. import runtime as R

    if not isinstance(名字, str):
        raise RunTypeError(
            f"「包.加载」要一个**包名字符串**（如 \"我的插件\"），现在给了"
            f"「{type(名字).__name__}」",
            hint="包名不带引号会被当成变量先求值 —— 从配置里读出来的名字正好可以直接用")
    名 = 名字.strip()
    if not 名:
        raise RunValueError("「包.加载」的包名不能是空串",
                            hint="写要加载的包目录名，如 `包.加载(\"我的插件\")`")

    执行器 = R.当前执行器()
    if 执行器 is None:
        raise RunValueError(
            "「包.加载」只能在**跑程序时**调用（它要把包编进当前执行器）",
            hint="这是运行期能力；不要在宿主侧直接调它（那时没有「当前执行器」）")

    # 缓存：同名重复加载给同一份门面（与 `导入` 一致：加载即常驻）
    缓存 = getattr(执行器, "_包缓存", None)
    if 缓存 is None:
        缓存 = {}
        try:
            执行器._包缓存 = 缓存
        except AttributeError:          # 某些执行器用 __slots__
            pass
    if 名 in 缓存:
        return 缓存[名]

    脚本目录 = LP._脚本目录(getattr(执行器, "filename", None) or "<输入>")
    壳源码, 结果名 = LP.运行期外壳源码(名, 脚本目录,
                                    getattr(执行器, "filename", None) or "<输入>")
    假名 = f"<包:{名}>"

    # ---- 跑：按当前执行器的类型分派（这就是 M237 的全部难点所在）----
    from ..interpreter import Interpreter

    if isinstance(执行器, Interpreter):
        # 树遍历：`跑源码` 用的是同一个 `self.globals`，同一条 Python 调用栈
        执行器.跑源码(壳源码, 假名)
        门面 = 执行器.globals.vars.get(结果名)
    else:
        from ..compiler import compile_source
        from ..vm import VM
        from ..cvm_bind import CvmRunner

        if isinstance(执行器, CvmRunner):
            # C 字节码 VM：摊平 → `jsvm_append_module` → `jsvm_run_code`。
            # 它内部自己生成外壳源码（同一套 `运行期外壳源码`），所以这里不传源码。
            # ⚠️ 别在这里 `return` 就算完 —— 缓存也要写，否则同名重复加载会**再追加一份**
            #（C 侧 codes_base 是累计的，第二份不会覆盖第一份，但白费且门面会指向新的那份）。
            门面 = _走C(执行器, 名, 结果名)
        elif not isinstance(执行器, VM):
            raise RunValueError(
                f"「包.加载」不认识这个执行器（{type(执行器).__name__}）",
                hint="这是内部错误：执行器栈里应该是 Interpreter / VM / CvmRunner")
        else:
            cmod = compile_source(壳源码, 假名)
            执行器.跑子模块(cmod)
            门面 = 执行器.globals.get(结果名)

    if 门面 is None:
        raise RunValueError(
            f"包「{名}」加载完了，但没拿到门面 —— 这是内部错误",
            hint="请把这段程序和 `jishi --version` 一起报上来")
    缓存[名] = 门面
    return 门面
