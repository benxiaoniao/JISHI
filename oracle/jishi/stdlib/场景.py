# -*- coding: utf-8 -*-
"""基石标准库：场景（M187）—— 标题页 → 游戏中 → 结束页 的开关。

做**状态机**。M197 加了「转场」：`转场(效果, 帧数)` 起一段遮罩动画，
`转场中()` 每帧问一次 —— 期间自己决定画不画游戏。

语义（三宿主必须一致）：

- `定(名, {"初始化"?, "每帧"?})` 登记一个场景；
- `切(名)`：第一次切进某场景时**跑一次**它的 `初始化`；**已经在这个场景就什么都不做**
  （返回假）—— 否则在 `每帧` 里无条件 `切` 会反复跑初始化；
- `现在()` 返回当前场景名（还没切过 = 空文本）；
- M197：`转场(效果, 帧数)` / `转场中()` —— **按帧数，不按毫秒**（见 `转场` 的说明）。
"""

from ..errors import RunTypeError, RunValueError

__all__ = ["定", "切", "现在", "转场", "转场中"]

#: 场景表：名字 → {"初始化": 函数或 None, "每帧": 函数或 None}
_场景们 = {}
#: 当前场景（空 = 还没切过）
_现在 = ""


def 定(名, 选项):
    """M187：登记一个场景（`选项` 里 `初始化` / `每帧` 都是可选函数）。"""
    if not isinstance(选项, dict):
        raise RunTypeError(f"「场景.定」的选项要字典，给的是{type(选项).__name__}")
    for 键 in ("初始化", "每帧"):
        v = 选项.get(键)
        if v is not None and not callable(v):
            raise RunTypeError(f"「场景.定」的「{键}」要函数，给的是{type(v).__name__}")
    _场景们[str(名)] = {"初始化": 选项.get("初始化"), "每帧": 选项.get("每帧")}
    return True


def 切(名):
    """M187：切到某个场景（第一次进来会跑一次它的 `初始化`）。"""
    global _现在
    名 = str(名)
    if 名 not in _场景们:
        raise RunValueError(f"没有叫「{名}」的场景",
                            hint='先 `场景.定("名字", {"初始化": 某函数})` 再切')
    if _现在 == 名:
        return False
    _现在 = 名
    初 = _场景们[名]["初始化"]
    if 初 is not None:
        初()
    return True


def 现在():
    """M187：当前场景名（还没切过 = 空文本）。"""
    return _现在


# ---------------------------------------------------------------------------
# M197：转场
# ---------------------------------------------------------------------------

#: 当前转场：`{"效果": 名, "总": 帧数, "已": 已走帧数}`。空 = 没在转场。
_转场 = {"效果": "", "总": 0, "已": 0}

#: 认的三种效果。`擦除` 是从左往右盖。
_效果们 = ("淡出", "淡入", "擦除")


def 转场(效果, 帧数):
    """M197：起一段转场遮罩 —— `淡出` / `淡入` / `擦除`，**按帧数**。

    例::

        场景.转场("淡出", 20)      # 20 帧淡到黑
        # 每帧：
        如果 场景.转场中()：
            返回                    # 转场期间不画游戏
        游戏.画()

    ⚠️ **第 2 个参数是帧数，不是毫秒** —— 与路线图原计划不同，理由是：
    毫秒要靠**时钟**，而三宿主的时钟在 wasm 里不一致（wasm 没有系统时钟，
    得由页面每帧喂），「同一段代码在命令行和页面里转场快慢不同」是最难查的那类
    问题。帧数是确定的：60 帧就是 60 帧，谁跑都一样。
    （要按时间算，自己拿 `帧号` 和 `间隔` 换算。）

    📌 `转场中()` **每帧只能调一次**（它就是「走一帧」）。
    """
    global _转场
    名 = str(效果)
    if 名 not in _效果们:
        raise RunValueError(
            f"「场景.转场」不认识的效果「{名}」—— 只能是：{' / '.join(_效果们)}")
    if isinstance(帧数, bool) or not isinstance(帧数, (int, float)):
        raise RunTypeError(f"「场景.转场」的帧数要数字，给的是{type(帧数).__name__}")
    总 = int(帧数)
    if 总 <= 0:
        raise RunValueError(f"「场景.转场」的帧数要大于 0，现在是 {帧数}")
    _转场 = {"效果": 名, "总": 总, "已": 0}
    return True


def 转场中():
    """M197：还在转场吗？**每帧调一次**（调一次就走一帧）。走完自动给 `假`。

    第一次调用时它是 `真` 且走第 1 帧，所以 `转场(效果, 20)` 之后连调 20 次
    `转场中()` 会是 20 个 `真`，第 21 次开始 `假`。
    """
    if _转场["已"] >= _转场["总"]:
        return False
    _转场["已"] += 1
    return True
