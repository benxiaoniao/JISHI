# -*- coding: utf-8 -*-
"""`外部`（M236 / L-7）：调用动态库里的函数 —— **主路径的逃生口**。

## 为什么 Python 侧全是「做不到」

FFI 是**平台与 ABI 交互**，而 Python 宿主在本项目里的定位是「参考实现 / 判据基准」
（M185 起的原则：Python 宿主**故意不做**硬件与系统底层那几层 —— 剪贴板、托盘、
文件关联、串口、文件监视都是这样）。

要在这儿真做，就得引入 `ctypes` 之外的**通用调用机制**（`ctypes` 其实能做，
但它把「类型表」也包办了，与 Rust 侧「类型必须显式给」的口径**对不上**）——
而两个宿主对同一个功能给出**看起来一样、其实不同**的语义，正是本项目一直在避免的。
更要紧的：`工具/判据` 只认 Rust 发行版那一侧（见 `tests/test_m236_ffi.py`）。

所以：**能力在 Rust 宿主上**（Windows `LoadLibraryW`+`GetProcAddress`、
Linux/macOS `dlopen`+`dlsym`，零第三方依赖）；Python 侧明确报错，不假装。

## 接口（与 Rust 侧一致）

```python
导入 外部

令 核 = 外部.加载("kernel32.dll")                 # 句柄
令 滴答 = 外部.调用(核, "GetTickCount64", [], [])  # 无参、返回整数
外部.释放(核)                                     # 幂等

令 块 = 外部.分配(64)                             # 一块原生内存
外部.写整数(块, 0, 123)                           # (块, 偏移, 值, 宽度=8)
打印(外部.读整数(块, 0))
外部.释放块(块)

# 带参数：类型表必须显式给（这是 `外部` 与「随便调」的分界）
外部.调用(核, "lstrlenW", ["文本"], ["你好"])      # 2（UTF-16 两个码元）
外部.调用(核, "lstrlenA", ["文本UTF8"], ["你好"])  # 6（UTF-8 六个字节）
```

类型名只有五种：`"整数"` / `"指针"` / `"文本"`（平台原生：Win32 UTF-16、POSIX UTF-8）/
`"文本UTF8"`（一律 UTF-8）/ `"空"`。**不支持浮点**（走 XMM 寄存器，不在这套里）。

⚠️ 详见 `docs/语言规格.md` 的「外部调用」一节与 `docs/设计决策.md` D137。
"""

from ..errors import RunValueError

__all__ = [
    "加载",
    "调用",
    "释放",
    "分配",
    "写整数",
    "读整数",
    "释放块",
]


def _做不到(名: str):
    raise RunValueError(
        f"这个宿主没有外部调用能力，「外部.{名}」用不了"
        "（Python 宿主故意不做 ABI 那一层，理由与「串口」「文件监视」相同）",
        hint="用 Rust 发行版跑：`jishi 程序.jsh`（发行包里的引擎）；"
             "参数与类型表见语言卡「外部」一节",
    )


def 加载(路径):
    """`外部.加载(路径)` → 句柄。**只有 Rust 宿主能做。**"""
    _做不到("加载")


def 调用(库, 名字, 参数类型们, 实参们, 返回类型="整数"):
    """`外部.调用(库, 名字, 类型表, 实参, 返回="整数")`。**只有 Rust 宿主能做。**"""
    _做不到("调用")


def 释放(库):
    """`外部.释放(库)` → 真/假（幂等）。**只有 Rust 宿主能做。**"""
    _做不到("释放")


def 分配(字节):
    """`外部.分配(字节)` → 内存块。**只有 Rust 宿主能做。**"""
    _做不到("分配")


def 写整数(块, 偏移, 值, 宽度=8):
    """`外部.写整数(块, 偏移, 值, 宽度=8)`。**只有 Rust 宿主能做。**"""
    _做不到("写整数")


def 读整数(块, 偏移, 宽度=8):
    """`外部.读整数(块, 偏移, 宽度=8)` → 整数。**只有 Rust 宿主能做。**"""
    _做不到("读整数")


def 释放块(块):
    """`外部.释放块(块)` → 真/假（幂等）。**只有 Rust 宿主能做。**"""
    _做不到("释放块")
