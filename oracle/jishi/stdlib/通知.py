# -*- coding: utf-8 -*-
"""基石标准库：通知（M221）。

与 `窗口.提示` 的区别：**提示点了没回调，通知点了有回调**。

⚠️ **本宿主没有通知能力**（浏览器应用模式里没有系统通知），但口径与其他宿主
统一：`发` / `关闭` **返回假并往 stderr 说一句为什么**，不报错 ——
通知是锦上添花，没有它程序该照常跑完。`当` 则明确报错（订阅静默不生效
是最难查的那类问题）。

真实现见 `rust/src/native_window.rs` 的 `通知发` / `通知关`。
"""

import sys

from ..errors import RunValueError

__all__ = ["发", "关闭", "当"]

#: 与 Rust / Node 侧**同一句**（判据对拍 stderr）。
_没有能力 = "通知没发出去：这个宿主没有系统通知能力（用 Rust 发行版的原生窗口）"


def 发(标题, 正文) -> bool:
    """M221：弹一条系统通知。返回真 = 发出去了，假 = 这个宿主没能力（见 stderr）。"""
    print(_没有能力, file=sys.stderr)
    return False


def 关闭() -> bool:
    """M221：撤掉当前那条通知。"""
    return False


def 当(事件, 函数) -> bool:
    """M221：点了通知之后跑哪个函数。**只能写在页面里。**"""
    raise RunValueError(
        "「通知.当」只在**页面里**有效 —— 脚本这会儿正阻塞在 窗口.等 上，接不了事件",
        hint="把 通知.当 写进页面的基石代码里")
