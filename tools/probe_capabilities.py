#: 缺口项的**结论**（M36 加）——探针不只报「缺什么」，还要报「这事我们怎么定的」。
#: 没有这一栏，❌ 会一直挂着，读者分不清「还没轮到」与「已决定不做」，
#: 于是「用户以为有、其实没有」的陷阱就长出来了（路线图 §3.1 的由来）。
VERDICT: dict[str, str] = {
    "位运算 & | ^": "不做语法：改用 位与()/位或()/位异或()/位取反()（M36 已提供）",
    "位移 << >>": "不做语法：改用 左移()/右移()（M36 已提供）",
    "元组字面量 (…)": "不做：列表已能当字典键、不可变性需求弱；真做要动 C 的 JVal 布局",
    "字典合并 |": "不做语法：改用 字典.合并(别的)（M36 已提供）",
    "多继承": "不做：要 C3 线性化 + 重做 超()，单继承 + 组合够用",
    "全局声明": "不做：需求弱，闭包与参数传递已能表达",
    "删除变量": "不做：需求弱，用函数边界表达更清楚",
    "生成器 产出": "搁置：脱糖走不通（要状态机/协程），真实项目未用到惰性序列",
}
def probe(src: str, expected: "str | None" = None) -> tuple[bool, str]:
    """跑一段源码，返回 (是否可用, 说明)。

    ``expected`` 非空时，输出里必须包含它才算通过——避免「能跑但没做对」
    被算成已支持。
    """
    buf = io.StringIO()
    try:
        with redirect_stdout(buf):
            run_source(src, "<探针>")
    except JishiError as e:
        return False, f"{e.code} {e.title}"
    except Exception as e:                              # noqa: BLE001
        return False, f"{type(e).__name__}: {e}"
    out = buf.getvalue().strip().replace("\n", " | ")
    if expected is not None and expected not in out:
        return False, f"能跑但结果不对（期望含 {expected!r}，实际 {out[:34]!r}）"
    return True, out


def main() -> int:
    groups: dict[str, list] = {}
    for group, name, src in CASES:
        ok, detail = probe(src, EXPECTED.get(name))
        groups.setdefault(group, []).append((name, ok, detail))

    total = sum(len(v) for v in groups.values())
    ok_n = sum(1 for v in groups.values() for _, o, _ in v if o)
    missing = [name for items in groups.values() for name, o, _ in items if not o]
    judged = [n for n in missing if n in VERDICT]
    pending = [n for n in missing if n not in VERDICT]

    print(f"共探测 {total} 项：可用 {ok_n}，缺 {len(missing)}")
    print(f"  缺的里面：已判定 {len(judged)}（不做 / 有替代 / 搁置），待定 {len(pending)}")
    if pending:
        print(f"  ⚠️ 待定项（还没给结论，正是「用户以为有、其实没有」的温床）：{pending}")
    else:
        print("  ✅ 无悬案：每个缺口都有明确结论 —— 这是「语法面已收敛」的判据")
    print()

    for group, items in groups.items():
        print(f"=== {group} ===")
        for name, ok, detail in items:
            if ok:
                print(f"  ✅ {name:<18} {detail[:58]}")
            elif name in VERDICT:
                # 结论比原始报错重要，放前面；报错留后面当证据
                print(f"  ❌ {name:<18} [已判定] {VERDICT[name]}｜原报错：{detail[:30]}")
            else:
                print(f"  ❌ {name:<18} {detail[:58]}")
        print()
    return 0 if not pending else 1


if __name__ == "__main__":
    sys.exit(main())
